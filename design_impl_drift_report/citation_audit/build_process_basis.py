#!/usr/bin/env python3
"""各工程でやる作業と、その工数の根拠を1本にまとめる。

工程モデルは build_plan.py と同一（数字が食い違わないようにする）:
  1 基本設計書 = 編集見積 x (1+INV) + 冊数 x BOOK_MAKE
  2 実装修正   = (乖離見積 + Backlog見積) x (1+INV)
  3 UT         = 工程2 x UT
  4 レビュー   = (工程1+工程2) x RV + 冊数 x BOOK_REVIEW
  5 レビューバック = (工程1+工程2) x RB

各工程について「何をするか」「何件が対象か」「いくらか」「その数字はどこから来たか」
「実データの例」「弱いところ」を出す。
"""
import csv, os, re, statistics as st
from collections import Counter, defaultdict

csv.field_size_limit(10 ** 9)

BASE = os.path.dirname(os.path.abspath(__file__))
REPORT = os.path.dirname(BASE)
ROOT = os.path.dirname(REPORT)
DRIFT = os.path.join(REPORT, 'drift_findings_list_effort.tsv')
BL = os.path.join(REPORT, 'backlog_wip', 'backlog_wip_effort.tsv')
OV = os.path.join(REPORT, 'backlog_wip', 'overlap_map.tsv')
IT = os.path.join(ROOT, 'integration_test', 'it-target-functions.tsv')
MD = os.path.join(REPORT, 'PROCESS_WORK_AND_BASIS.md')

HOURS = 8.0
INV = 0.5                      # 工程2の該当箇所特定・影響範囲
UT, RV, RB = 0.30, 0.10, 0.20  # 工程3/4/5（工程2に対する比率）
BOOK_MAKE, BOOK_REVIEW = 0.50, 0.25

NAME = {'1': '外部インタフェース契約', '2': '画面表示', '3': 'データ永続化', '4': '入力検証',
        '5': '業務ロジック', '6': '未実装機能', '7': '外部連携・副作用', '8': '実行制御'}
EX = {'1': 'ルートを1本足す／レスポンス組み立ての1ファイルを直す',
      '2': 'messages.ja.yaml の翻訳値を1行直す／Twigの出力条件を移す',
      '3': 'マイグレーションを書き、Entity・Repository・バッチを直し、既存データを再集計する',
      '4': 'FormTypeに制約を1つ足す／CSV行検証に重複判定を足す',
      '5': 'Controller・Repositoryの条件分岐を直す（1〜2ファイル）',
      '6': 'ルート・Controller・Service・Twigを新設する（既存基盤は流用）',
      '7': 'スマレジ/メール/S3の呼び出し経路を追加または差し替える',
      '8': 'トランザクション境界を組み替える／set_time_limitを1行足す'}
WN = {'ADD': '記述が無い項目を書き足す', 'FIX': '実装と食い違う既存記述を直す',
      'IMAGE': '画面レイアウト画像を差し替える', 'RESOLVE': '正本内部の矛盾を解消する'}


def n(v):
    try:
        return float(v or 0)
    except ValueError:
        return 0.0


def flat(s, m=140):
    s = re.sub(r'[\s　]+', ' ', s or '').strip()
    return s[:m] + ('…' if len(s) > m else '')


def main():
    F = list(csv.DictReader(open(DRIFT, encoding='utf-8'), delimiter='\t'))
    B = list(csv.DictReader(open(BL, encoding='utf-8'), delimiter='\t'))
    O = list(csv.DictReader(open(OV, encoding='utf-8'), delimiter='\t'))
    ITF = list(csv.DictReader(open(IT, encoding='utf-8'), delimiter='\t'))

    live = [r for r in F if not r['トリアージ区分'].endswith('クローズ')]
    fix = [r for r in F if r['優先度'] in ('P1', 'P2', 'P3', 'P4') and r['仕様確定要'] != 'YES']
    doc = [r for r in F if r['設計書作業'] not in ('NONE', '', 'UNSURE')]
    bfix = [r for r in B if r['仕様確定要'] != 'YES']
    books = {m.group(1) for r in doc
             if (m := re.search(r'(\d{4}[^/\s,、]*?)\.html', r['設計書参照']))}

    d_edit = sum(n(r['設計書工数']) for r in doc)
    i_dr = sum(n(r['codex工数']) for r in fix)
    i_bl = sum(n(r['工数']) for r in bfix)

    s1 = d_edit * (1 + INV) + len(books) * BOOK_MAKE
    s2 = (i_dr + i_bl) * (1 + INV)
    s3 = s2 * UT
    s4 = (s2 + s1) * RV + len(books) * BOOK_REVIEW
    s5 = (s2 + s1) * RB
    TOT = s1 + s2 + s3 + s4 + s5

    # 見積不可
    nd_a = [r for r in F if r['優先度'] in ('P1', 'P2', 'P3', 'P4') and r['仕様確定要'] == 'YES']
    dj = [r for r in live if r['優先度'] == 'D']
    rr = [r for r in live if r['優先度'] == 'R']
    b_uns = [r for r in F if r['設計書作業'] == 'UNSURE']
    c_nd = [r for r in B if r['仕様確定要'] == 'YES']
    UNDEC = len(nd_a) + len(dj) + len(rr) + len(b_uns) + len(c_nd)

    touched = {r['機能No'] for r in fix} | {r['機能No'] for r in doc}
    itset = {r['id'].upper() for r in ITF}
    retest = touched & itset

    # 設計書シート数
    def sheetkey(v):
        m = re.search(r'(\d{4}[^/\s,、]*?\.html(?:#sheet-\d+)?)', v)
        return m.group(1) if m else v[:40]
    sheets = {sheetkey(r['設計書参照']) for r in doc}

    L, A = [], lambda x: L.append(x)
    A('# 各工程でやる作業と、工数の根拠\n')
    A('工程は **1 基本設計書 → 2 実装修正 → 3 ユニットテスト → 4 レビュー → 5 レビューバック対応**。')
    A('この順序と、結合テスト・シナリオテストを順守する前提は変えていない。')
    A(f'1人日 = {HOURS:.0f}時間。\n')
    A('この文書は「各工数がどの作業の時間で、その数字がどこから来たか」を工程ごとに書いたもの。'
      '**個別に見て積んだ数字と、係数で作った数字を分けて示す**。\n')

    # ---------------- 総括 ----------------
    A('## 0. 総括\n')
    A('| 工程 | 人日 | 割合 | 対象件数 | 根拠の等級 |')
    A('|---|---:|---:|---:|---|')
    A(f'| 1 基本設計書 | {s1:.0f} | {s1/TOT*100:.0f}% | {len(doc)}件 / {len(books)}冊 '
      f'| 個別見積＋仮置き係数 |')
    A(f'| 2 実装修正 | {s2:.0f} | {s2/TOT*100:.0f}% | {len(fix)+len(bfix)}件 | 個別見積＋仮置き係数 |')
    A(f'| 3 ユニットテスト | {s3:.0f} | {s3/TOT*100:.0f}% | 同上 | **係数のみ** |')
    A(f'| 4 レビュー | {s4:.0f} | {s4/TOT*100:.0f}% | 同上 | **係数のみ** |')
    A(f'| 5 レビューバック対応 | {s5:.0f} | {s5/TOT*100:.0f}% | 同上 | **係数のみ** |')
    A(f'| **開発5工程 小計** | **{TOT:.0f}** | | | |')
    A('')
    A(f'この小計には **入っていないもの** が3つある。')
    A('')
    A(f'1. **意思決定 {UNDEC}件**（何を作るか決まっていないもの）。開発工数ではないので別枠。第7節。')
    A('2. **結合テスト・シナリオテスト**。順守前提だが単価の実績がないため数字を作っていない。第8節。')
    A('3. **移行・環境・リリース・PR運用・並列化の統合コスト**。第9節に一覧。')
    A('')
    A(f'素の個別見積は 設計書 {d_edit:.1f} ＋ 実装 {i_dr+i_bl:.1f} = **{d_edit+i_dr+i_bl:.1f}人日**。'
      f'残る {TOT-(d_edit+i_dr+i_bl):.0f}人日 は「探索の上乗せ」「書籍固定費」「工程3-5の係数」で作った数字であり、'
      f'**総額の {(TOT-(d_edit+i_dr+i_bl))/TOT*100:.0f}% は仮置きの係数に依存している**。')

    # ---------------- 工程1 ----------------
    A('\n---\n')
    A('## 1. 基本設計書（{:.0f}人日）\n'.format(s1))
    A('### やる作業\n')
    A('| # | 作業 | 対象 |')
    A('|---|---|---|')
    A('| 1-1 | 指摘が指す **正本Excelのブック・シート・セル** を特定する | '
      f'{len(doc)}件（{len(sheets)}シート・{len(books)}冊） |')
    A('| 1-2 | 記述を書き足す／直す／レイアウト画像を差し替える／正本内部の矛盾を解消する | 同上 |')
    A('| 1-3 | 改版履歴・版数を更新する | 書籍単位 |')
    A('| 1-4 | `convert.py` でHTMLを再生成し、差分を確認する | 書籍単位 |')
    A('')
    A('**HTMLを直接編集しても意味がない**（再生成で消える）。正本はExcelなので、'
      'Excelを直してから再生成する。この再生成・差分確認・改版管理が書籍単位の固定費になる。')

    A('\n### 作業種別の内訳\n')
    A('| 種類 | 何をするか | 件数 | 編集工数(人日) |')
    A('|---|---|---:|---:|')
    bw = defaultdict(list)
    for r in doc:
        bw[r['設計書作業']].append(r)
    for k in ['ADD', 'FIX', 'IMAGE', 'RESOLVE']:
        g = bw.get(k, [])
        if g:
            A(f'| {k} | {WN[k]} | {len(g)} | {sum(n(r["設計書工数"]) for r in g):.1f} |')
    A(f'| **計** | | **{len(doc)}** | **{d_edit:.1f}** |')

    A('\n### 工数の作り方\n')
    A('```')
    A(f'工程1 = 編集見積 {d_edit:.1f} × (1 + 探索 {INV:.0%}) + {len(books)}冊 × {BOOK_MAKE}人日/冊')
    A(f'      = {d_edit*(1+INV):.1f} + {len(books)*BOOK_MAKE:.1f} = {s1:.1f}人日')
    A('```')
    A('')
    A('| 数字 | 値 | 根拠 |')
    A('|---|---:|---|')
    A(f'| 編集見積 | {d_edit:.1f}人日 | **codexが{len(doc)}件を1件ずつ判定**。'
      'どのブックのどのシートの何を直すかを書かせている（下に実例） |')
    A(f'| 探索の上乗せ | {INV:.0%} | **仮置き**。該当シートを探す時間。1冊やれば実測できる |')
    A(f'| 書籍固定費 | {BOOK_MAKE}人日/冊 | **仮置き**。再生成・差分確認・改版管理。'
      f'別に工程4で{BOOK_REVIEW}人日/冊の書籍レビューを積んでいる |')

    A('\n### 実データの例（codexが書いた根拠のまま）\n')
    A('| 種類 | 直す対象 | 人日 | 根拠 |')
    A('|---|---|---:|---|')
    for k in ['ADD', 'FIX', 'IMAGE', 'RESOLVE']:
        g = sorted(bw.get(k, []), key=lambda x: n(x['設計書工数']))
        if not g:
            continue
        for r in [g[len(g) // 2]]:
            A(f'| {k} | {flat(r["設計書対象"], 60)} | {n(r["設計書工数"]):.2f} '
              f'| {flat(r["設計書工数根拠"], 120)} |')

    A('\n### この工数の弱いところ\n')
    A(f'- **{len(doc)}件は「実装の見積が取れた行」とは一致しない。**'
      f'仕様確定待ち・設計判断待ちの行でも、記述漏れは書き足せるので工程1は発生する。')
    A(f'- **Backlog 255件については設計書の更新要否を判定していない**。'
      f'そのぶん工程1は下振れしている（第9節）。')
    A(f'- 書籍固定費 {BOOK_MAKE+BOOK_REVIEW}人日/冊 は実測ではない。1冊通してやれば決まる。')

    # ---------------- 工程2 ----------------
    A('\n---\n')
    A('## 2. 実装修正（{:.0f}人日）\n'.format(s2))
    A('### やる作業\n')
    A('| # | 作業 | 備考 |')
    A('|---|---|---|')
    A('| 2-1 | 指摘に対応する**実装箇所を特定する** | Controller/Service/Repository/Form/Twig/locale のどれか |')
    A('| 2-2 | **影響範囲を確認する** | 同じメソッド・同じ翻訳キーを使う他画面への波及 |')
    A('| 2-3 | コードを直す | 下表の「具体的に何をするか」 |')
    A('| 2-4 | 手元で動作を確認する | |')
    A('')
    A(f'2-1と2-2ぶんとして、codexの見積に **{INV:.0%}を上乗せ** している。'
      'codexの見積は「どこを直すか分かっている前提」の値なので、探す時間が入っていない。')

    A('\n### 改修区分別（乖離1,034件のうち見積が取れた{}件）\n'.format(len(fix)))
    A('| 区分 | 件数 | 見積(人日) | 上乗せ後 | 1件中央値 | 具体的に何をするか |')
    A('|---|---:|---:|---:|---:|---|')
    by = defaultdict(list)
    for r in fix:
        by[r['確定改修区分']].append(r)
    for k in sorted(NAME):
        g = by.get(k, [])
        if not g:
            continue
        e = sum(n(r['codex工数']) for r in g)
        m = st.median([n(r['codex工数']) for r in g]) * (1 + INV)
        A(f'| ({k}) {NAME[k]} | {len(g)} | {e:.1f} | {e*(1+INV):.1f} | {m*HOURS:.1f}h | {EX[k]} |')
    A(f'| **計** | **{len(fix)}** | **{i_dr:.1f}** | **{i_dr*(1+INV):.1f}** | | |')

    A('\n### Backlog「不具合（バグ）」対応中（見積が取れた{}件）\n'.format(len(bfix)))
    A('| 区分 | 件数 | 見積(人日) | 上乗せ後 |')
    A('|---|---:|---:|---:|')
    cb = defaultdict(list)
    for r in bfix:
        cb[r['改修区分']].append(r)
    for k in sorted(NAME):
        g = cb.get(k, [])
        if not g:
            continue
        e = sum(n(r['工数']) for r in g)
        A(f'| ({k}) {NAME[k]} | {len(g)} | {e:.1f} | {e*(1+INV):.1f} |')
    A(f'| **計** | **{len(bfix)}** | **{i_bl:.1f}** | **{i_bl*(1+INV):.1f}** |')
    A('')
    A('Backlogのチケットは**既に起票・再現済み**なので、2-1の特定作業は本来もっと軽い。'
      f'ここでは乖離側と同じ{INV:.0%}を当てており、**保守側に振れている**。')

    A('\n### 工数の作り方\n')
    A('```')
    A(f'工程2 = (乖離 {i_dr:.1f} + Backlog {i_bl:.1f}) × (1 + 特定・影響範囲 {INV:.0%}) = {s2:.1f}人日')
    A('```')
    A('')
    A('| 数字 | 値 | 根拠 |')
    A('|---|---:|---|')
    A(f'| 乖離側 | {i_dr:.1f}人日 | **codexが{len(fix)}件を1件ずつ、実コードを見て見積**。'
      '触るファイルと範囲を根拠欄に書かせている |')
    A(f'| Backlog側 | {i_bl:.1f}人日 | **codexが{len(bfix)}件を1件ずつ見積**。'
      'チケット本文＋実コード |')
    A(f'| 上乗せ | {INV:.0%} | **仮置き**。特定と影響範囲確認ぶん |')

    A('\n### 実データの例（各区分の中央値の行）\n')
    A('| 区分 | 機能 | 人日 | 直す対象 | 根拠 |')
    A('|---|---|---:|---|---|')
    for k in sorted(NAME):
        g = sorted(by.get(k, []), key=lambda x: n(x['codex工数']))
        if not g:
            continue
        r = g[len(g) // 2]
        A(f'| ({k}) | {r["機能No"]} | {n(r["codex工数"]):.2f} | {flat(r["直す対象"], 60)} '
          f'| {flat(r["工数根拠"], 110)} |')

    A('\n### この工数の弱いところ\n')
    A(f'- **区分(3)データ永続化と(6)未実装機能が単価を押し上げている**（中央値 '
      f'{st.median([n(r["codex工数"]) for r in by["3"]])*HOURS*(1+INV):.0f}h / '
      f'{st.median([n(r["codex工数"]) for r in by["6"]])*HOURS*(1+INV):.0f}h）。'
      'ここは既存データの再集計やマイグレーションを伴うので、実際にはさらに振れる。')
    A(f'- 乖離とBacklogは**重複する**。機械突合では確度A 8件・確度B 74件が一致候補で、'
      '人が確認するまで確定できない。単純合算は上振れしている。')
    A(f'- 上乗せ{INV:.0%}は全区分一律。1行直すだけの画面表示と、'
      '複数層を追うデータ永続化で同じ率にしているのは粗い。')

    # ---------------- 工程3 ----------------
    A('\n---\n')
    A('## 3. ユニットテスト（{:.0f}人日）\n'.format(s3))
    A('### やる作業\n')
    A('- 直したコードに対するテストを書く')
    A('- 既存テストが落ちるものを直す（fixture・期待値の更新を含む）')
    A('- 実行して通す')
    A('')
    A('### 工数の作り方\n')
    A('```')
    A(f'工程3 = 工程2 {s2:.0f} × {UT:.0%} = {s3:.0f}人日')
    A('```')
    A('')
    A(f'**この{UT:.0%}に根拠はない。実測ゼロの係数である。**')
    A('')
    A('区分によって実際の比率は大きく違うはずで、そこを均している。')
    A('')
    A('| 区分の例 | UT比率は本来どうなるか |')
    A('|---|---|')
    A('| (2) 画面表示（翻訳値1行） | ほぼ0。テストを書く対象がない |')
    A('| (4) 入力検証 | 高い。制約1つに対して正常系・異常系のケースが増える |')
    A('| (3) データ永続化 | 高い。マイグレーションと再集計の検証が要る |')
    A('| (6) 未実装機能 | 高い。新規なので既存テストが無い |')
    A('')
    A(f'**画面表示{len(by["2"])}件にも一律{UT:.0%}を掛けているため、その分は上振れしている。'
      f'逆に(3)(6)は下振れしている可能性がある。**')

    # ---------------- 工程4 ----------------
    A('\n---\n')
    A('## 4. レビュー（{:.0f}人日）\n'.format(s4))
    A('### やる作業\n')
    A('- PRを出す（説明・関連指摘IDの記載を含む）')
    A('- レビュアーが読み、指摘する')
    A('- **設計書の変更もレビューする**（工程1のぶん）')
    A('- 書籍単位の設計レビュー（1冊まとまった時点で通しで見る）')
    A('')
    A('### 工数の作り方\n')
    A('```')
    A(f'工程4 = (工程2 {s2:.0f} + 工程1 {s1:.0f}) × {RV:.0%} + {len(books)}冊 × {BOOK_REVIEW}人日/冊')
    A(f'      = {(s2+s1)*RV:.0f} + {len(books)*BOOK_REVIEW:.0f} = {s4:.0f}人日')
    A('```')
    A('')
    A(f'**{RV:.0%}は実測ゼロの係数。**設計書にもレビューが発生するので、'
      '工程1を分母に含めている（含めないと設計レビューがゼロになってしまう）。')
    A('')
    A('レビュー工数はPRの粒度で変わる。小さいPRを大量に出せば1件あたりは軽いが本数が増え、'
      '大きいPRにまとめれば本数は減るが1件が重くなる。'
      '**この係数はPR粒度を決めないまま置いた数字**なので、粒度方針を決めた時点で見直しが要る。')

    # ---------------- 工程5 ----------------
    A('\n---\n')
    A('## 5. レビューバック対応（{:.0f}人日）\n'.format(s5))
    A('### やる作業\n')
    A('- 指摘を直す')
    A('- 再度テストを通す')
    A('- 再レビューに出す（往復ぶん）')
    A('')
    A('### 工数の作り方\n')
    A('```')
    A(f'工程5 = (工程2 {s2:.0f} + 工程1 {s1:.0f}) × {RB:.0%} = {s5:.0f}人日')
    A('```')
    A('')
    A(f'**{RB:.0%}は実測ゼロの係数。**レビュー時間（工程4）の2倍を置いている。'
      '「見る時間より直す時間のほうが長い」という一般則であって、このプロジェクトの実績ではない。')
    A('')
