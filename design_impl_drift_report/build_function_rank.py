def parse_trace():
    """02_トレーサビリティ.md から S を算出する。

    S1/S2 は `紐づけ機能No`（経路証拠あり）にのみ与える。
    `期待機能No` にしか無いものは S0（期待のみ・紐づけ未確認）。
    """
    linked_kind = collections.defaultdict(set)
    expected = set()
    biz = collections.defaultdict(set)
    for line in TRACE.read_text(encoding='utf-8').splitlines():
        if not line.startswith('| ') or line.startswith('|---'):
            continue
        c = [x.strip() for x in line.strip().strip('|').split('|')]
        if len(c) < 9 or c[0] == '業務':
            continue
        b, kind = c[0], c[3]
        exp = [x.strip() for x in c[7].split(',') if x.strip() and x.strip() != '-']
        lnk = [x.strip() for x in c[8].split(',') if x.strip() and x.strip() != '-']
        expected.update(exp)
        for f in lnk:
            linked_kind[f].add(kind)
            biz[f].add(b)
    s = {}
    for f, kinds in linked_kind.items():
        s[f] = 'S1' if '正常代表' in kinds else 'S2'
    for f in expected - set(linked_kind):
        s[f] = 'S0'
    return s, biz


def build():
    s_map, biz = parse_trace()
    rows = []
    seen = collections.defaultdict(list)
    with MASTER.open(encoding='utf-8') as f:
        for r in csv.DictReader(f, delimiter='\t'):
            fid = r['id'].strip()
            mod = fid.split('-')[0]
            if fid in OV:
                rk, why = OV[fid]
            elif mod in MOD:
                rk, why = MOD[mod]
            else:
                raise AssertionError(f'未知のモジュール: {fid}')
            rows.append({'機能No': fid, '機能名': r['機能名'].strip(), 'モジュール': mod,
                         'ステータス': r['ステータス'].strip(), 'ランク': rk, '判定根拠': why})
            seen[fid].append(rk)
    for fid, nm, rk, why in EXTRA:
        rows.append({'機能No': fid, '機能名': nm, 'モジュール': fid.split('-')[0],
                     'ステータス': 'マスタ外(乖離指摘に出現)', 'ランク': rk, '判定根拠': why})
        seen[fid].append(rk)

    for r in rows:
        r['_S'] = s_map.get(r['機能No'], 'S3')
        r['出現業務'] = '/'.join(sorted(biz.get(r['機能No'], [])))

    # ---- 検証 ----
    assert all(r['ランク'] in ('C1', 'C2', 'C3') for r in rows), 'ランクの値が不正'
    assert all(r['判定根拠'] for r in rows), '判定根拠が空の行がある'
    assert all(re.fullmatch(r'[A-Z]\d{2}-\d{2}', r['機能No']) for r in rows), '機能Noの形式が不正'
    dup = {k: v for k, v in seen.items() if len(v) > 1}
    for k, v in dup.items():
        assert len(set(v)) == 1, f'重複機能No {k} でランクが割れている: {v}'
    unknown = {r['機能No'] for r in rows} - set(OV) - {f for f, *_ in [(e[0],) for e in EXTRA]}
    del unknown  # モジュール既定は許容

    # ---- TSV ----
    cols = ['機能No', '機能名', 'モジュール', 'ステータス', 'ランク', '判定根拠', '出現業務']
    with (REPORT / 'FUNCTION_RANK.tsv').open('w', encoding='utf-8', newline='') as f:
        w = csv.DictWriter(f, fieldnames=cols, delimiter='\t',
                           lineterminator='\n', extrasaction='ignore')
        w.writeheader()
        w.writerows(rows)

    # ---- Markdown ----
    cnt = collections.Counter(r['ランク'] for r in rows)
    md = ['# 機能ランク一覧（C1コア／C2準コア／C3周辺）\n',
          '`PRIORITY_BUSINESS_CRITERIA.md` §4 の軸2。機能マスタ '
          '`integration_test/it-target-functions.tsv` 全件＋補遺を機能単位で分類したもの。\n',
          '正本は `FUNCTION_RANK.tsv`。本ファイルは閲覧用。生成: `python3 '
          'design_impl_drift_report/build_function_rank.py`\n',
          '| ランク | 件数 |', '|---|---:|']
    for k in ('C1', 'C2', 'C3'):
        md.append(f'| {k} | {cnt[k]} |')
    md += [f'| **計** | **{len(rows)}** |', '']
    bymod = collections.defaultdict(list)
    for r in rows:
        bymod[r['モジュール']].append(r)
    for m in sorted(bymod):
        md += [f'## {m}\n', '| 機能No | 機能名 | ランク | 判定根拠 |', '|---|---|---|---|']
        for r in bymod[m]:
            md.append(f"| {r['機能No']} | {r['機能名']} | **{r['ランク']}** | {r['判定根拠']} |")
        md.append('')
    (REPORT / 'FUNCTION_RANK.md').write_text('\n'.join(md), encoding='utf-8')

    print('総件数', len(rows), '／ユニーク機能No', len(seen))
    print('ランク分布', dict(cnt))
    print('S分布', dict(collections.Counter(r['_S'] for r in rows)))
    if dup:
        print('重複機能No（機能マスタ側の欠陥。ランクは一致を検証済み）:', dict(dup))
    c = collections.defaultdict(collections.Counter)
    for r in rows:
        c[r['モジュール']][r['ランク']] += 1
    for m in sorted(c):
        print(' ', m, dict(c[m]))


if __name__ == '__main__':
    build()
