def main() -> int:
    issues = {int(i["issueKey"].rsplit("-", 1)[1]): i for i in json.load(ISSUES.open(encoding="utf-8"))}
    rows = list(csv.DictReader(DRIFT.open(encoding="utf-8"), delimiter="\t"))
    idx = {i + 2: r for i, r in enumerate(rows)}
    cand = {}
    for r in csv.DictReader(CAND.open(encoding="utf-8"), delimiter="\t"):
        if r["候補順位"] == "1":
            cand[int(r["課題キー"].rsplit("-", 1)[1])] = r

    bad = [k for k in VERDICTS if k not in issues]
    if bad:
        print(f"対象277件に無い課題キー: {bad}", file=sys.stderr)
        return 1
    bad = [(k, v[0]) for k, v in VERDICTS.items() if v[0] not in idx]
    if bad:
        print(f"乖離リストに無い行番号: {bad}", file=sys.stderr)
        return 1

    out = []
    for key in sorted(VERDICTS):
        ln, verdict, note = VERDICTS[key]
        it, d = issues[key], idx[ln]
        c = cand.get(key, {})
        out.append({
            "判定": verdict,
            "課題キー": it["issueKey"],
            "状態": it["status"]["name"],
            "件名": it["summary"].replace("\t", " ").replace("\n", " "),
            "重複と判断した理由": note,
            "drift行番号": ln,
            "乖離機能No": d["機能No"],
            "乖離機能名": d["機能名"],
            "乖離優先度": d["優先度"],
            "乖離トリアージ区分": d["トリアージ区分"],
            "乖離codex工数": d["codex工数"],
            "乖離設計期待値": d["設計期待値"].replace("\t", " ").replace("\n", " "),
            "乖離差分内容": d["差分内容"].replace("\t", " ").replace("\n", " "),
            "機械突合の1位一致": c.get("一致した手掛かり", ""),
            "機械突合の1位スコア": c.get("スコア", ""),
            "機械突合の1位が同じ行か": "Y" if c.get("drift行番号") == str(ln) else "",
        })

    OUT = BASE / "backlog_wip" / "backlog_drift_duplicates.tsv"
    with OUT.open("w", encoding="utf-8", newline="") as fh:
        w = csv.DictWriter(fh, fieldnames=list(out[0].keys()), delimiter="\t",
                           lineterminator="\n")
        w.writeheader()
        w.writerows(out)

    dup = [o for o in out if o["判定"] == "重複"]
    part = [o for o in out if o["判定"] == "部分重複"]
    by_row = defaultdict(list)
    for o in out:
        by_row[o["drift行番号"]].append(o["課題キー"])
    multi = {k: v for k, v in by_row.items() if len(v) > 1}
    st = Counter(o["状態"] for o in dup)

    lines = [
        "# Backlog課題と設計書乖離リストの重複",
        "",
        f"対象: Backlog カテゴリ「不具合（バグ）」／状態 未対応・処理中 **{len(issues)}件**"
        f"（未対応 {sum(1 for i in issues.values() if i['status']['name'] == '未対応')} / "
        f"処理中 {sum(1 for i in issues.values() if i['status']['name'] == '処理中')}）",
        f"照合先: `drift_findings_list_effort.tsv` {len(rows)}件",
        "",
        "機械突合（機能No・設計書・実装ファイル・本文類似度の4信号）で各課題の上位3候補を出し、",
        "**1位候補を277件すべて目視で確かめた**。同じ欠陥を指すものだけを重複としている。",
        "",
        "| 判定 | 件数 | 意味 |",
        "|---|---:|---|",
        f"| 重複 | {len(dup)} | 同じ欠陥。乖離側の改修で課題も消える → **クローズ検討の対象** |",
        f"| 部分重複 | {len(part)} | 論点は重なるが範囲がずれる → 残差の確認が要る |",
        f"| 対応する乖離指摘なし | {len(issues) - len(out)} | Backlog固有の指摘 |",
        f"| **計** | **{len(issues)}** | |",
        "",
        f"重複{len(dup)}件の状態内訳: "
        + " / ".join(f"{k} {v}件" for k, v in st.most_common()) + "。",
        "",
        f"明細: `backlog_wip/backlog_drift_duplicates.tsv`",
        f"候補と根拠（全277件×上位3候補）: `backlog_wip/backlog_drift_candidates.tsv`",
        "",
        "## クローズ検討の対象（重複）",
        "",
        "| 課題キー | 状態 | 件名 | 対応する乖離 | 機能No | 優先度 |",
        "|---|---|---|---:|---|---|",
    ]
    for o in dup:
        lines.append(f"| {o['課題キー']} | {o['状態']} | {o['件名'][:60]} | 行{o['drift行番号']} | "
                     f"{o['乖離機能No']} | {o['乖離優先度']} |")

    lines += ["", "## 部分重複（クローズ前に残差の確認が要る）", "",
              "| 課題キー | 件名 | 対応する乖離 | 判断が要る点 |", "|---|---|---:|---|"]
    for o in part:
        lines.append(f"| {o['課題キー']} | {o['件名'][:50]} | 行{o['drift行番号']} | "
                     f"{o['重複と判断した理由']} |")

    if multi:
        lines += ["", "## 同じ乖離行に複数の課題がぶら下がるもの", "",
                  "Backlog側どうしも重複している可能性がある。",
                  "", "| 乖離行 | 機能No | 課題キー |", "|---:|---|---|"]
        for ln, keys in sorted(multi.items()):
            lines.append(f"| {ln} | {idx[ln]['機能No']} | {', '.join(keys)} |")

    lines += [
        "", "## この突合の限界", "",
        "- 目視で確かめたのは**各課題の1位候補まで**。真の相手が2位・3位にいる課題は",
        "  取りこぼしている可能性がある（見落としの方向で、誤ってクローズ対象に挙げる方向ではない）。",
        "- 重複と判定しても、乖離側の改修範囲が課題の再現条件を完全に覆うかまでは",
        "  実機で確かめていない。クローズ前に課題本文の再現手順で確認すること。",
        "",
    ]
    (BASE / "BACKLOG_DRIFT_DUPLICATES.md").write_text("\n".join(lines) + "\n", encoding="utf-8")

    print(f"重複={len(dup)} 部分重複={len(part)} 対応なし={len(issues) - len(out)} "
          f"複数課題が同一行={len(multi)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
