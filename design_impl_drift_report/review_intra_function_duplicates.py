def num(v):
    try:
        return float(v)
    except (TypeError, ValueError):
        return None


def main() -> int:
    rows = list(csv.DictReader((BASE / "drift_findings_list_effort.tsv").open(encoding="utf-8"),
                               delimiter="\t"))
    idx = {i + 2: r for i, r in enumerate(rows)}
    pairs = list(csv.DictReader((BASE / "DUPLICATE_CANDIDATES.tsv").open(encoding="utf-8"),
                                delimiter="\t"))

    missing = [(p["行A"], p["行B"]) for p in pairs
               if (int(p["行A"]), int(p["行B"])) not in VERDICTS]
    if missing:
        print(f"判定漏れ {len(missing)}件: {missing[:5]}", file=sys.stderr)
        return 1

    out = []
    for p in pairs:
        key = (int(p["行A"]), int(p["行B"]))
        verdict, reason = VERDICTS[key]
        a, b = idx[key[0]], idx[key[1]]
        out.append({
            "判定": verdict,
            "理由": reason,
            "機能No": p["機能No"],
            "類似度": p["類似度"],
            "行A": key[0], "行B": key[1],
            "機能名A": a["機能名"], "機能名B": b["機能名"],
            "観点A": a["観点"], "観点B": b["観点"],
            "指摘区分A": a["指摘区分"], "指摘区分B": b["指摘区分"],
            "優先度A": a["優先度"], "優先度B": b["優先度"],
            "トリアージA": a["トリアージ区分"], "トリアージB": b["トリアージ区分"],
            "codex工数A": a["codex工数"], "codex工数B": b["codex工数"],
            "設計書関係": p["設計書関係"],
            "設計書参照A": p["設計書参照A"], "設計書参照B": p["設計書参照B"],
            "設計期待値A": a["設計期待値"].replace("\t", " ").replace("\n", " "),
            "設計期待値B": b["設計期待値"].replace("\t", " ").replace("\n", " "),
            "差分内容A": a["差分内容"].replace("\t", " ").replace("\n", " "),
            "差分内容B": b["差分内容"].replace("\t", " ").replace("\n", " "),
        })
    order = {"重複": 0, "部分重複": 1, "別指摘": 2}
    out.sort(key=lambda r: (order[r["判定"]], r["機能No"], r["行A"]))

    with (BASE / "duplicate_pairs_evidence.tsv").open("w", encoding="utf-8", newline="") as fh:
        w = csv.DictWriter(fh, fieldnames=list(out[0].keys()), delimiter="\t",
                           lineterminator="\n")
        w.writeheader()
        w.writerows(out)

    with (BASE / "drift_findings_duplicate_partial.tsv").open("w", encoding="utf-8",
                                                              newline="") as fh:
        part = [r for r in out if r["判定"] == "部分重複"]
        w = csv.DictWriter(fh, fieldnames=list(part[0].keys()), delimiter="\t",
                           lineterminator="\n")
        w.writeheader()
        w.writerows(part)

    # 「重複」だけを連結してクラスタ化する（部分重複は統合可否の判断が要るので混ぜない）
    parent = {}

    def find(x):
        parent.setdefault(x, x)
        while parent[x] != x:
            parent[x] = parent[parent[x]]
            x = parent[x]
        return x

    def union(x, y):
        rx, ry = find(x), find(y)
        if rx != ry:
            parent[rx] = ry

    for r in out:
        if r["判定"] == "重複":
            union(r["行A"], r["行B"])
    clusters = {}
    for k in list(parent):
        clusters.setdefault(find(k), []).append(k)
    clusters = {k: sorted(v) for k, v in clusters.items() if len(v) > 1}

    dup_rows = sum(len(v) for v in clusters.values())
    mergeable = dup_rows - len(clusters)  # 各クラスタ1件を残した場合に消える件数

    # 残す1件（代表）の決め方。手心が入らないよう順序を固定する。
    #   1) 優先度が最も強い  2) codex工数が最大  3) 記述量が最大  4) 行番号が小さい
    prio_rank = {"P1": 0, "P2": 1, "P3": 2, "P4": 3, "D": 4, "R": 5, "-": 6, "": 6}

    def keep_key(ln):
        r = idx[ln]
        body = len(r["設計期待値"]) + len(r["実装実態"]) + len(r["差分内容"])
        return (prio_rank.get(r["優先度"], 6), -(num(r["codex工数"]) or 0.0), -body, ln)

    reason_of = {}
    for r in out:
        if r["判定"] == "重複":
            reason_of.setdefault(r["行A"], r["理由"])
            reason_of.setdefault(r["行B"], r["理由"])

    excluded = []
    conflicts = []
    keep_of = {}
    for members in clusters.values():
        keep = sorted(members, key=keep_key)[0]
        keep_of[tuple(members)] = keep
        prios = {idx[m]["優先度"] for m in members}
        triages = {idx[m]["トリアージ区分"] for m in members}
        if len(prios) > 1 or len(triages) > 1:
            conflicts.append((members, sorted(prios), sorted(triages)))
        cid = f"{idx[keep]['機能No']}-{keep}"
        for m in members:
            if m == keep:
                continue
            row = dict(idx[m])
            row.pop("_row", None)
            row["除外理由"] = "同一機能内の重複指摘（同じ欠陥の二重起票）"
            row["重複クラスタID"] = cid
            row["統合先drift行番号"] = keep
            row["統合先の設計書参照"] = idx[keep]["設計書参照"]
            row["重複と判定した根拠"] = reason_of.get(m, "")
            row["クラスタ内の全drift行番号"] = ",".join(str(x) for x in members)
            row["優先度の食い違い"] = ("あり: " + "/".join(sorted(prios))) if len(prios) > 1 else ""
            row["drift行番号"] = m
            excluded.append(row)
    excluded.sort(key=lambda r: (r["機能No"], int(r["統合先drift行番号"]), int(r["drift行番号"])))

    ex_fields = [c for c in rows[0].keys() if c != "_row"] + [
        "除外理由", "重複クラスタID", "統合先drift行番号", "統合先の設計書参照",
        "重複と判定した根拠", "クラスタ内の全drift行番号", "優先度の食い違い", "drift行番号",
    ]
    with (BASE / "drift_findings_excluded_duplicate.tsv").open("w", encoding="utf-8",
                                                               newline="") as fh:
        w = csv.DictWriter(fh, fieldnames=ex_fields, delimiter="\t", lineterminator="\n",
                           extrasaction="ignore")
        w.writeheader()
        for r in excluded:
            w.writerow({k: (v.replace("\t", " ").replace("\n", " ") if isinstance(v, str) else v)
                        for k, v in r.items()})

    # 工数の二重計上分（代表を残し、除外行の工数を重複計上とみなす）
    dup_hours = 0.0
    hours_known = True
    for r in excluded:
        v = num(r["codex工数"])
        if v is None:
            hours_known = False
        else:
            dup_hours += v

    counts = {}
    for r in out:
        counts[r["判定"]] = counts.get(r["判定"], 0) + 1

    lines = [
        "# 同一機能内の重複指摘 判定結果",
        "",
        f"対象: `drift_findings_list_effort.tsv` {len(rows)}件 / {len({r['機能No'] for r in rows})}機能",
        "",
        f"`check_intra_function_duplicates.py` が挙げた候補{len(out)}ペアを1件ずつ読み、",
        "設計期待値・差分内容・実装参照・設計書参照を突き合わせて判定した。",
        "",
        "| 判定 | ペア数 | 意味 |",
        "|---|---:|---|",
        f"| 重複 | {counts.get('重複', 0)} | 同じ欠陥の二重起票。片方を残せばもう片方は消える |",
        f"| 部分重複 | {counts.get('部分重複', 0)} | 片方が他方を包含／同一原因だが対象が複数 |",
        f"| 別指摘 | {counts.get('別指摘', 0)} | 文面が似ているだけで対象項目・対象画面が別 |",
        f"| **計** | **{len(out)}** | |",
        "",
        "## 除外リスト",
        "",
        f"- 「重複」でつながる行の集合（クラスタ）: **{len(clusters)}件** / 関与行 **{dup_rows}件**",
        f"- 各クラスタから代表1件を残し、残り **{mergeable}件** を除外"
        f"（{len(rows)}件 → **{len(rows) - mergeable}件**）",
        f"- 除外分の codex工数: **約{dup_hours:.2f}人日**"
        + ("（工数未記入の行があるため下限値）" if not hours_known else ""),
        "- 除外リスト: `drift_findings_excluded_duplicate.tsv`"
        "（`drift_findings_list_effort.tsv` の全列＋除外理由・統合先行番号）",
        "- 残りリストの組み立ては `build_remaining_list.py`（`EXCLUSION_SUMMARY.md`）。",
        "- 代表の決め方: 優先度が最も強い行 → codex工数が最大 → 記述量が最大 → 行番号が小さい、の順。",
        f"- 優先度またはトリアージ区分がクラスタ内で食い違うもの: **{len(conflicts)}件**"
        "（代表側の値を採る。`優先度の食い違い` 列で追える）",
        "- 「部分重複」20ペアは統合可否の判断が要るので除外していない"
        "（`drift_findings_duplicate_partial.tsv`）。",
        "",
        "## 重複の出どころ",
        "",
        "最大の要因は **1つの機能Noが複数の設計書シートを束ねている** こと。",
        "監査をシート単位で回したため、検索入力シートと検索結果シートの双方に書かれた",
        "同じ要求について、同じ実装欠陥が2件起票されている。",
        "",
    ]

    rel = {}
    for r in out:
        if r["判定"] == "重複":
            rel[r["設計書関係"] or "(参照なし)"] = rel.get(r["設計書関係"] or "(参照なし)", 0) + 1
    lines += ["| 設計書参照の関係 | 重複ペア数 |", "|---|---:|"]
    for k, v in sorted(rel.items(), key=lambda kv: -kv[1]):
        lines.append(f"| {k} | {v} |")
    lines.append("")

    lines += ["## 重複クラスタ一覧（残す行と除外する行）", "",
              "| 機能No | 残す行 | 除外する行 | 内容 |", "|---|---:|---|---|"]
    for members in sorted(clusters.values(), key=lambda m: idx[m[0]]["機能No"]):
        fno = idx[members[0]]["機能No"]
        keep = keep_of[tuple(members)]
        drop = ", ".join(str(m) for m in members if m != keep)
        head = idx[keep]["設計期待値"].replace("\n", " ")[:60]
        lines.append(f"| {fno} | {keep} | {drop} | {head} |")
    lines.append("")

    lines += ["## 部分重複（包含関係の整理が要る）", "",
              "| 機能No | 行A | 行B | 理由 |", "|---|---:|---:|---|"]
    for r in out:
        if r["判定"] == "部分重複":
            lines.append(f"| {r['機能No']} | {r['行A']} | {r['行B']} | {r['理由']} |")
    lines += ["", f"明細（別指摘を含む全{len(out)}ペア）: `duplicate_pairs_evidence.tsv`", ""]

    (BASE / "DUPLICATE_REPORT.md").write_text("\n".join(lines) + "\n", encoding="utf-8")

    print(f"重複={counts.get('重複',0)} 部分重複={counts.get('部分重複',0)} 別指摘={counts.get('別指摘',0)}")
    print(f"クラスタ={len(clusters)} 関与行={dup_rows} 除外={len(excluded)} "
          f"残={len(rows) - len(excluded)} 除外工数≈{dup_hours:.2f}人日 "
          f"優先度/トリアージ食い違い={len(conflicts)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
