    """items: [(suffix, 日本語説明の card 句, category switch text or None, lang)] """
    rows = []
    for suf, card, c, lang in items:
        code = f"{prefix}-{suf}"
        rows.append(csv_row(code, code, code, lang, 0))
    out = [csv_upload(rows)]
    codes = "・".join(f"「{prefix}-{s[0]}」" for s in items)
    for suf, card, c, lang in items:
        code = f"{prefix}-{suf}"
        e = f"「カード指定 >」ボタンを押し、カード検索ポップアップで{card}の行の決定ボタンを押す。続けて商品名(日)に「{code}」、商品名(英)に「{code}」を入れ（カード指定で自動で入った値は書き換える）、"
