def swap(old, a, b, new, include_b=True):
    i = old.index(a)
    j = old.index(b, i + len(a) if b != a else i + 1)
    j = j + len(b) if include_b else j
    return old[:i] + new + old[j:]


def read(fid):
    ls = [l.rstrip("\n").split("\t") for l in open(P / f"in/{fid}.tsv", encoding="utf-8")]
    return ls[0], ls[1:]


