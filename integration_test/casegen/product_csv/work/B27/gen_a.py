def gen_f1001():
    seeds = load("F10-01")
    out = []
    for s in seeds:
        sid = s["シードID"]
        if sid.startswith("S-F10-01-PRD"):
            m = re.search(r"商品ID=(\d+)／商品コード=(\S+?)／商品名=(\S+?)／本店公開・日本語・単価500・在庫あり", s["状態・属性"])
            pid, code, name = m.groups()
            new = upload([row(code, name, name, 500)])
            attr = s["状態・属性"].replace(f"商品ID={pid}／", "商品IDは取り込み後に画面が振る番号（ケースは商品コードで参照するため控えない）／")
            reason = ("元は商品管理＞商品登録で登録していたので、グッズ商品CSV登録で作った。元の属性の商品ID " + pid + " はCSVでは指定できず（商品IDは新規なら空）、"
                      "画面が振る番号になるので、状態・属性の商品IDを書き換えた（ケースは商品コード " + code + " で参照している）。"
                      "元の属性の「在庫あり」を作る操作は元の投入方法に無く、CSVの規格は在庫0で作られる（元のシードの誤り。直していない）。"
                      "商品名(英)・買取価格・原価単価は元に指定が無いので商品名(日)と同じ値・0にした。")
            out.append((sid, "直す", new, attr, BASE, reason))
        else:
            t = s["投入方法"]
            old = "管理画面の商品管理＞商品登録で上記の商品を登録し、"
            new_head = upload([row("F1001-028-A", "結合商品F1001-028", "結合商品F1001-028", 500)])
            t2 = sub(t, old, new_head)
            reason = ("元は商品管理＞商品登録で商品を登録していたので、グッズ商品CSV登録で作った（商品名(英)・買取価格・原価単価は元に指定が無いので商品名(日)と同じ値・0）。"
                      "受注登録の操作は変えていない。元の属性の「在庫あり」を作る操作は元の投入方法に無く、CSVの規格は在庫0で作られる（元のシードの誤り。直していない）。")
            out.append((sid, "直す", t2, "", BASE, reason))
    save("F10-01", out)


