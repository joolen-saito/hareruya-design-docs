def gen_m0404():
    seeds = load("M04-04")
    pat = re.compile(r"商品登録編集画面で商品名に「(?P<n>[^」]+)」を入れ、公開状態で「公開」を選び、そのほかの必須項目に入力チェックを通る任意の値を入れて登録ボタンを押す。"
                     r"登録後の商品登録編集画面に表示された商品IDを控える（(?P<pl>〔[^〕]+〕)）。"
                     r"その商品の商品規格一覧画面から商品規格登録編集画面を開き、商品コードに「(?P<code>[^」]+)」を入れ、言語で「日本語」、状態で「NM」を選び、"
                     r"基準価格に「(?P<b>\d+)」を入れ、セールフラグにチェックを入れて販売価格に「(?P<s>\d+)」を入れ、買取価格に「(?P<buy>\d+)」を入れ、"
                     r"部門で任意の部門を選び、公開ステータスで「公開」を選んで商品規格を登録ボタンを押す。")
    out = []
    for s in seeds:
        t = s["投入方法"]
        n_found = len(pat.findall(t))
        assert n_found >= 1, s["シードID"]

        def rep(m):
            n, code, b, sp, buy = m.group("n"), m.group("code"), m.group("b"), m.group("s"), m.group("buy")
            cost = "800" if "EXCLUDE" in code else "400"
            return (upload([row(code, n, code + " Product", int(b), buy=int(buy), cost=int(cost))])
                    + find_id(code, m.group("pl"))
                    + f"その商品の商品規格一覧画面（商品登録編集画面の「規格設定」ボタン）から、取り込みで作られた規格の行を開いて商品規格登録編集画面を開き、"
                      f"セールフラグにチェックを入れて販売価格に「{sp}」を入れ、部門で登録済みの部門を選び、公開ステータスで「公開」を選んで商品規格を登録ボタンを押す。")
        t2 = pat.sub(rep, t)
        reason = ("元は商品登録編集画面で商品を新規に作っていたので、グッズ商品CSV登録で作った（商品を登録せず、取り込みで作られたニアミントの規格を開いてセールフラグ・販売価格・部門・公開ステータスを入れる）。"
                  "元が「任意」としていた商品名(英)・サイズ・重量・部門は、商品名(英)は商品コードに「 Product」を足した値、サイズ1・重量1、登録済みの部門に決めた。"
                  "CSVの原価単価は、のちに承認する入庫の仕入単価（400。比較用は800）と同じ値にした。"
                  "新しい規格のうち、複数の規格を持つ商品（DP-DATA-005）は、2件目以降の規格を元のとおり商品規格一覧から新しく作る。")
        out.append((s["シードID"], "直す", t2, "", BASE + "、M03-09 L0086〜L0087・L0100・L0171、M03-08 L0059", reason))
    save("M04-04", out)


