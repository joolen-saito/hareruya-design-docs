from common import *
hdr, I = load('A02-03')
O = []
CARD = re.compile(r'^(?P<num>\d+\) )?(?P<pre>(?:候補[AB]として、|非公開の商品Aとして、|公開の商品Bとして、))?商品登録編集画面でカード指定を押し、カード検索ポップアップでカード名に「(?P<cn>[^」]+)」を入れて検索してカード詳細ID (?P<cid>\d+)の行を選び、商品名に「(?P<ja>[^」]+)」、商品名\(英\)に「(?P<en>[^」]+)」を入れ、商品公開ステータスに(?P<pub>公開|非公開|廃止)を選んで（ほかの必須項目は任意の値を入れる）商品を登録ボタンを押す$')
SPEC = re.compile(r'^(?P<num>\d+\) )?(?P<who>(?:候補[AB]の|[ABC]件目の商品規格として、その商品の|その商品の))商品登録編集画面で規格設定を押し、商品規格一覧から商品規格登録編集画面を開いて、商品コードに「(?P<code>[^」]+)」を入れ、言語に(?P<lang>日本語|英語)、状態にNMを選び、基準価格に(?P<base>\d+)、買取価格に(?P<buy>\d+)を入れ（セールフラグはオフのままにして、基準価格を販売価格にする）、部門に任意の1件、公開ステータスに公開を選んで商品規格を登録ボタンを押す$')
B = "M03-27 L0092・L0119・L0123・L0124・L0129・L0134、M03-02 L0075〜L0077・L0092・L0146（識別ID 35）、M03-09 L0130〜L0134"
for r in I:
    sid, old = r[0], r[5]
    s = old.split('。')
    why = []
    n_conv = 0
    used_spec = set()
    for i, x in enumerate(s):
        m = CARD.match(x)
        if m:
            # 後ろの最初の規格の文
            j = next(j for j in range(i + 1, len(s)) if SPEC.match(s[j]) and not re.match(r'^(\d+\) )?[BC]件目', s[j]))
            ms = SPEC.match(s[j]); used_spec.add(j)
            code, lang = ms['code'], ms['lang']
            pub = m['pub']
            csvpub = {'公開': 2, '非公開': 1, '廃止': 2}[pub]
            row = csv_row(code, m['ja'], m['en'], lang=lang, pub=csvpub, branch=1, base=int(ms['base']), buy=int(ms['buy']))
            t = (m['num'] or '') + (m['pre'] or '') + csv_upload([row]) + "。" + open_edit(code) + "、「カード指定 >」ボタンを押し、カード検索ポップアップでカード名に「" + m['cn'] + "」を入れて検索してカード詳細ID " + m['cid'] + "の行を選ぶ。続けて商品名(日)に「" + m['ja'] + "」、商品名(英)に「" + m['en'] + "」を入れ（カード指定で自動で入った値は書き換える）、"
            if pub == '廃止':
                t += "商品公開ステータスに廃止を選び、"
            t += DISC + "「商品を登録」ボタンを押す"
            s[i] = t
            why.append(f"{code}")
            tt = (ms['num'] or '') + ms['who'] + "商品登録編集画面で規格設定を押し、商品規格一覧で取り込みで作られた状態ニアミント・" + lang + "の規格の行を開き、商品規格登録編集画面で部門は選択肢の先頭を選び、公開ステータスに公開を選んで商品規格を登録ボタンを押す"
            s[j] = tt
            n_conv += 1
    if sid == 'S-A02-03-GOODS-015':
        m = re.match(r'^1\) 商品登録編集画面でカード指定を押さずに、商品名に「([^」]+)」、商品名\(英\)に「([^」]+)」を入れ、商品公開ステータスに公開を選んで（ほかの必須項目は任意の値を入れる）商品を登録ボタンを押す$', s[0])
        ms = re.match(r'^2\) その商品の商品登録編集画面で規格設定を押し、商品規格一覧から商品規格登録編集画面を開いて、商品コードに「([^」]+)」を入れ、言語に任意の1件、状態に任意の1件を選び、基準価格に(\d+)、買取価格に(\d+)を入れ', s[2])
        assert m and ms
        row = csv_row(ms[1], m[1], m[2], lang="日本語", pub=2, branch=1, base=int(ms[2]), buy=int(ms[3]))
        s[0] = "1) " + csv_upload([row])
        assert s[1].startswith('登録後の商品登録編集画面に表示された商品IDを控える')
        s[1] = "商品マスター(検索入力)で商品コードに「" + ms[1] + "」を入れて「検索する >」を押し、商品マスター(検索結果)の行の商品IDに表示された番号を控える（〔商品ID-A0203-015〕）"
        s[2] = "2) 商品マスター(検索結果)の行から商品登録編集画面（既存の商品の編集）を開き、規格設定を押し、商品規格一覧で取り込みで作られた状態ニアミント・日本語の規格の行を開き、商品規格登録編集画面で部門は選択肢の先頭を選び、公開ステータスに公開を選んで商品規格を登録ボタンを押す"
        n_conv = 1
        why = ["A0203GOODS-015（カード指定なし）"]
    # WEEKLY-012 の B/C 件目は新規作成
    for i, x in enumerate(s):
        if re.match(r'^\d+\) [BC]件目の商品規格として', x):
            s[i] = x.replace("商品規格一覧から商品規格登録編集画面を開いて", "商品規格一覧の「新規作成」から商品規格登録編集画面を開いて")
    assert n_conv >= 1, sid
    # 取り残し検査
    left = [x for x in s if re.search(r'商品登録編集画面でカード指定を押|商品規格一覧から商品規格登録編集画面を開いて', x)]
    assert not left, (sid, left[:1])
    reason = ("元の手順は商品登録編集画面でカード指定から商品を新規登録していた。グッズ商品CSVで商品と状態ニアミントの規格を作り、"
              "取り込んだ商品を商品登録編集画面（既存の商品の編集）でカード指定して商品名を入れ直す。規格の商品コード・言語・基準価格・買取価格・原価単価10・サイズ1・重量1は元の規格の値のとおりCSVに入れ（状態は元からNM）、"
              "部門は選択肢の先頭、規格の公開ステータスは元のとおり公開にする。支店の商品公開ステータスは1（ee の初期値は公開）とした。カテゴリは元のシードで任意だったのでサプライ・グッズのままにした。")
    if sid.endswith('ABOLISHED-023'):
        reason += "商品公開ステータス『廃止』は、新規のCSVでなく、取り込み後に商品登録編集画面で選ぶ（元の手順と同じ順序で、在庫を入れる前に廃止にする）。"
    if sid.endswith('WEEKLY-012'):
        reason += "A件目の規格だけCSVが作る。B件目・C件目は商品規格一覧の「新規作成」で足す（元のシードは同じ商品に言語JP/JP/ENの状態NMの規格を3件作る）。"
    if sid.endswith('FILTER-005'):
        reason += "気づいた誤り（直していない）: 手順13は規格が1件だけの商品005Bの規格を削除するが、最後の1件の規格は削除できない（M03-09 L0197・HTTP400）。ケースへの影響: 手順13の結果が元のシードの想定どおりにならない。"
    if sid.endswith('GOODS-015'):
        reason += "元の規格の『言語に任意の1件・状態に任意の1件』は、CSVに具体値が要るので日本語・ニアミントにした。"
    O.append([sid, "直す", joined(s), "", B, reason])
write('A02-03', O)
print(len(O))
