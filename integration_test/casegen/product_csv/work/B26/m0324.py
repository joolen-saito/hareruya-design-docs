from common import *
pat=re.compile(r"(?P<pre>(?:\d+件目: )?)商品登録画面で商品名\(日\)に「(?P<jp>[^」]+)」、商品名\(英\)に「(?P<en>[^」]+)」(?:、ショップ用メモ欄に「(?P<memo>[^」]+)」)?を入れ、商品カテゴリ・購入グループ・サイズ・重量・割引率・販売制限は任意の値を入れて「商品を登録」を押す。続けて「規格設定」から商品規格一覧画面を開いて「新規登録」を押し、商品規格登録画面で言語に「(?P<lang>[^」]+)」、状態に「(?P<state>[^」]+)」、商品コードに「(?P<code>[^」]+)」、(?P<sale>セールフラグにチェックを入れ、)?基準価格に「(?P<base>\d+)」、販売価格に「(?P<sp>\d+)」、買取価格に「(?P<buy>\d+)」を入れ、部門は任意の値を選び、公開ステータスを「公開」にして「商品規格を登録」を押す。登録後の商品規格登録画面に表示された商品IDと商品規格IDを控える（(?P<lab>[^）]+)）。商品登録画面へ戻り、商品公開ステータスを「公開」にして「商品を登録」を押す。")
LANG={"日本語":"日本語のID","英語":"英語のID"}
def rep(m):
    g=m.groupdict()
    code,state=g["code"],g["state"]
    lang=g["lang"]
    base,sp,buy=int(g["base"]),int(g["sp"]),int(g["buy"])
    sale=bool(g["sale"])
    csvcode=code if state=="NM" else code+"-CSV"
    cbase=base
    cbuy=min(buy,cbase) if not sale else min(buy,cbase)
    t=g["pre"]+csv_one(csvcode,g["jp"],g["en"],cbase,cbase,cbuy,lang=LANG[lang])
    if g["memo"]:
        t+=open_prod(csvcode)+f"ショップ用メモ欄に「{g['memo']}」を入れ、割引率に販売割引率に登録済みのものを選んで「商品を登録」ボタンを押す。"
        t+="続けて"
    else:
        t+=open_prod(csvcode)
    if state=="NM":
        extra=""
        if sale: extra=f"セールフラグにチェックを入れ、販売価格に{sp}、買取価格に{buy}を入れ、"
        t+=spec_fix(extra,lang=lang)
    else:
        t+=(f"「規格設定」ボタンから商品規格一覧を開き、「新規作成」を押し、商品規格登録編集画面で言語に{lang}、状態に{state}、商品コードに「{code}」、基準価格に{base}、販売価格に{sp}、買取価格に{buy}を入れ、部門は選択肢の先頭を選び、公開ステータスに「公開」を選んで「商品規格を登録」ボタンを押す。"
            f"登録後の商品規格登録編集画面に表示された商品IDと商品規格IDを控える（{g['lab']}）。"
            f"そのあと、取り込みで作られたニアミントの規格（商品コード「{csvcode}」）の行から商品規格登録編集画面を開き、「商品規格を削除」ボタンを押す。")
        return t
    t+=f"商品規格登録編集画面に表示された商品IDと商品規格IDを控える（{g['lab']}）。"
    return t
ix,rows=load("M03-24")
res=[]
for r in rows:
    old=r[ix["投入方法"]]
    new,n=pat.subn(rep,old)
    assert n>=1 and "商品登録画面" not in new, (r[0],n)
    new=new.replace("商品規格の登録時に自動で作られた価格履歴","取り込みと規格の編集で自動で作られた価格履歴")
    assert "規格の登録時" not in new, r[0]
    if "-CSV" in new:
        new=new.replace("取り込みと規格の編集で自動で作られた価格履歴は、削除する画面が無いためDBで削除する。","取り込みと規格の編集で自動で作られた価格履歴（削除した規格の履歴を含む）は、削除する画面が無いためDBで削除する。")
    sale="セールフラグ" in old
    why=("元のシードは商品登録画面で商品を作り、商品規格一覧の『新規登録』で規格を足していた。商品はグッズ商品CSV登録で作り、取り込みで作られたニアミントの規格を規格の画面で直す形にした（規格の言語はCSVの言語(ID)で決まる）。"
         "元のシードの最後の『商品公開ステータスを公開にして商品を登録』は、CSVの商品公開ステータスを2（公開）で取り込むので外した（ショップ用メモ欄を入れる商品は編集画面の『商品を登録』で入れる）。"
         "商品名(英)・サイズ・重量・原価単価・商品カテゴリ・購入グループはCSVの必須列の都合で入れた値（商品カテゴリはサプライ・グッズ、元のシードは任意）。"
         "価格履歴はこのシードがすべてDBで置き換えるので、取り込みや規格の編集で履歴ができても結果は変わらない。")
    if sale: why+="CSVの基準価格・販売価格・買取価格は買取価格が販売価格を上回れない（M03-27 L0119）ので基準価格と同額にし、元のシードの販売価格と買取価格は、取り込んだあと規格の画面でセールフラグを入れて入れ直す。"
    if "-CSV" in new: why+="状態がNM以外の規格が要るため、ニアミントの規格は取り込まれるが、状態SPの規格を足してからニアミントの規格を削除する。ニアミントの規格の商品コードは、SPの規格の商品コードと重ならないよう末尾に『-CSV』を付けた。ケースに影響: 規格の削除が許されない・削除した規格が履歴の検索に残る場合は崩れる（削除した規格の履歴は、価格履歴をDBで置き換える手順で除く）。"
    res.append([r[0],"直す",new,"",BASIS+"、M03-09 L0059〜L0062・L0086〜L0087・L0189、M03-02 L0075〜L0077",why])
write_out("M03-24",res)
print(len(res))
