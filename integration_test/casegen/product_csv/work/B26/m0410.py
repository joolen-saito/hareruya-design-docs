from common import *
pat=re.compile(r"商品登録で商品名に(?:任意の名称|「(?P<nm>[^」]+)」)を入れ、ほかの必須項目に任意の値を入れて登録ボタンを押す。続けてその商品の商品規格登録で商品コードに「(?P<code>[^」]+)」、基準価格\(円\)に(?:任意の値|「(?P<pr>\d+)」)を入れ、ほかの必須項目に任意の値を入れて登録ボタンを押す（開店中の全店舗に、在庫区分ごとの在庫が在庫数0で作られる）。")
def rep(m):
    code=m.group("code"); nm=m.group("nm") or f"{code}商品"; pr=m.group("pr") or "1000"
    return (csv_one(code,nm,nm,pr,pr,100)+open_prod(code)+spec_fix()
      +"取り込みは、公開中の店舗と在庫場所の組み合わせぶんだけ、在庫を数量0で作る（開店中の全店舗に、在庫区分ごとの在庫が在庫数0で作られる）。")
ix,rows=load("M04-10")
res=[]
for r in rows:
    old=r[ix["投入方法"]]
    new,n=pat.subn(rep,old)
    assert n>=1 and "商品登録で" not in new, r[0]
    anyname="任意の名称" in old
    anypr="任意の値" in old.split("商品規格登録で")[1][:80]
    why=("元のシードは商品登録と商品規格登録で商品を作っていた。商品はグッズ商品CSV登録で作り、取り込みで作られたニアミント・日本語の規格の部門と公開ステータスを規格の画面で直す形にした。"
         + ("元のシードで商品名が任意だったため、商品名は商品コードに『商品』を付けた値にした。" if anyname else "")
         + ("基準価格が任意だったため1000、買取価格は100とした（基準価格合計=1000の移動点数1と合う）。" if anypr else "買取価格は元のシードに指定が無いので100とした。")
         + "取り込みが在庫を作るのは公開中の店舗（M03-27 L0129）。元のシードの店舗登録は『開店』だけを指定していて公開の指定が無いので、店舗が公開になっていることを実行時に確かめる。")
    res.append([r[0],"直す",new,"",BASIS,why])
write_out("M04-10",res)
print(len(res))
