from common import *
pat=re.compile(r"商品登録画面の「カード指定」でカード「(?P<card>[^」]+)」のカード詳細を選び、商品名\(日\)に「(?P<jp>[^」]+)」、商品名\(英\)に「(?P<en>[^」]+)」を入れ、公開状態で「公開」を選び、そのほかの必須項目（購入グループ・サイズ・重量・割引率・販売制限・カテゴリ）は任意の値にして「商品を登録」を押す。続けてその商品の商品規格登録画面で言語に任意の言語、状態で状態コードNMの状態を選び、商品コードに「(?P<code>[^」]+)」を入れ、公開状態で「公開」を選び、そのほかの必須項目（販売種別・販売価格\(円\)・基準価格\(円\)・買取価格\(円\)・部門）は任意の値にして「商品規格を登録」を押す。商品規格登録画面に表示された商品IDと商品規格IDを控える（(?P<lab>[^）]+)）。")
def rep(m):
    code,jp,en,card,lab=m.group("code","jp","en","card","lab")
    return (csv_one(code,jp,en,1000,1000,100)+open_prod(code)
      +f"「カード指定 >」ボタンを押し、カード検索ポップアップのカード名(日/英)に「{card}」を入れて検索ボタンを押し、検索結果のその行の決定ボタンを押す。続けて商品名(日)に「{jp}」、商品名(英)に「{en}」を入れ（カード指定で自動で入った値は書き換える）、割引率に販売割引率に登録済みのものを選んで「商品を登録」ボタンを押す。"
      +spec_fix()+f"商品規格登録編集画面に表示された商品IDと商品規格IDを控える（{lab}）。")
ix,rows=load("M12-09")
res=[]
for r in rows:
    old=r[ix["投入方法"]]
    new,n=pat.subn(rep,old)
    assert n>=1 and "商品登録画面" not in new, r[0]
    why=("元のシードは商品登録画面で商品を作り、続けて商品規格登録画面で規格を足していた。商品はグッズ商品CSV登録で作り、取り込みで作られたニアミント・日本語の規格を直す形にした。"
         "元のシードの『言語は任意の言語』『販売種別・価格・部門は任意の値』は、CSVの必須列の都合で言語は日本語、基準価格・販売価格は1000、買取価格は100とし、部門は選択肢の先頭にした。"
         "元のシードの『カテゴリは任意の値』は、取り込みがサプライ・グッズ配下しか選べない（M03-27 L0123）ためサプライ・グッズのままにした。"
         "カード指定後の商品名は、カード指定で自動で入る値を元のシードの商品名に入れ直す。")
    res.append([r[0],"直す",new,"",BASIS+"、M03-02 L0092（カード指定 >）、M03-09 L0123・L0124",why])
write_out("M12-09",res)
print(len(res))
