out=[]
for c in rows:
    sid,_,_,_,_,meth=c[:6]
    ss=meth.split("。")
    new=[];i=0;changed=False
    while i<len(ss):
        s=ss[i]
        m=re.match(r"管理画面の商品登録編集画面で、商品名に「([^」]+)」を入れ、(?:商品カテゴリで「([^」]+)」を選び、)?商品公開ステータスで「公開」を選んで「商品を登録」ボタンを押す$",s)
        if m:
            name,cat=m.group(1),m.group(2)
            n=ss[i+1]
            m2=re.match(r"「規格設定」ボタンから商品規格登録編集画面を開き、(1つ目の商品規格として、)?商品コードに (\S+)、販売価格に (\d+)、部門に試験用の部門を入れ、公開ステータスで「公開」を選んで「商品規格を登録」ボタンを押す$",n)
            assert m2,(sid,n)
            code,price=m2.group(2),m2.group(3)
            new.append(csvs(code,name,price)); new.append(edit_spec(code,cat)); changed=True
            i+=2; continue
        new.append(s); i+=1
    # 017: second spec sentence
    for k,s in enumerate(new):
        if s.startswith("同じ商品の商品規格一覧へ戻り、「規格設定」ボタンから商品規格登録編集画面を開き、言語または状態を1つ目と変えた"):
            new[k]=s.replace("「規格設定」ボタンから商品規格登録編集画面を開き","商品規格一覧の「新規作成」を押して商品規格登録編集画面を開き").replace("言語または状態を1つ目と変えた2つ目の商品規格として","言語または状態を1つ目（日本語・ニアミント）と変えた2つ目の商品規格として").replace("販売価格に 500、","基準価格(円)に 500、販売価格(円)に 500、買取価格(円)に 100、")
    assert changed,sid
    newm="。".join(new)
    reason=""
    if sid.endswith("-017"):
        reason="元のシードの2つ目の規格は1つ目と同じ商品コードを入れて登録している（M03-27 L0134は新規の商品コードの重複を不可としているが、商品規格登録編集画面の重複可否は未確認。元のシードのとおり残した）"
    elif sid.endswith("-020"):
        reason="商品カテゴリはCSVではサプライ・グッズの配下しか入れられないため、取り込み後に商品登録編集画面で付け替える（M03-27 L0123）"
    elif sid.endswith("-018"):
        reason="商品名(英)は元のシードに指定が無いため商品名(日)と同じ値にした。ケースは日本語の商品名の表示だけを確かめる"
    else:
        reason="商品名(英)・基準価格・買取価格・原価単価・サイズ・重量は元のシードに指定が無いためCSV必須列の都合で入れた値"
    if sid.endswith("-007"): pass
    out.append([sid,"直す",newm,"","M03-27 L0092・L0119・L0123・L0124・L0129・L0134〜L0153、M03-09 L0125〜L0134、M03-02 L0075〜L0077",reason])
for r in out:
    for x in r: assert "\t" not in x and "\n" not in x
open("out/F10-02.tsv","w",encoding="utf-8").write("\n".join("\t".join(r) for r in [HDR]+out)+"\n")
print(len(out))
