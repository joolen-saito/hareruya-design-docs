import re
HDR=["シードID","判定","新しい投入方法","新しい状態・属性","根拠","理由"]
rows=[l.split("\t") for l in open("in/F10-02.tsv",encoding="utf-8").read().split("\n")[1:] if l]
CAT="サプライ・グッズのカテゴリID（カテゴリ登録/編集画面の最上位の一覧で「サプライ・グッズ」の行のID欄に表示された値）"
def csvs(code,name,price):
    return ("グッズ商品CSV登録で雛形ファイルをダウンロードし、1行を書いたCSVをCSVファイル選択で選んで「CSVファイルのアップロード」を押し、表示された確認モーダルでアップロードを確定する"
      f"（商品IDは空・商品コードは「{code}」・商品名(日)は「{name}」・商品名(英)は「{name}」・言語(ID)は日本語のID・商品公開ステータスは2（公開）・支店の商品公開ステータスは1（公開）・サイズ1・重量1・商品カテゴリ(ID)は{CAT}・購入グループ名称は既存の購入グループの名称・基準価格{price}・販売価格{price}・買取価格100・原価単価10・地域別販売制限は0（日英の両サイト）・部門IDは空）。グッズ商品は状態ニアミント・日本語の規格が1件作られる")
def edit_spec(code,cat=None,lead=""):
    s=(f"商品マスター(検索入力)で商品コードに「{code}」を入れて「検索する >」を押し、商品マスター(検索結果)の行から商品登録編集画面（既存の商品の編集）を開く")
    if cat:
        s+=f"。商品カテゴリはサプライ・グッズの選択を外して「{cat}」を選び、割引率に販売割引率に登録済みのものを選んで「商品を登録」ボタンを押す。続けて商品登録編集画面の「規格設定」ボタンから商品規格一覧を開く"
