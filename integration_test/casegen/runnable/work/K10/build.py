def load(n):
    ls=open(R/f'kept/in/{n}.tsv',encoding='utf-8').read().split('\n')
    return [l.split('\t') for l in ls[1:] if l.strip()]
def save(n,rows):
    out=["\t".join(["種別","対象ID","列","判定","新しい文","根拠","理由"])]
    for r in rows:
        assert all(('\t' not in c and '\n' not in c) for c in r),r[:2]
        out.append("\t".join(r))
    (R/f'kept/out/{n}.tsv').write_text("\n".join(out)+"\n",encoding='utf-8')
def rep1(t,old,new):
    assert t.count(old)==1,(old,t.count(old))
    return t.replace(old,new)

