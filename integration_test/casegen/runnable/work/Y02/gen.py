def b0205(text, sid):
    no = sid.split('-')[-1]
    cnt = [0]
    def rep(m):
        lab = m['lab']; code = lab[len('〔商品ID-'):-1]
        ja = m['ja']; en = m['en']
        ja = (code + '商品') if '任意' in ja else ja.strip('「」')
        en = ('Item' + code.replace('-', '')) if '任意' in en else en.strip('「」')
        lang = m['lang']
        if 'どちらか' in lang:
            lang = '日本語' if code.endswith('D') else '英語'
        else:
            lang = lang.strip('「」')
        sale = m['sale'].startswith('に')
        s = one(code, ja, en, lang + '', lab)
        s = s.replace(f'言語(ID)は{lang}のID', f'言語(ID)は{lang}のID')
        s += f'{lab}の商品規格一覧画面で' + NEWSPEC.format(code=code)
        if sale:
            s += 'セールフラグにチェックを入れ、販売価格に「800」を入れ、'
        else:
            s += 'セールフラグのチェックは外したまま、'
        s += '部門は登録済みの部門を選び、公開ステータスに「公開」を選んで「商品規格を登録」ボタンを押す。'
        cnt[0] += 1
        return s
    new = R05.sub(rep, text)
    return new, cnt[0]

