def b0202(text, sid):
    cnt = [0]
    def rep(m):
        n = m['n']; sl = m['sl']; pl = m['pl'] or m['pl2']
        code = sl[len('〔商品規格ID-'):-1]
        en = 'Item' + code.replace('-', '')
        s = one(code, n, en, '日本語', pl) if pl else (UP.format(n=1, body=row(code, n, en, '日本語')).replace('件ずつ作られる','件作られる') + f'商品マスター(検索入力)で商品コードに「{code}」を入れて「検索する >」を押す。')
        if m['card']:
            s += CARD.format(ja=n, en=en)
            s += SPEC.format(code=code)
        else:
            s += OPEN + SPEC.format(code=code)
        s += f'商品規格登録編集画面の商品規格ID欄に表示された番号を控える（{sl}）。'
        cnt[0] += 1
        return s
    new = R02.sub(rep, text)
    return new, cnt[0]

