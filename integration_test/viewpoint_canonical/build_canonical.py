def main():
    vp = {r["観点ID"]: r for r in csv.DictReader(
        (ROOT / "ipa-integration-test-viewpoints.tsv").open(encoding="utf-8"), delimiter="\t")
        if r.get("観点ID")}
    old = {int(r["No"]): r for r in csv.DictReader(
        (ROOT / "archive/integration-test-viewpoints.md").open(encoding="utf-8"), delimiter="\t")
        if r.get("No")}
    mig = {int(r["旧No"]): r for r in csv.DictReader(
        (ROOT / "MIGRATION_MAP.tsv").open(encoding="utf-8"), delimiter="\t")}

    # 観点は必ず何かに紐づく。何に紐づくかを層ごとに固定する。
    # 結合行だけがテストケースへ紐づき、機械ゲートの検査対象になる。
    # 1行1観点。テストケース1行が複数観点を見る状態を作らない（依頼者決裁）。
    # 納品物なので「要確認」を残さない（依頼者指示 2026-09-01）。
    # 出典・位置付け・改訂・旧No・旧IT-ID・旧層メモは表の来歴を記録する列で、
    # テストケースの作成にも実行にも使わないため落とす。
    # 出典は331行中169行が「要確認」だった。
    hdr = ["判定ID", "観点ID", "テスト区分", "大項目", "テスト観点",
           "対象", "判定単位", "期待値の決め方", "確認内容", "適用条件"]

    # Excelの注記が大項目に紛れ込んでいる。対象の名前へ直す。
    FIX = {"※ファイルダウンロードを含む": "ファイル出力", "※ファイルアップロードを含む": "ファイル取込"}
    rows, n = [], 0

    def add(層, 由来, vids, oldno, oldid, oldcls, text, meta_id, memo=""):
        nonlocal n
        n += 1
        m = vp.get(meta_id, {})
        how = "設計書から引用" if any(k in text for k in REF) else "観点内で確定"
        assert len(vids) == 1, f"1行1観点でない: {oldno} {vids}"
        rows.append([f"IT-{n:04d}", vids[0], m.get("テスト区分", ""), m.get("大項目", ""),
                     m.get("テスト観点", ""), oldcls, text, how,
                     m.get("確認内容", ""), m.get("適用条件", "")])

    for no in sorted(old):
        r = old[no]
        if r["テスト層"] != "結合":
            continue
        st = mig.get(no, {}).get("状態", "")
        if st != "移行":          # e2eへ送る旧No.332 を落とす
            continue
        層 = {"移行": "結合", "委譲(機能別チェックリスト)": "機能別チェックリスト",
              "e2eへ送る": "e2eへ送る"}.get(st, st or "未分類")
        由来 = "旧結合" if r["テスト層"] == "結合" else "旧委譲"
        vids = [v.strip() for v in mig.get(no, {}).get("新観点ID", "").replace("/", ",").split(",") if v.strip()]
        parts = [FIX.get(x, x) for x in (r["分類"], r["大項目"], r["中項目"], r["小項目"])
                 if x and x != "-"]
        cls = " / ".join(dict.fromkeys(parts))
        memo = r.get("層メモ", "")
        if no in DECOMP:
            for vid, text in DECOMP[no]:
                add(層, 由来, [vid], str(no), r["IT-ID"], cls, text, vid, memo)
        else:
            if len(vids) != 1:
                raise SystemExit(f"分解されていない複数割当: 旧No.{no} {vids}")
            add(層, 由来, vids, str(no), r["IT-ID"], cls, r["観点"], vids[0], memo)

    for vid, small, text in ADD:
        add("結合", "63観点分解", [vid], "", "",
            f"{vp[vid]['大項目']} / {vp[vid]['テスト観点']} / {small}", text, vid, "")

    for vid, small, text in ADD_LINK:
        add("結合", "依頼者追加", [vid], "", "", f"機能間データ連携 / {small}", text, vid, "")

    for vid, small, text in ADD_GA:
        add("結合", "依頼者追加", [vid], "", "", f"アクセス解析連携 / {small}", text, vid, "")

    for vid, small, text in ADD_OUTPUT:
        add("結合", "依頼者追加", [vid], "", "", f"ファイル処理 / ファイル出力 / {small}", text, vid, "")

    for vid, small, text in ADD_MAIL:
        add("結合", "依頼者追加", [vid], "", "", f"メール処理 / {small}", text, vid, "")

    for vid, small, text in ADD_BATCH:
        add("結合", "依頼者追加", [vid], "", "", f"バッチアプリケーション / バッチ / {small}", text, vid, "")

    for vid, small, text in ADD_LINK_PUB:
        add("結合", "依頼者追加", [vid], "", "", f"機能間データ連携 / {small}", text, vid, "")

    for vid, small, text in ADD_DATAPAT:
        add("結合", "依頼者追加", [vid], "", "", f"データパターン / {small}", text, vid, "")

    for vid, small, text in ADD_LINK_API:
        add("結合", "依頼者追加", [vid], "", "", f"機能間データ連携 / {small}", text, vid, "")

    # 同じ判定単位が別の対象で重複する行は、対象の系統を文頭へ足して一意にする。
    seen = collections.Counter(r[6] for r in rows)
    for r in rows:
        if seen[r[6]] > 1 and r[5]:
            r[6] = f"{r[5].split(' / ')[0]}において、{r[6]}"

    b = io.StringIO()
    w = csv.writer(b, delimiter="\t", lineterminator="\n")
    w.writerow(hdr); w.writerows(rows)
    (OUT / "viewpoints_canonical.tsv").write_text(b.getvalue(), encoding="utf-8")

    print(f"観点表 {len(rows)} 行（全行がテストケースへ紐づく）")
    d = collections.Counter(r[6] for r in rows)
    print(f"  判定単位の重複: {sum(v - 1 for v in d.values() if v > 1)}")
    print(f"  1行1観点: {'○' if all(',' not in r[1] for r in rows) else '×'}")
    print(f"  期待値: " + str(dict(collections.Counter(r[7] for r in rows))))
    print(f"  『要確認』を含む行: {sum(1 for r in rows if any('要確認' in str(c) for c in r))}")
    cov = {r[1] for r in rows}
    print(f"  63観点の被覆: {len(cov & set(vp))} / {len(vp)}")


if __name__ == "__main__":
    main()
