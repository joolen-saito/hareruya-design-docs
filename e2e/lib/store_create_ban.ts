/** 店舗登録画面（新規）の URL を返す。許された1回だけ。それ以外は止める（開かない） */
export function 店舗の作成を1回だけ許す(呼び出し元: string, ケースID: string): string {
  if (process.env.E2E_STORE_CREATE_ONCE !== "1") 店舗の作成は禁止(`${呼び出し元}（E2E_STORE_CREATE_ONCE=1 で流していない）`);
  if (!(作ってよいケース as readonly string[]).includes(ケースID)) 店舗の作成は禁止(`${呼び出し元}（${ケースID} は作ってよい4件ではない）`);
  const rows = fs.existsSync(台帳) ? fs.readFileSync(台帳, "utf-8").split("\n").filter((l) => l.trim()) : [];
  if (rows.some((l) => l.split("\t")[0] === ケースID)) 店舗の作成は禁止(`${呼び出し元}（${ケースID} はもう1回作った。2回目は作らない）`);
  if (rows.length >= 上限) 店舗の作成は禁止(`${呼び出し元}（作ってよい${上限}店舗に達した）`);
  fs.mkdirSync(path.dirname(台帳), { recursive: true });
  fs.appendFileSync(台帳, `${ケースID}\t${new Date().toISOString()}\t${呼び出し元}\n`);
  return adminUrl("/mall/tenant/create");
}

