defineSeed("S-A15-09-MASTER", { needs: ["S-A15-18-FORMATS", "S-A15-18-CARDS", "S-A15-18-SCOPES", "S-A15-18-RELATED"] }, async (ctx) => {
  const { notes } = ctx;
  notes.set("〔フォーマットID-A1509-共有〕", notes.get("〔フォーマットID-A1518-共有B〕"));
  notes.set("〔アーキタイプID-A1509-共有〕", notes.get("〔アーキタイプID-A1518-共有〕"));
  const 写し: [string, string][] = [["A", "A"], ["B", "B"], ["C", "C"], ["D", "D"], ["E", "E"], ["F", "F"], ["G", "A"]];
  for (const [k, 元] of 写し) notes.set(`〔カードID-A1509-共有${k}〕`, notes.get(`〔カードID-A1518-共有${元}〕`));
  notes.set("〔キャンペーンタグID-A1509-共有A〕", notes.get("〔キャンペーンタグID-A1518-共有A〕"));
  notes.set("〔キャンペーンタグID-A1509-共有B〕", notes.get("〔キャンペーンタグID-A1518-共有B〕"));
  const 不足 = 参照マスタの不足();
  if (不足.length) throw new Error(`登録済みのはずのマスタが足りない（${不足.join("、")}）。書き換えずに止める`);
  if (!アーキタイプの番号("結合試験アーキタイプ", notes.get("〔フォーマットID-A1509-共有〕"))) throw new Error("アーキタイプ「結合試験アーキタイプ」が見つからない");
  if (公開範囲の数("4") !== 0) throw new Error("公開範囲ID 4 が登録されている（シード表は未登録。ほかの方の行かもしれないので消さずに止める）");
  if (配置ボードの数("7") !== 0) throw new Error("配置ボードID 7 が登録されている（シード表は未登録。ほかの方の行かもしれないので消さずに止める）");
  注(ctx, "フォーマット・カード・アーキタイプ・キャンペーンタグは A15-18 のシードが作った（または既にある）ものを使った（フォーマット=「結合試験フォーマット」、カードA〜F=A15-18 のカードA〜F、カードGはカードAを使い回し、キャンペーンタグ=結合試験キャンペーンA・B。カード画像ID 15932の代わりにカードAの画像）。公開範囲ID 1〜3・配置ボードID 1〜3・ユーザー作成デッキの種別は有ることを DB で確かめ、公開範囲ID 4・配置ボードID 7 は無いことを数えた（消さない）");
});

