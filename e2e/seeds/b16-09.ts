/**
 * B16-09 サイトマップ生成処理のシード。正本: cases/B16-09_seed_data.tsv
 * 2026-11-20 は、サイトマップを読むだけのケース（下のシードだけを使うもの）を書いた。記録 review/B16-09_progress_2026-11-20_dev.md。
 *
 * シードでの解釈（正本の外の補い）:
 * - S-B16-09-WEB（試験用サイト）は、共有の開発環境をそのまま使う。サイトマップ1ファイルあたりの件数と、画像の配信の基点の設定値は
 *   書き換えない（アプリの設定ファイルの値で、開発環境では変えられない）。それに頼るケースは流せない一覧に入れてあり、ここでは書かない。
 *   在庫なし商品を隠す設定が無効なことは、DB を読んで確かめる（有効なら止める。共有の設定なので書き換えない）。
 * - 「公開中の商品が1件登録されている」「デッキが1件登録されている」だけを置くシードは、そのケースの期待結果がその商品・デッキを見ない。
 *   そのため新しく作らず、公開中の商品・公開のデッキが開発環境にすでにあることを DB で確かめる（ほかの方のデータは読むだけ）。
 */
import { 公開のデッキの数, 公開中の商品の数, 在庫なし商品を隠す } from "../db/b16_09";
import { defineSeed, reportSeedIssue } from "../lib/seeds";

defineSeed("S-B16-09-WEB", async ({ seed }) => {
  if (在庫なし商品を隠す()) throw new Error(`${seed.シードID}: 本店の基本設定の「在庫なし商品を隠す」が有効（シード表は無効。共有の設定なので書き換えずに止める）`);
  reportSeedIssue(seed.シードID, "共有の開発環境をそのまま使った。サイトマップ1ファイルあたりの件数・画像の配信の基点の設定値は書き換えていない（開発環境の設定ファイルの値）。本店の「在庫なし商品を隠す」が無効なことを DB で確かめた");
});

for (const id of ["S-B16-09-MIME-012", "S-B16-09-HEAD-013", "S-B16-09-REDIR-061", "S-B16-09-REDIRQ-062", "S-B16-09-REDIRNAME-063", "S-B16-09-LANGIDX-066"]) {
  defineSeed(id, async ({ seed }) => {
    const n = 公開中の商品の数();
    if (n < 1) throw new Error(`${seed.シードID}: 公開中の商品が1件も無い`);
    reportSeedIssue(seed.シードID, `シード表の商品は作らず、公開中の商品が開発環境にすでにあること（${n}件）を DB で確かめた。このケースの期待結果は、その商品を見ない`);
  });
}

defineSeed("S-B16-09-LANGDECKL-087", async ({ seed }) => {
  const n = 公開のデッキの数();
  if (n < 1) throw new Error(`${seed.シードID}: 公開のデッキが1件も無い`);
  reportSeedIssue(seed.シードID, `シード表のデッキは作らず、公開のデッキが開発環境にすでにあること（${n}件）を DB で確かめた。このケースの期待結果は、デッキ一覧のサイトマップの全部の掲載の言語区分を見る`);
});
