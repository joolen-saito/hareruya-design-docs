/**
 * M07-10 買取商品履歴 の画面シード。正本: cases/M07-10_seed_data.tsv
 *
 * 作り方（シード表の手順のとおり。部品は seeds/m07-03-b.ts・seeds/m07-01-b.ts・seeds/m07-db-prep.ts を使う）:
 *  1) 査定担当者のメンバーを、メンバー管理の画面で登録する。
 *  2) 買取に入れる商品を、グッズ商品CSV登録（カード情報なしのサプライ品）で登録する。買取の申込に使う商品（買取価格500）も同じ方法で登録する。
 *  3) 会員をフロントの会員登録＋管理画面の会員登録編集で作り、会員IDを控える。その会員でフロントから申込用の商品を申し込む。
 *  4) 管理画面の買取情報編集で、「商品追加」で商品を足し、「査定編集」で査定価格・数量・売却「する」を入れて保存し、申込用の商品の明細を削除し、
 *     買取状況を「査定内容承諾」→「振込完了」（入庫待ちへ進む）→「入庫済み」の順に保存する（売却する明細の数量で実在庫と実在庫履歴が作られる）。
 *  5) 画面で指定できない部分だけ、実行の印つきの行に限り DB で整える: 販売価格・基準価格、査定担当者、買取依頼日、振込完了日、実在庫履歴の数量、実在庫の数量、
 *     画面で作れない買取状況（振込完了・未登録在庫あり）。
 * 決め打ちの商品コードには実行の印を付ける。会員のメールアドレスも実行の印つき。注文者名（姓）も実行の印つき。
 * シード表の「ほかの買取情報があれば削除する」は共有の環境を消すので行わない。ただし M07-10-021 は査定担当者名の部分一致で件数を数えるため、
 * 前の実行の残り（注文者名 M0710-021姓 を含む買取）だけを一覧から削除してから始める。
 */
