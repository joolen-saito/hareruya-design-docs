const 必要な状況 = ["注文", "商品到着", "査定中", "査定中断", "査定再開", "MTGBuyer査定完了", "査定内容連絡済み", "査定内容承諾", "簡易書留送付済み", "振込依頼済み", "振込完了", "振込失敗", "未登録在庫あり", "入庫待ち", "入庫済み（仕入れ完了）", "キャンセル済み"];

// 買取状況マスタは共有のマスタ。書き換えず、登録済みであることを読んで確かめる（シード表も「登録済みの環境ではそのまま使う」）
defineSeed("S-M07-10-STATUS", async ({ seed }) => {
  let 登録済み: string[];
  try { 登録済み = 買取状況の名前一覧(); } catch (e) {
    reportSeedIssue(seed.シードID, `買取状況マスタの登録済みの確認（DB参照）ができなかったので、確認せずに進めた: ${(e as Error).message.split("\n")[0]}`);
    return;
  }
  const 名 = (s: string) => s.replace(/（[^）]*）$/, "").trim();
  const 無い = 必要な状況.filter((s) => !登録済み.some((r) => 名(r) === 名(s)));
  if (無い.length) throw new Error(`買取状況マスタに ${無い.join("・")} が無い（共有のマスタは書き換えない。登録済みの名前: ${登録済み.join("・")}）`);
  if (登録済み.some((r) => r === "入庫済み")) reportSeedIssue(seed.シードID, "買取状況マスタの名前は「入庫済み」（正本は「入庫済み（仕入れ完了）」）。同じ状況として扱った");
});

// ---- 作り方の部品 ----

type 明細 = {
  /** 商品コードの枝（例 A・P01）。商品コードは M0710-<n>-<枝> */
  枝: string; 基準価格?: number; 販売価格?: number; 設定の買取価格?: number; 実際の買取単価?: number; 買取明細の数量?: number; 実在庫履歴の数量?: number;
};
type 買取の状況 = "入庫済み" | "入庫待ち" | "振込完了" | "未登録在庫あり";
type 買取 = {
  /** 呼び名の末尾（011A の A。1件だけなら空） */
  末尾: string; 明細: 明細[]; 状況?: 買取の状況;
  /** 査定担当者（名前・ログインID）。省略は「M0710-<n>担当」 */
  担当?: { 名前: string; ログインID: string };
  /** 実在庫の数量を直接設定する（商品の枝と数量） */
  実在庫の数量?: { 枝: string; 数: number };
};
type 会員 = { 末尾: string; 買取: 買取[] };

const コード = (n: string, 枝: string): string => rc(`M0710-${n}-${枝}`);
const 日時 = (s: string): string => `${s}+09`;
const 既定 = { 基準価格: 300, 販売価格: 400, 設定の買取価格: 250, 実際の買取単価: 200, 買取明細の数量: 1, 実在庫履歴の数量: 1 };
const 申込用の枝 = (n: string): string => rc(`M0710-APPLY-${n}`);

/** 「呼び名」に付ける末尾つきの形: 〔買取番号-M0710-011A〕 */
const 買取番号の呼び名 = (n: string, 末尾: string): string => `〔買取番号-M0710-${n}${末尾}〕`;
const 会員IDの呼び名 = (n: string, 末尾: string): string => `〔会員ID-M0710-${n}${末尾}〕`;

type 作り方 = { 会員: 会員[]; 会員IDは会員ごと?: boolean };

/** 会員ごとに買取を作る。会員IDの呼び名は 会員.末尾、買取番号の呼び名は 買取.末尾 */
function 買取を作る(seedId: string, n: string, o: 作り方 & { 前の残りを消す?: boolean; 存在しない買取番号?: string }): void {
  defineSeed(seedId, { needs: ["S-M07-10-ADM", "S-M07-10-STATUS"] }, async ({ browser, notes }) => {
    const issue = (m: string) => reportSeedIssue(seedId, m);
    const 全買取 = o.会員.flatMap((m) => m.買取);
    const 担当 = (b: 買取) => b.担当 ?? { 名前: `M0710-${n}担当`, ログインID: `m0710_t${n}` };
    // 1) 査定担当者のメンバー
    const 登録済み = new Set<string>();
    for (const b of 全買取) {
      const t = 担当(b);
      if (登録済み.has(t.ログインID)) continue;
      登録済み.add(t.ログインID);
      await 試験管理者を用意する(browser, { loginId: t.ログインID, password: "Passw0rd!M0710T" }, t.名前);
    }
    issue("シード作成時の問題: 査定担当者は、メンバー管理のメンバー登録（名前は正本の値。ログインIDとパスワードは試験用、権限はシステム管理者）で作り、買取への紐づけは画面で指定できないのでDBで行った");
    // 前の実行の残りを消す（件数を数えるケースだけ）
    if (o.前の残りを消す) {
      const removed = await 注文者名の残りを削除する(browser, `M0710-${n}姓`, []);
      issue(`前の実行の残り（注文者名に「M0710-${n}姓」を含む買取 ${removed} 件）を一覧から削除してから始めた（査定担当者名の部分一致で件数を数えるケースのため）`);
    }
    if (o.存在しない買取番号) {
      let 件数: number | null = null;
      try { 件数 = 買取情報の件数(o.存在しない買取番号); } catch { 件数 = null; }
      if (件数 === null) issue(`買取番号 ${o.存在しない買取番号} を持つ買取情報が無いことは、DB参照ができず確かめられなかった`);
      else if (件数 > 0) issue(`買取番号 ${o.存在しない買取番号} を持つ買取情報が既にある（${件数}件）。シード表は存在しない前提だが、共有の環境の買取は消さないので、そのまま進めた`);
    }
    // 2) 商品
    const 明細一覧 = 全買取.flatMap((b) => b.明細);
    const 申込用 = 申込用の枝(n);
    const ids = await withAdminSession(browser, SETUP_ADMIN, async (page) => {
      page.setDefaultTimeout(60_000);
      await サプライ品を登録する(page, [
        { コード: 申込用, 名前: 申込用, 基準価格: "1000", 買取価格: "500" },
        ...明細一覧.map((m) => ({ コード: コード(n, m.枝), 名前: コード(n, m.枝), 基準価格: String(m.基準価格 ?? 既定.基準価格), 買取価格: String(m.設定の買取価格 ?? 既定.設定の買取価格) })),
      ], issue);
      return { 申込用: await 商品IDを画面で引く(page, 申込用) };
    });
    // 販売価格・基準価格は画面で指定できない（販売価格は基準価格と同じ値で保存される）のでDBで設定する
    for (const m of 明細一覧) 商品の価格を設定する(コード(n, m.枝), m.基準価格 ?? 既定.基準価格, m.販売価格 ?? 既定.販売価格);
    issue(`シード作成時の問題: 商品の基準価格・販売価格は画面で指定できない（グッズ商品CSV登録は販売価格が買取価格より大きい値しか登録できず、基準価格と同じ値で保存される）ので、DBで ${明細一覧.map((m) => `${コード(n, m.枝)}（基準${m.基準価格 ?? 既定.基準価格}・販売${m.販売価格 ?? 既定.販売価格}）`).join(" / ")} にした。商品コードは実行の印つき、買取価格500の申込用商品（${申込用}）も同じ方法で登録した`);

    // 3)〜5) 会員ごと
    for (const 会 of o.会員) {
      const 主 = `m0710-${n}${会.末尾.toLowerCase()}`;
      const メール = `${rc(主)}@example.test`.toLowerCase();
      const 姓 = rc(`M0710-${n}姓`);
      const 名 = `M0710-${n}名`;
      const 会員ID = await 会員を用意する(browser, seedId, { 姓, 名, セイ: "テストセイ", メイ: "テストメイ", メール, 電話: ["090", "1234", "5678"] });
      notes.set(会員IDの呼び名(n, 会.末尾), 会員ID);
      // 申込（買取ごと）
      const 番号: string[] = [];
      const ctx = await browser.newContext({ baseURL: BASE_URL, locale: "ja-JP", ignoreHTTPSErrors: true });
      try {
        await hideDebugToolbar(ctx);
        const fp = await ctx.newPage();
        fp.setDefaultTimeout(60_000);
        await ログインする(fp, { メール, パスワード: 会員のパスワード });
        for (const _ of 会.買取) {
          番号.push(await 条件つきで申込む(fp, [{ 商品ID: ids.申込用, 数量: "1" }], { 承諾方法: "査定結果を確認してから承諾する", 登録番号: null, 口座名義: "シケンシード" }));
        }
      } finally { await ctx.close(); }
      // 管理画面の操作
      for (let i = 0; i < 会.買取.length; i++) {
        const b = 会.買取[i];
        const 画面の状況 = b.状況 === "入庫済み" ? ["査定内容承諾", "振込完了", "入庫済み"] : ["査定内容承諾", "振込完了"];
        const 画面で出来なかった: string[] = [];
        await withAdminSession(browser, SETUP_ADMIN, async (page) => {
          page.setDefaultTimeout(60_000);
          let e = await 一覧から編集を開く(page, 番号[i]);
          for (const m of b.明細) await e.明細に商品を追加する(コード(n, m.枝));
          await e.査定編集を始める();
          for (const m of b.明細) await e.明細を名前で入れる(コード(n, m.枝), { 査定価格: String(m.実際の買取単価 ?? 既定.実際の買取単価), 数量: String(m.買取明細の数量 ?? 既定.買取明細の数量), 売却: "する" });
          await e.査定確定する();
          await e.保存する(`買取番号 ${番号[i]} の査定（${b.明細.map((m) => コード(n, m.枝)).join("・")}）`);
          e = await 一覧から編集を開く(page, 番号[i]);
          await e.明細を削除する(申込用, "OK");
          for (const st of 画面の状況) {
            e = await 一覧から編集を開く(page, 番号[i]);
            try { await e.買取状況を変えて保存する(st); } catch (err) {
              const msg = (err as Error).message;
              if (!/買取状況に「.*」が無い/.test(msg)) throw err;
              画面で出来なかった.push(st);
              break;
            }
          }
        });
        const 目標 = b.状況 ?? "入庫済み";
        if (画面で出来なかった.length) issue(`買取番号 ${番号[i]}: 買取状況の選択肢に ${画面で出来なかった.join("・")} が無く、画面の保存で進められなかったので、DBで買取状況を「${目標}」にした`);
        // DB: 画面で指定できない部分
        const 印 = メール;
        const 担 = 担当(b);
        査定担当者を設定する(番号[i], 印, 担.ログインID);
        買取依頼日をDBで設定する(番号[i], 印, 日時("2026-06-14 00:00:00"));
        if (画面で出来なかった.length || 目標 === "振込完了" || 目標 === "未登録在庫あり") 買取状況をDBで設定する(番号[i], 印, 目標);
        状況の履歴をDBで入れ替える(番号[i], 印, "振込完了", [日時("2026-06-15 00:00:00")]);
        for (const m of b.明細) {
          const 履歴数 = m.実在庫履歴の数量 ?? 既定.実在庫履歴の数量;
          if (履歴数 !== (m.買取明細の数量 ?? 既定.買取明細の数量)) {
            実在庫履歴の数量を設定する(番号[i], 印, コード(n, m.枝), 履歴数);
            issue(`実在庫履歴の数量は画面では買取明細の数量と同じ数で作られ、増減数で変えると履歴がもう1件増えるので、DBで ${コード(n, m.枝)} の実在庫履歴の数量を ${履歴数} にした`);
          }
        }
        if (b.実在庫の数量) {
          実在庫の数量を設定する(番号[i], 印, コード(n, b.実在庫の数量.枝), b.実在庫の数量.数);
          issue(`実在庫の数量は、実在庫履歴を1件のままにして画面で作れないので、DBで ${コード(n, b.実在庫の数量.枝)} の実在庫の数量を ${b.実在庫の数量.数} にした`);
        }
        notes.set(買取番号の呼び名(n, b.末尾), 番号[i]);
      }
    }
    issue(`シード作成時の問題: 会員は、フロントの会員登録＋管理画面の会員登録編集（本会員・職業）で作った。メールアドレスと注文者名（姓）は実行の印つき。申込は買取価格500の申込用商品で行い、商品追加・査定編集・申込用商品の明細削除・買取状況の保存はシード表の順に画面で行った。買取依頼日（2026-06-14）・振込完了日（2026-06-15）は画面では操作した日時になるのでDBで設定した（振込完了のステータス変更履歴の日時を置き換えた）`);
    issue("シード作成時の問題: シード表の「上で作った買取以外の行を削除する」は、共有の環境の買取を消すので行っていない（ケースは買取番号・会員ID・商品コードなど、作った行だけに絞る検索で確かめる）");
  });
}

