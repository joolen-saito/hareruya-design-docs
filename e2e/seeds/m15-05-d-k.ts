/**
 * M15-05 デッキ編集 の、DBで整える部分が残っていたシード（現行フォーマット=真・代表カード未設定・記事の紐づけ・検討中のカード）。正本: cases/M15-05_seed_data.tsv
 *
 * 依頼者の承認 2026-11-10「印つきデータは何でも」: E2E が画面で作った「実行の印つき」のデッキ（デッキ名に実行の印が入っている）にだけ、
 * DB への書き込みをしてよい。作り方: まず管理画面でデッキを登録し（seeds/m15-05.ts の 一件登録）、画面で作れない部分だけを
 * db/m15_05_prep.ts（db/write_adapter.ts の writeTestData（lib/db_write.ts の窓口を通す） 経由）で整える。整えたことは、シードの注記（シード作成時の問題）に残る。
 *
 * 読み替え（シード表から一意に決まらず、こう決めた）:
 * - 記事「M1505-0nn-記事」の記事名は、記事の表に名前の列が無い（外部の投稿側の値）ので設定できない。記事の行を1件作り（URL にデッキ名＝実行の印を入れた）、デッキに紐づけた。
 * - 「同じ名前のデッキが残っていれば登録し直さず戻す」は、デッキ名が実行の印つきで毎回新しい名前なので、行わない（記事・検討中のカードが付いたデッキは画面で消せないが、残りと名前がぶつからない）。
 * - 検討中のカードのカードは、シード表の「登録済みの任意の1枚」のうち DeckTestAlpha（共有のカード。読むだけ）にした。
 */
import { defineSeed, reportCurrentSeedIssue } from "./current_seed";
import { 名, 一件登録, 管理画面, マスタ, defineArchetypeSeed, ALPHA, BETA, 標準, 単一, 上限, 下限, 統率なし, 型甲 } from "./m15-05-k";
import type { デッキ内容 } from "../pages/admin/m15_05_deck_edit";
import * as prep from "../db/m15_05_prep";

const 記す = (m: string) => reportCurrentSeedIssue(`シード作成時の問題: ${m}`);

type 整え = {
  現行フォーマット?: boolean;
  代表カード未設定?: boolean;
  記事?: boolean;
  検討中のカード?: boolean;
};

/** デッキを1件画面で登録し、画面で作れない部分をDBで整える。デッキIDを〔デッキID-M1505-<key>〕に控える */
function defineWDeckSeed(seedId: string, key: string, 正本名: string, 内容: デッキ内容, 整え: 整え, needs: string[] = マスタ): void {
  defineSeed(seedId, { needs }, async ({ browser, notes }) => {
    await 管理画面(browser, async (page) => {
      const id = await 一件登録(page, seedId, 正本名, 内容);
      notes.set(`〔デッキID-M1505-${key}〕`, id);
      const デッキ名 = 名(正本名);
      if (整え.現行フォーマット) {
        prep.現行フォーマットを真にする(id, デッキ名);
        記す(`現行フォーマット=真は画面で指定できないので、DBでデッキ ${id}（${デッキ名}）の現行フォーマットを真にした`);
      }
      if (整え.代表カード未設定) {
        prep.代表カードを未設定にする(id, デッキ名);
        記す(`代表カード=未設定は画面で戻せないので、DBでデッキ ${id}（${デッキ名}）の代表カードを未設定（画像なし）にした（アーキタイプの代表カードは変えていない）`);
      }
      if (整え.記事) {
        prep.記事を紐づける(id, デッキ名);
        記す(`記事とデッキの紐づけは画面で指定できないので、DBで記事の行を1件作ってデッキ ${id}（${デッキ名}）に紐づけた（記事名は記事の表に列が無いので設定していない）`);
      }
      if (整え.検討中のカード) {
        prep.検討中のカードを足す(id, デッキ名, ALPHA);
        記す(`検討中のカードは画面で指定できないので、DBでデッキ ${id}（${デッキ名}）に ${ALPHA} を1枚足した（デッキ削除の処理が参照の制約で失敗する仕掛け）`);
      }
    });
  });
}

