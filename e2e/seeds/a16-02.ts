/**
 * A16-02 言語コードに紐づいたトップバナーの情報一覧の取得のシード。正本: cases/A16-02_seed_data.tsv
 *
 * 全員が見る開発環境のフロントのトップページに影響するため、トップバナーと言語は書き換えない（依頼者の指示 2026-11-21）。
 * シードでの解釈（正本の外の補い。記録 review/A16-02_progress_2026-11-21_dev.md にも書く）:
 * - ENV（接続先の設定）: 共有の開発環境では接続先を書き換えず、環境に設定済みの値を使う（何もしない）。
 * - JP: 言語が登録済みであることと名称を DB で読んで確かめるだけ。シード表の「再登録」は行わない（共有マスタ）。
 * - BANNERS: 行わない。バナーの内容・日本語への紐づけを書き換えると、全員が見るトップページの表示が変わるため。
 *   このシードを使うケースは、期待結果が個々のバナーの内容に依存しないもの（001・006）だけ書いた。
 */
import { 言語を探す } from "../db/a16_02";
import { defineSeed, reportSeedIssue } from "../lib/seeds";

defineSeed("S-A16-02-ENV", async ({ seed }) => {
  reportSeedIssue(seed.シードID, "共有の開発環境では接続先を書き換えず、環境に設定済みの値を使った（試験ブラウザから公開APIへ認証情報なしで GET を送る）");
});

defineSeed("S-A16-02-JP", async ({ seed }) => {
  const 言語 = 言語を探す("JP");
  if (!言語) throw new Error(`${seed.シードID}: 言語コードJPの言語が登録されていない（共有マスタなので書き込まずに止める）`);
  const 同じ = 言語.名日 === "日本語" && 言語.名英 === "Japanease";
  reportSeedIssue(seed.シードID, `言語コードJPの言語は登録済み（言語名（日本語）「${言語.名日}」・言語名（英語）「${言語.名英}」）。${同じ ? "シード表の値と同じなので" : "シード表の値と違うが共有マスタなので"}書き換えずに使った`);
});

defineSeed("S-A16-02-BANNERS", async ({ seed }) => {
  reportSeedIssue(seed.シードID, "全員が見るトップページに出る内容（バナーの画像・リンク先・日本語への紐づけ）を書き換えるため、トップバナーは書き換えずに現状のまま使った。個々のバナーの内容に依存しない確かめだけを行う");
});
