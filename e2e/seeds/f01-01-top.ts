type 計画 = {
  フォーマット: { 名: string; メタ日数: string; ランキング: boolean; 呼び名?: string }[];
  カード: (試験カード & { 呼び名?: string })[];
  イベント?: { 名: string; 日前: number; フォーマット: number[]; 呼び名?: string }[];
  デッキ?: { フォーマット: number; 公開: boolean; 日前: number; イベント名: string; メイン: [number, string][]; 呼び名?: string }[];
  /** ほかのフォーマットの「ランキング表示」を外す（058） */
  ほかを外す?: boolean;
};

/** このプロセスで作ったカード（カード名 → 商品ID・商品名など）。ケースが商品名を引くのに使う */
export const 作ったデッキのカード: Map<string, 作ったカード> = new Map();

function デッキのシード(seedId: string, p: 計画): void {
  defineSeed(seedId, async (ctx) => {
    const { browser } = ctx;
    const issue = (m: string) => reportSeedIssue(seedId, m);
    const 値: Record<string, string> = {};
    const ids: string[] = [];
    for (const f of p.フォーマット) {
      const id = await 試験フォーマットを登録する(browser, seedId, { 名: f.名, メタ日数: f.メタ日数 }, issue);
      ids.push(id);
      if (f.呼び名) 値[f.呼び名] = id;
    }
    issue(`フォーマットの並び順は9000、フォーマットコードは名前から作った値にした（シード表は値を定めない）`);
    if (p.ほかを外す) {
      const 外した = await ほかのフォーマットのランキング表示を外す(browser, seedId, ids, issue);
      issue(`ほかのフォーマットのうち「ランキング表示」にチェックのあった ${外した.length} 件（番号 ${外した.join("・") || "なし"}）のチェックを外した（ケースの終わりに入れ直す）`);
    }
    const cards = await 試験カードを作る(browser, seedId, p.カード, issue);
    for (const c of p.カード) {
      const m = cards.get(c.名)!;
      作ったデッキのカード.set(c.名, m);
      if (c.呼び名 && m.商品ID) 値[c.呼び名] = m.商品ID;
    }
    for (const e of p.イベント ?? []) {
      const id = await 試験イベントを登録する(browser, seedId, { 名: e.名, 開始日: 日前の日付(e.日前), フォーマット: e.フォーマット.map((i) => rc(p.フォーマット[i].名)) }, issue);
      if (e.呼び名) 値[e.呼び名] = id;
    }
    const アーキタイプ = new Map<number, string>();
    for (const d of p.デッキ ?? []) {
      if (!アーキタイプ.has(d.フォーマット)) アーキタイプ.set(d.フォーマット, await 試験アーキタイプを登録する(browser, p.フォーマット[d.フォーマット].名, issue));
      const id = await 試験デッキを登録する(browser, {
        フォーマット名: p.フォーマット[d.フォーマット].名, アーキタイプ: アーキタイプ.get(d.フォーマット)!, 公開: d.公開, イベント名: d.イベント名, 開催日: 日前の日付(d.日前), メイン: d.メイン,
      }, issue);
      if (d.呼び名) 値[d.呼び名] = id;
    }
    if (アーキタイプ.size) issue("デッキの登録に要るアーキタイプ（公開）を、フォーマットごとに1件「<フォーマット名>-ARCHETYPE」で登録した。デッキの開催日の時刻は12:00");
    await ランキング表示を入れる(browser, seedId, ids.filter((_, i) => p.フォーマット[i].ランキング), issue);
    控える(ctx, 値);
  });
}

