/** シード表が控えると定めた呼び名（「…」の例示を除く）を、値の表から控える。表に無い呼び名があれば止める */
function 控える(ctx: SeedCtx, 値: Record<string, string>): void {
  const promised = Notes.labelsIn(ctx.seed["状態・属性"] + ctx.seed.投入方法).filter((l) => !l.includes("…") && l.replace(/[〔〕\s]/g, "") !== "");
  for (const l of promised) {
    if (!(l in 値)) throw new Error(`${ctx.seed.シードID}: シード表の呼び名 ${l} の値を作り方が持っていない`);
    ctx.notes.set(l, 値[l]);
  }
}

