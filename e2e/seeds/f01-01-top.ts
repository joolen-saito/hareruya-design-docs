/** バナーを見分ける文字（画像URL・リンク先URLの問い合わせに付ける） */
export const バナーの印 = (k: string): string => `f0101banner=${k}-${RUN_MARK}`;
export const バナーの画像 = (k: string): string => `/html/template/default/assets/img/noimg.png?${バナーの印(k)}`;
export const バナーのリンク = (lang: "ja" | "en", k: string): string => `/${lang}/?${バナーの印(k)}`;
export const バナーのalt = (k: string): string => `F0101-BANNER-${k}-${RUN_MARK}`;

/** このプロセスで S-F01-01-BANNER が割り当てたバナー（見分ける文字）。日本語・表示は並び順の順 */
export const 割り当てたバナー = { 日本語: [] as string[], 英語: [] as string[], 非表示: "JAHIDE", 画像なし: "JANOURL" };

defineSeed("S-F01-01-BANNER", async ({ browser, seed }) => {
  const issue = (m: string) => reportSeedIssue(seed.シードID, m);
  await 共有のバナーを書き換える(browser, seed.シードID, (控え) => {
    const n = 控え.length;
    if (n < 15) throw new Error(`${seed.シードID}: トップバナー管理のバナーが ${n} 行しか無い（日本語・表示を11件以上と、英語2件・非表示1件・画像URLなし1件に割り当てられない）`);
    const 日本語の数 = Math.min(12, n - 4);
    if (日本語の数 < 12) issue(`トップバナー管理のバナーは ${n} 行しか無い（行は画面で足せない）。日本語・表示・画像URLありのバナーを12件ではなく ${日本語の数} 件にした（表示の上限10件を超える件数は保った）`);
    const 日本語 = Array.from({ length: 日本語の数 }, (_, i) => `JA${String(i + 1).padStart(2, "0")}`);
    const 英語 = ["EN01", "EN02"];
    割り当てたバナー.日本語 = 日本語;
    割り当てたバナー.英語 = 英語;
    type 割り当て = { k: string; 言語: "日本語" | "英語"; 表示: boolean; 画像: boolean };
    const plan: 割り当て[] = [
      ...日本語.map((k) => ({ k, 言語: "日本語" as const, 表示: true, 画像: true })),
      ...英語.map((k) => ({ k, 言語: "英語" as const, 表示: true, 画像: true })),
      { k: 割り当てたバナー.非表示, 言語: "日本語", 表示: false, 画像: true },
      { k: 割り当てたバナー.画像なし, 言語: "日本語", 表示: true, 画像: false },
    ];
    issue(`バナーIDの小さい行から順に、日本語・表示 ${日本語.length} 件 → 英語・表示 2 件 → 日本語・非表示 1 件 → 日本語・表示・画像URLなし 1 件を割り当てた。残りの ${n - plan.length} 行は表示タイプだけ非表示にした`);
    return 控え.map((r, i): バナー行 => {
      const p = plan[i];
      if (!p) return { ...r, 表示タイプ: "非表示", 並び順: r.id };
      return {
        id: r.id, 画像URL: p.画像 ? バナーの画像(p.k) : "", リンク先URL: バナーのリンク(p.言語 === "英語" ? "en" : "ja", p.k),
        言語: [p.言語], 表示タイプ: p.表示 ? "表示" : "非表示", 画像alt: バナーのalt(p.k), 並び順: r.id,
      };
    });
  }, issue);
});

