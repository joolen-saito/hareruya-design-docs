const pad = (n: number) => String(n).padStart(2, "0");
const at = (y: number, md: string) => `${y}-${md}`;

let basePromise: Promise<{ 受注ID: string }> | null = null;
function 基の受注(browser: Browser, issue: (m: string) => void): Promise<{ 受注ID: string }> {
  if (!basePromise) {
    basePromise = 画面で受注を作る(browser, "M12-03 の集計用データの基の受注", "注文受領", issue);
    basePromise.catch(() => { basePromise = null; });
  }
  return basePromise;
}

type データ = {
  /** 受注番号の途中に入る3文字（シードごとに違う値） */
  番号: string;
  月: number;
  受注: (y: number) => 受注の定め[];
  タグ?: boolean;
  注記?: string[];
};

function defineSalesSeed(seedId: string, d: データ): void {
  defineSeed(seedId, { needs: ["S-M12-03-ADM", "S-M05-01-ADM"] }, async ({ browser }) => {
    const issue = (m: string) => reportSeedIssue(seedId, m);
    const y = 空いている年(d.番号, { 月: d.月 });
    const tags = d.タグ ? 使う売上分析タグ(2) : [];
    const base = await 基の受注(browser, issue);
    const 受注 = 受注群を作る(base.受注ID, d.番号, d.受注(y), tags.map((t) => t.id));
    データを控える(seedId, { 年: y, 受注, タグ名: tags.map((t) => t.名称) });
    issue(`読み替え: 正本の日付の年（2026）は、ほかの人の受注が無い遠い将来の年（実行ごとに探して決める。今回は ${y} 年）に読み替えた。商品コードは実行の印を付けた値にした`);
    issue("DBで設定した: 受注は、画面（フロントの購入）で作った印つきの受注の行をDBで写し、注文日・対応状況・キャンセル日・受注明細の単価・数量・商品コード・受注時商品名・移行先受注・スマレジ由来を設定した（画面では指定できないため）。" +
      "店舗の受注（TC東京・店頭受取）は、配送先の配送方法を店頭受取にした。正本の出荷完了・引渡し済みは入金済みの受注で表した");
    for (const n of d.注記 ?? []) issue(n);
  });
}

