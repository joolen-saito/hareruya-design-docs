/**
 * シード表が控えると定めた呼び名を、作ったものの番号で控える（2026-11-12 追加）。
 * 呼び名の末尾の記号（-A・-B…）を、作った順（受注・明細・カテゴリの並び）の番号に当てる。記号の無い呼び名は1つめ。
 * 作っていないもの（シードの読み替えで作らないカテゴリ・カードなど）は「（読み替え: 作らない）」と控える。
 */
function 呼び名を控える(seedId: string, text: string, notes: Notes, v: { 受注: { 受注ID: string; 明細: { 明細ID: string }[] }[]; カテゴリ: string[]; タグID: string[]; カードセットID: string[] }): void {
  const 明細 = v.受注.flatMap((o) => o.明細.map((m) => m.明細ID));
  const 作らない: string[] = [];
  for (const l of [...new Set(text.match(/〔[^〕]+〕/g) ?? [])].filter((x) => !x.includes("…"))) {
    if (notes.has(l) || /〔(管理者ID|店舗ID)-/.test(l)) continue;
    const m = /-([A-Z])〕$/.exec(l);
    const i = m ? m[1].charCodeAt(0) - 65 : 0;
    const 種類 = /^〔([^-]+)-/.exec(l)?.[1] ?? "";
    let 値: string | undefined;
    if (種類 === "受注ID") 値 = v.受注[i]?.受注ID;
    else if (種類 === "注文明細ID") 値 = 明細[i];
    else if (種類 === "配送情報ID") 値 = v.受注[i] ? 受注の配送情報ID(v.受注[i].受注ID) : undefined;
    else if (種類 === "商品ID") 値 = 明細[i] ? 明細の商品と規格(明細[i]).商品ID : undefined;
    else if (種類 === "商品規格ID") 値 = 明細[i] ? 明細の商品と規格(明細[i]).規格ID : undefined;
    else if (種類 === "カテゴリID") 値 = v.カテゴリ[i];
    else if (種類 === "売上分析タグID") 値 = v.タグID[i];
    else if (種類 === "カードセットID") 値 = v.カードセットID[i];
    if (!値) { 作らない.push(l); 値 = "（読み替え: 作らない）"; }
    notes.set(l, 値);
  }
  if (作らない.length) reportSeedIssue(seedId, `読み替え: ${作らない.join("・")} は、このシードでは作らない（呼び名には「（読み替え: 作らない）」を控えた）`);
}

function defineSalesSeed(seedId: string, d: データ): void {
  defineSeed(seedId, { needs: ["S-M12-03-ADM", "S-M05-01-ADM", ...(d.needs ?? [])] }, async ({ browser, seed, notes }) => {
    const issue = (m: string) => reportSeedIssue(seedId, m);
    const y = 空いている年(d.番号, { 月: d.月 });
    const tags = d.タグ ? 使う売上分析タグ(2) : [];
    const 用意: 用意した = { カテゴリ: {}, 商品: {}, カードセット名: [], カードセットID: [], ...(d.用意 ? await d.用意(browser, issue) : {}) };
    const 店 = (k: string) => (notes.has(`〔店舗ID-M1203-共有${k}〕`) ? notes.get(`〔店舗ID-M1203-共有${k}〕`) : "");
    const base = await 基の受注(browser, issue);
    const t0 = Date.now();
    const 定め = d.受注(y, { ...用意, 店舗: { A: 店("A"), B: 店("B"), C: 店("C") } });
    const 受注 = 受注群を作る(base.受注ID, d.番号, 定め, tags.map((t) => t.id));
    const 秒 = Math.round((Date.now() - t0) / 1000);
    データを控える(seedId, { 年: y, 受注, タグ名: tags.map((t) => t.名称), カテゴリ: 用意.カテゴリ, カードセット名: 用意.カードセット名 });
    呼び名を控える(seedId, seed["状態・属性"] + seed.投入方法, notes, { 受注, カテゴリ: Object.values(用意.カテゴリ).map((c) => c.ID), タグID: tags.map((t) => t.id), カードセットID: 用意.カードセットID });
    issue(`読み替え: 正本の日付の年（2026）は、ほかの人の受注が無い遠い将来の年（実行ごとに探して決める。今回は ${y} 年）に読み替えた。商品コードは実行の印を付けた値にした`);
    issue("DBで設定した: 受注は、画面（フロントの購入）で作った印つきの受注の行をDBで写し、注文日・対応状況・キャンセル日・受注明細の単価・数量・商品コード・受注時商品名・移行先受注・スマレジ由来を設定した（画面では指定できないため）。" +
      "店舗の受注（TC東京・店頭受取）は、配送先の配送方法を店頭受取にした。正本の出荷完了・引渡し済みは入金済みの受注で表した");
    issue(`受注を写して整えた時間: 受注 ${受注.length} 件・明細 ${受注.reduce((a, o) => a + o.明細.length, 0)} 件で ${秒} 秒（DBの書き込みは受注1件あたり約10回・明細1件あたり約3回）`);
    for (const n of d.注記 ?? []) issue(n);
  });
}

