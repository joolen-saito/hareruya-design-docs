import { rc } from "../lib/run_marker";
import { reportSeedIssue } from "../lib/seeds";
import { 使い回す店舗の入力 } from "../pages/admin/m04_24_reuse_k";
import { defineSeed } from "./current_seed";
import { M0610_ADMIN } from "./m06-10";
import { 作る, 品, 店の定義 } from "./m06-e-support";

const 入力 = 使い回す店舗の入力("5006", "M06-10試験店舗（本店相当）");
const 本店: 店の定義 = { 入力, 閾値: ["100", "500", "1000"], get 支店URL() { return 入力.支店URL; } };
const セット = { 名: "M06-10試験カードセット", 英: "M0610 Test Set", コード: "M0610S" };
const NEEDS = ["S-M06-10-ADM", "S-M06-10-REF"];

/** 実行の印つきの略称ABCのタグ名（シードごとに登録する） */
export const 略称ABCのタグ = (シードID: string): string => rc(`ABC-${シードID}`);

function 買取シード(seedId: string, 申込者の姓: string, 呼び名: string, 品: 品[], 読み替え: string[] = []): void {
  defineSeed(seedId, { needs: NEEDS }, async ({ browser, notes }) => {
    const { ids: [id] } = await 作る(browser, { seedId, 申込者の姓, 店: 本店, 管理者: M0610_ADMIN, カードセット: セット, 買取: [{ ラベル: 呼び名, 品 }], 読み替え });
    notes.setExtra(呼び名, id);
    reportSeedIssue(seedId, `買取は査定ID ${id}（正本の ${呼び名.replace(/^〔査定ID-|〕$/g, "")} の読み替え）。棚戻し未処理のまま`);
  });
}

