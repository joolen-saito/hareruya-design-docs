/** 会員1人で、件の数だけ申し込み、それぞれにDBの準備をするシードを定める */
function 組(seedId: string, o: 組の作り方): void {
  defineSeed(seedId, { needs: ADM }, async ({ browser, notes }) => {
    const issue: Issue = (m) => reportSeedIssue(seedId, m);
    const ids = await 商品を用意する(browser, o.商品, issue);
    const 姓 = 注文者名(o.姓);
    const nums = await 申し込む(browser, seedId, { 姓, メール: o.メール, 本人確認: o.本人確認 }, ids, o.件.map((k) => ({ 品: k.品, 保存: k.保存 })));
    const p = 印(o.メール);
    nums.forEach((n, i) => {
      const l = o.ラベル?.[i];
      if (l) notes.set(l, n);
      o.件[i].DB?.(n, p);
    });
    作った買取一覧.set(seedId, { 番号: nums[0], メール: p, 会員ID: "" });
    issue("シード作成時の問題: 買取に使う商品はグッズ商品CSV登録で毎回作った（商品コード・商品名は実行の印つき、買取価格500）");
    issue(印つきの姓(姓, o.姓));
    issue("シード作成時の問題: シード表の「上で作った買取以外の行を削除する」「この N 件以外を削除する」は、共有の環境の買取を消すので行っていない。注文者名が実行の印つきなので、注文者名で絞るケースは作った買取だけになる");
    for (const m of o.読み替え ?? []) issue(`シード作成時の問題: ${m}`);
  });
}

