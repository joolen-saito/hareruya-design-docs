/**
 * A06-08 カード名検索の 008（任意の項目が未設定の商品）のシード（S-A06-08-OPTIONAL-008）。既存の seeds/a06-08.ts は変えず、そこの共通のシード（認証・店舗・マスタ・管理者）を needs で使う。
 * 作り方は seeds/a06-buying.ts と同じ（A06-07 の 006 と同じ作り）。正本の外の補い:
 * - 商品名は「A06-08任意値なし」に実行の印を付けた値（ケースの検索語も同じ印つきの値）。
 * - カードセット・プロモーション・保管コード・買取価格・部門は、画面で空にできない（試験用のカードはカードセット・プロモ種別を付け、買取価格と部門は必須）ので、
 *   E2E の行にだけ DB で空（null）にした（依頼者決定 2026-11-10）。基準価格 2508。部門IDは取込で入れない。
 */
import { defineSeed, reportSeedIssue } from "../lib/seeds";
import { カード商品を作る } from "./a06-buying";
import { カード詳細の関連を外す, 規格の関連を外す, 商品の保管コードを外す } from "../db/a06_rel";
import "./a06-08";

defineSeed("S-A06-08-OPTIONAL-008", { needs: ["S-A06-08-ADM-A"] }, async ({ browser, notes, seed }) => {
  const issue = (m: string) => reportSeedIssue(seed.シードID, m);
  const p = await カード商品を作る(browser, seed.シードID, {
    商品コード: "A0608-008", 商品名日: "A06-08任意値なし", 商品名英: "A06-08 OPTIONAL Product 008", カード名日: "A06-08任意008", カード名英: "A06-08 OPTIONAL 008",
    基準価格: "2508", 販売価格: "2508", 買取価格: "10", 在庫: 8, 画像: "a0608-008.jpg",
  });
  if (!p.カード詳細ID || !p.カードID) throw new Error(`${seed.シードID}: カードID・カード詳細ID が控えられていない`);
  カード詳細の関連を外す(`${seed.シードID}: カードセット・プロモーションを外す`, p.カード詳細ID, ["カードセット", "プロモーション"]);
  規格の関連を外す(`${seed.シードID}: 買取価格・部門を外す`, p.規格ID, ["買取価格", "部門"]);
  商品の保管コードを外す(`${seed.シードID}: 保管コードを外す`, p.商品ID);
  issue("E2E のカード詳細のカードセット・プロモーション、E2E の商品の保管コード、商品規格の買取価格・部門を、DB で空（null）にした（画面で空にできない。依頼者決定 2026-11-10）");
  notes.set("〔商品ID-A0608-008〕", p.商品ID);
  notes.set("〔商品規格ID-A0608-008〕", p.規格ID);
  notes.set("〔カードID-A0608-008〕", p.カードID);
  notes.set("〔カード詳細ID-A0608-008〕", p.カード詳細ID);
});
