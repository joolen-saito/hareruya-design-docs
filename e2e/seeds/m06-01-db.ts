/**
 * M06-01 買取一覧 の、日時・金額を前提にするシード（2026-11-12 に足した。正本: cases/M06-01_seed_data.tsv）。
 *
 * 作り方: 買取はフロントの店頭買取査定申込（会員登録なし。申込者の姓に実行の印）で作り、ステータスは管理画面のステータス変更で変える。
 * 画面で指定できない値（査定申込日時・買取成立日時・買取キャンセル日時・買取金額・棚戻し済み）は、E2E が作った実行の印つきの買取にだけ DB で書く
 * （db/m06_01.ts。lib/db_write.ts の窓口を通す）。
 * 日付だけの値（2026-08-15 など）は、その日の 00:00（日本時間）として書く（買取一覧の日時の欄に日付だけを入れると 00:00 になるため）。
 *
 * ほかの方の買取は消さない（シード表の「ほかの買取情報を DB から削除する」は行わない）:
 * - 020 は「ほかに 2026-08-10〜2026-08-20 の査定申込日時の買取が無い」ことが期待結果（だけが表示される）に関わるので、DB を参照して確かめ、あれば止める。
 * - 024 は期待結果が「表示されること」だけなので、ほかに同じ金額帯の買取があってもそのまま使う（件数を注記に残す）。
 */
import { Browser } from "@playwright/test";
import { rc } from "../lib/run_marker";
import { reportSeedIssue } from "../lib/seeds";
import { defineSeed } from "./current_seed";
import { 一件ずつ申込む, 試験者, ステータスを変える } from "./m06-01";
import {
  ほかの買取の査定申込, 査定申込日時を設定する, 買取成立日時を設定する, 買取キャンセル日時を設定する, 申込者名と買取金額を設定する, 棚戻し済みにする,
  ステータスを設定する, 買取のステータス名, ほかの買取の買取金額の数,
} from "../db/m06_01";

const NEEDS = ["S-M06-01-SHOPS", "S-M06-01-ADM-ALL"];
const 呼び名 = (no: string, 枝 = "") => `〔査定ID-M0601-${no}${枝}〕`;
const 棚戻しの注記 = "棚戻し済みは画面で指定できないので、DB で実行の印つきの買取の棚戻し済みフラグを立てた";

async function 申込む(browser: Browser, 正本の姓: string): Promise<{ 査定ID: string; 姓: string }> {
  const t = 試験者(rc(正本の姓));
  return { 査定ID: await 一件ずつ申込む(browser, "A", t.姓, t.名, t.セイ, t.メイ), 姓: t.姓 };
}

// ---- 020: 査定申込日時の範囲 ----
defineSeed("S-M06-01-DATE-AMOUNT-020", { needs: NEEDS }, async ({ browser, notes, seed }) => {
  const issue = (m: string) => reportSeedIssue(seed.シードID, m);
  const a = await 申込む(browser, "買取試験020A");
  const b = await 申込む(browser, "買取試験020B");
  査定申込日時を設定する(a.査定ID, "2026-08-15 00:00");
  査定申込日時を設定する(b.査定ID, "2026-08-09 00:00");
  棚戻し済みにする(a.査定ID); 棚戻し済みにする(b.査定ID);
  const ほか = ほかの買取の査定申込("2026-08-10 00:00", "2026-08-20 23:59", [a.査定ID, b.査定ID]);
  if (ほか.length > 0) {
    throw new Error(`${seed.シードID}: 査定申込日時が 2026-08-10〜2026-08-20 の買取が、作った2件のほかに ${ほか.length} 件ある`
      + `（${ほか.map((x) => `査定ID ${x.査定ID}・申込者の姓 ${x.姓}`).join("、")}）。ほかの方の買取は消さないので、前提（範囲にほかの買取が無い）を作れない`);
  }
  notes.set(呼び名("020", "A"), a.査定ID);
  notes.set(呼び名("020", "B"), b.査定ID);
  issue(`DB で査定申込日時を、${a.査定ID}（姓 ${a.姓}）は 2026-08-15 00:00、${b.査定ID}（姓 ${b.姓}）は 2026-08-09 00:00 にした。${棚戻しの注記}`);
  issue("ほかの買取の削除は行わず、査定申込日時が 2026-08-10〜2026-08-20 の買取がほかに無いことを DB の参照で確かめた（0件）");
});

// ---- 022: 買取日時（買取成立日・買取キャンセル日）の範囲 ----
defineSeed("S-M06-01-DATE-AMOUNT-022", { needs: NEEDS }, async ({ browser, notes, seed }) => {
  const issue = (m: string) => reportSeedIssue(seed.シードID, m);
  const a = await 申込む(browser, "買取試験022A");
  const b = await 申込む(browser, "買取試験022B");
  await ステータスを変える(browser, [b.査定ID], "買取キャンセル");
  // A は買取成立。画面のステータス変更で「買取成立」を選んで保存し、別のステータスへ進んだときだけ DB で買取成立に戻す
  await ステータスを変える(browser, [a.査定ID], "買取成立");
  const 画面のあと = 買取のステータス名(a.査定ID);
  if (画面のあと !== "買取成立") { ステータスを設定する(a.査定ID, "買取成立"); issue(`${a.査定ID} は画面で「買取成立」に変えたあと「${画面のあと}」になったので、DB で「買取成立」にした`); }
  買取成立日時を設定する(a.査定ID, "2026-08-15 00:00");
  買取キャンセル日時を設定する(b.査定ID, "2026-08-16 00:00");
  for (const x of [a, b]) { 査定申込日時を設定する(x.査定ID, "2026-09-20 00:00"); 棚戻し済みにする(x.査定ID); }
  notes.set(呼び名("022", "A"), a.査定ID);
  notes.set(呼び名("022", "B"), b.査定ID);
  issue(`ステータスは画面のステータス変更で ${a.査定ID} を「買取成立」、${b.査定ID} を「買取キャンセル」にした。DB で買取成立日時を 2026-08-15 00:00、買取キャンセル日時を 2026-08-16 00:00、` +
    `両方の査定申込日時を 2026-09-20 00:00 にした（日付だけの値はその日の 00:00）。${棚戻しの注記}`);
});

// ---- 024: 買取金額の範囲（From・To の入れ替え） ----
defineSeed("S-M06-01-DATE-AMOUNT-024", { needs: NEEDS }, async ({ browser, notes, seed }) => {
  const issue = (m: string) => reportSeedIssue(seed.シードID, m);
  const x = await 申込む(browser, "買取試験024");
  申込者名と買取金額を設定する(x.査定ID, x.姓, "一郎", 1500);
  棚戻し済みにする(x.査定ID);
  notes.set(呼び名("024"), x.査定ID);
  const ほか = ほかの買取の買取金額の数(1000, 2000, x.査定ID);
  issue(`DB で ${x.査定ID}（姓 ${x.姓}）の買取金額を 1500 にした（申込者名は申込の値のまま書き直した）。${棚戻しの注記}`);
  issue(`シード表の「ほかに 1000〜2000 円の買取金額の買取が無い」は、ほかの方の買取を消さないので作っていない（いま ${ほか} 件ある）。期待結果は 1500 円の査定IDが表示されることなので、一覧のページを送って探す`);
});

