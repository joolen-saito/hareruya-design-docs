/**
 * M11-01 メンバー管理一覧の追加分の画面シード（004・007・008・035）。正本: cases/M11-01_seed_data.tsv
 * 作り方・読み替え（所属・権限・店舗・表示順の基準・パスワード）は seeds/m11-01.ts と同じ。
 */
import { defineSeed, reportSeedIssue } from "../lib/seeds";
import { ケース, 基本の5人, ケースのメンバーを作る } from "./m11-01";

type 定め = (typeof ケース)[string];
const 記号 = "ABCDEFGHIJKL".split("");

/** 004: 管理者1人（表示順12）と、ページング確認01〜11（表示順1〜11）の計12人 */
const 十二人 = (n: string): 定め => ({
  番号: n,
  人: [
    { 記号: "A", 名前: `ログイン管理者-${n}`, 表示順: 12, 所属: "東京店", 権限: "システム権限", 稼働: "稼働", ログイン: { 正本のID: `m1101_admin-${n}`, 正本のパスワード: `M11P${n}X9` } },
    ...記号.slice(1).map((k, i) => ({ 記号: k, 名前: `ページング確認${String(i + 1).padStart(2, "0")}-${n}`, 表示順: i + 1, 稼働: "稼働" as const })),
  ],
});
/** 035: 管理者（表示順2）と、ログインIDが重なる既存利用中（表示順1）の2人 */
const 二人 = (n: string): 定め => ({
  番号: n,
  人: [
    { 記号: "A", 名前: `ログイン管理者-${n}`, 表示順: 2, 所属: "東京店", 権限: "システム権限", 稼働: "稼働", ログイン: { 正本のID: `m1101_admin-${n}`, 正本のパスワード: `M11P${n}X9` } },
    { 記号: "B", 名前: `既存利用中-${n}`, 表示順: 1, 権限: "システム権限", 稼働: "稼働", ログイン: { 正本のID: `m1101-${n}-dup`, 正本のパスワード: `M11P${n}Y9` } },
  ],
});

ケース["004"] = 十二人("004");
ケース["007"] = { 番号: "007", 人: 基本の5人("007") };
ケース["008"] = { 番号: "008", 人: 基本の5人("008") };
ケース["035"] = 二人("035");

const シードID: Record<string, string> = { "004": "S-M11-01-MEMBERS-004", "007": "S-M11-01-MEMBERS-007", "008": "S-M11-01-MEMBERS-008", "035": "S-M11-01-DUPID-035" };
for (const n of Object.keys(シードID)) {
  defineSeed(シードID[n], { needs: ["S-M11-01-MASTER"] }, async ({ browser, notes, seed }) => {
    await ケースのメンバーを作る(browser, seed.シードID, ケース[n], notes, (m) => reportSeedIssue(seed.シードID, m));
  });
}
