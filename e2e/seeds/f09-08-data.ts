/**
 * F09-08 デッキ一括購入のシード表（購入対象のカード・商品・在庫）の「状態・属性」の文を、作るものの一覧に読み替える。
 * シード表の文をコードに写さないため、文の決まった形（カード『…』…の商品は、商品（…）の商品規格は規格（…）、…）を読む。
 * 形が読めなければ止める（推測で作らない）。
 */

export type 言語 = "日本語" | "英語" | "その他言語";
export type 状態 = "NM" | "SP" | "MP" | "HP";

export type 規格の計画 = { 呼び名: string; 言語: 言語; 状態: 状態; 価格: number; 在庫: number; 削除済み: boolean };
export type 商品の計画 = {
  呼び名: string; 名: string; セット: string; セットの呼び名: string; 発売日: string;
  Foil: boolean; 公開: "公開中" | "非公開" | "削除済み"; 規格: 規格の計画[];
};
export type カードの計画 = { 呼び名: string; 名: string; 英語名: string; 日本語名: string; 商品: 商品の計画[] };

const 振る = (種類: string) => `（${種類}IDは登録時に画面が振る（控える。以下(〔[^〕]+〕)）`;

const カードの形 = new RegExp(`カード『([^』]+)』${振る("カード")}・英語名『([^』]+)』・日本語名『([^』]+)』）の商品は、(.*?)。このカードの商品は上記だけで、他に無い`, "gu");
const 商品の形 = new RegExp(`^商品${振る("商品")}・商品名『([^』]+)』・カードセット『([^』]+)』${振る("セット")}・発売日(\\d{4}-\\d\\d-\\d\\d)）・(通常|Foil)・(公開中|非公開|削除済み)(?:・[^）]*)?）の商品規格は(.*)$`, "u");
const 規格の形 = new RegExp(`規格${振る("規格")}・(日本語|英語|その他言語)・(NM|SP|MP|HP)・販売価格(\\d+)円・在庫(\\d+)(・削除済み)?(?:・更新日時[^）]*)?）`, "gu");

/** シード表の「状態・属性」の文から、カード・商品・規格の一覧を読む */
export function 在庫の計画(文: string, seedId: string): カードの計画[] {
  const out: カードの計画[] = [];
  for (const c of 文.matchAll(カードの形)) {
    const [, 名, カードの呼び名, 英語名, 日本語名, 商品の文] = c;
    const 商品: 商品の計画[] = [];
    for (const p of 商品の文.split("；")) {
      const m = 商品の形.exec(p);
      if (!m) throw new Error(`${seedId}: 商品の文の形が読めない: ${p}`);
      const [, 呼び名, 商品名, セット, セットの呼び名, 発売日, foil, 公開, 規格の文] = m;
      const 規格: 規格の計画[] = [...規格の文.matchAll(規格の形)].map((k) => ({
        呼び名: k[1], 言語: k[2] as 言語, 状態: k[3] as 状態, 価格: Number(k[4]), 在庫: Number(k[5]), 削除済み: !!k[6],
      }));
      const 規格の数 = (規格の文.match(/規格（/g) ?? []).length;
      if (規格.length === 0 || 規格.length !== 規格の数) throw new Error(`${seedId}: 商品「${商品名}」の規格の文の形が読めない: ${規格の文}`);
      商品.push({ 呼び名, 名: 商品名, セット, セットの呼び名, 発売日, Foil: foil === "Foil", 公開: 公開 as 商品の計画["公開"], 規格 });
    }
    out.push({ 呼び名: カードの呼び名, 名, 英語名, 日本語名, 商品 });
  }
  if (out.length === 0) throw new Error(`${seedId}: シード表の文からカードを読めない`);
  return out;
}
