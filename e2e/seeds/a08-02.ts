/**
 * A08-02 指定言語の設定済みトップバナー一覧の取得のシード。正本: cases/A08-02_seed_data.tsv
 *
 * 全員が見る開発環境のフロントのトップページに影響するため、トップバナーと言語は書き換えない（依頼者の指示 2026-11-21）。
 * シードでの解釈（正本の外の補い。記録 review/A08-02_progress_2026-11-21_dev.md にも書く）:
 * - シード表の「DBシードで…残存言語・紐づけを削除して登録する」は行わない（共有マスタ・他の方が使うバナー）。
 *   代わりに「紐づくバナーが0件の言語がある」「その言語コードの言語が無い」ことを DB で読んで確かめ、満たさなければ止める。
 * - 言語コードの大文字小文字: 新しいアプリでは言語コードがマスタの表記（大文字）で登録されている。シード表の小文字の言語コード
 *   （fr・zz）は、大文字のマスタ（FR・ZZ）を指すものとして読む。
 * - 言語IDの 108020201 は使えない（マスタの既存の言語を使う）。
 */
import { 言語を探す, 紐づくトップバナーの数 } from "../db/a08_02";
import { defineSeed, reportSeedIssue } from "../lib/seeds";

defineSeed("S-A08-02-EMPTY-002", async ({ seed }) => {
  const 言語 = 言語を探す("FR");
  if (!言語) throw new Error(`${seed.シードID}: フランス語（言語コードFR）の言語が登録されていない`);
  const n = 紐づくトップバナーの数("FR");
  if (n !== 0) throw new Error(`${seed.シードID}: フランス語に紐づくトップバナーが ${n} 件ある（0件のはず）。他の方のバナーなので外さずに止める`);
  reportSeedIssue(seed.シードID, `フランス語（言語コードFR・言語ID ${言語.番号}）が登録済みで、紐づくトップバナーが0件であることを DB で読んで確かめた（シード表の言語ID 108020201 の登録・削除は行わない）`);
});

defineSeed("S-A08-02-NOTFOUND-003", async ({ seed }) => {
  if (言語を探す("ZZ")) throw new Error(`${seed.シードID}: 言語コードZZの言語が登録されている（無いはず）。共有マスタなので消さずに止める`);
  reportSeedIssue(seed.シードID, "言語コードZZ（zz）の言語が無いことを DB で読んで確かめた（シード表の「あれば削除」は行わない）");
});
