/** 会員を作って配送先を登録し、番号を控える */
async function 会員と配送先を作る(browser: Browser, notes: Notes, d: 会員の定め): Promise<void> {
  const issue = (m: string) => reportSeedIssue(d.シードID, m);
  const 会員ID = await 本会員を作る(browser, { 姓: "配送", 名: "試験", セイ: "ハイソウ", メイ: "シケン", 前半: d.前半, パスワード: 会員のパスワード });
  notes.set(d.会員の呼び名, 会員ID);
  await withAdminSession(browser, SETUP_ADMIN, async (page) => {
    page.setDefaultTimeout(60_000);
    const edit = new DeliveryEditPage(page);
    for (const a of d.配送先) {
      await edit.openNew(会員ID);
      await edit.fill(a.v);
      await edit.pressRegister();
      for (const w of await expectSaved(page, `${d.シードID}: 配送先「${a.v.配送先名称}」の登録`)) issue(w);
      const 配送先ID = edit.配送先ID();
      notes.set(a.呼び名, 配送先ID);
      if (a.後で === "都道府県を未登録") 配送先を設定する(`${d.シードID}: 配送先ID ${配送先ID} の都道府県を未登録にする`, 配送先ID, { pref_id: null });
      if (a.後で === "名称を未登録") 配送先を設定する(`${d.シードID}: 配送先ID ${配送先ID} の配送先名称を未登録にする`, 配送先ID, { address_name: null });
    }
  });
  if (d.既定 === "消す") 既定の配送先を消す(`${d.シードID}: 会員ID ${会員ID} の既定の配送先の削除`, 会員ID);
  else if (d.既定 !== "残す") {
    const ids = 既定の配送先ID(会員ID);
    if (ids.length !== 1) throw new Error(`${d.シードID}: 会員ID ${会員ID} の既定の配送先が ${ids.length} 件（1件のはず）`);
    配送先を設定する(`${d.シードID}: 既定の配送先の配送先名称`, ids[0], { address_name: d.既定.名前 });
    notes.set(d.既定.呼び名, ids[0]);
  }
}

for (const id of [...new Set(会員.map((d) => d.シードID))]) {
  defineSeed(id, { needs: ["S-M08-09-MASTERS"] }, async ({ browser, notes, seed }) => {
    reportSeedIssue(seed.シードID, "会員のメールアドレスは、シード表の値の @ の前に実行の印を付けた。会員ステータスはフロントの会員登録のまま本会員（会員登録編集画面での選び直しはしない）");
    for (const d of 会員.filter((x) => x.シードID === id)) await 会員と配送先を作る(browser, notes, d);
    if (id === "S-M08-09-EDIT-010" && 配送先があるか("999999")) throw new Error(`${id}: 配送先ID 999999 の配送先がある（ほかの方のデータなので消さずに止める）`);
  });
}
