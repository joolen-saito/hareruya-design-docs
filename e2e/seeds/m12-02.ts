/**
 * M12-02 日別・月別集計 CSV出力 のシードの作り方。正本: cases/M12-02_seed_data.tsv
 *
 * - S-M12-02-ADM: 試験管理者をメンバー管理で登録する。権限は、分析・集計管理を操作できる「システム管理者」、所属店舗は本店。
 * - S-M12-02-ROOT: 通販集計の基準店舗は共有の設定（全員が使う1件）なので、書き換えない（何もしない）。実装したケースは、集計対象(通販)をチェックOFFにして
 *   印つきの店舗だけを集計するので、基準店舗の設定に依存しない。通販を集計対象にするケース（IT-M12-02-007・021・022）は実装していない。
 * - 店舗: 依頼者決定 2026-11-11「店舗は新しく作って実行の印をつけてよい」に従い、店名に実行の印を付けた店舗を店舗登録画面で新しく作る
 *   （売上集計の検索項目は「表示する」）。「大阪店」は M12-01 など他の機能の店舗と集計行が混ざらないよう「大阪店-M1202-<番号>」にした。
 * - 集計データ（日次・月次）: 画面に入れる操作が無く更新コマンド（アプリサーバでの実行）でしか作れないので、印つきの店舗の行だけ DB で足す（db/m12_01.ts）。
 *   店舗は新しく作ったので他の集計行は無く、正本の「登録前に集計結果を削除する」は要らない（削除はしない）。集計データIDの固定値は自動採番。
 */
