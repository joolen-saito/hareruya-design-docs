/** 集計行は消せないので、同じ処理の中で同じ年に二度足さない（やり直しで重ねない） */
const 足した = new Set<string>();

function 作る(o: 作り方): (ctx: { browser: import("@playwright/test").Browser; seed: { シードID: string }; notes: { set(k: string, v: string): void } }) => Promise<void> {
  return async ({ browser, seed, notes }) => {
    const issue = (m: string) => reportSeedIssue(seed.シードID, m);
    const 役割 = [...new Set(o.店.map((d) => d.役割))];
    const 整えた = await withAdminSession(browser, SETUP_ADMIN, async (page) => {
      page.setDefaultTimeout(60_000);
      return 店舗を整える(page, 役割, issue);
    });
    for (const d of o.店) {
      const s = 整えた.get(d.役割)!;
      店舗を控える(d.名前, { id: s.id, 店名: s.店名 });
      notes.set(`〔店舗ID-M1202-${d.呼び名}〕`, s.id);
    }
    let y: number;
    if (足した.has(o.番号)) y = 年を読む(o.番号);
    else {
      y = 空いている集計の年(`M1202-${o.番号}`);
      年を控える(o.番号, y); 足した.add(o.番号);
      if (o.日次) 日次を足す(o.日次(y));
      if (o.月次) 月次を足す(o.月次(y));
    }
    issue(`読み替え: 正本の日付の年（2026）は、E2E の店舗の集計行がほかに無い年（今回は ${y} 年）に読み替えた（集計行は消せず、流すたびに重ならないため）。`
      + "集計データ・店舗IDの固定値は自動採番、店舗は E2E の店舗（東京=店舗ID 5006・大阪=店舗ID 221。店舗は作らない。依頼者 2026-11-15）。画面に集計行を入れる操作が無いので、E2E の店舗の集計行をDBで足した。"
      + "通販集計の基準店舗（共有の設定）は書き換えていない");
  };
}

