const 値 = (総売上: number, 原価: number, 粗利益高: number, 販売点数: number, 取引数: number, 取引単価: number, 買取件数: number, 買取金額: number, 廃棄: number, 欠品: number): 集計の値 =>
  ({ 総売上, 原価, 粗利益高, 販売点数, 取引数, 取引単価, 買取件数, 買取金額, 廃棄, 欠品 });

/** 正本の店名（呼び名）。印はここでは付けない（rc は店舗を作る側が付ける） */
type 店 = { 呼び名: string; 名前: string; 表示順: number; カナ: string; 英語: string };
type 行 = { 店: string; 日または月: string; 値: 集計の値 };
type 作り方 = { 店: 店[]; 日次?: 行[]; 月次?: 行[] };

const 日次1200 = 値(1200, 400, 800, 3, 2, 600, 1, 250, 5, 6);
const 月次3000 = 値(3000, 1000, 2000, 10, 4, 750, 2, 500, 7, 8);

function 作る(o: 作り方): (ctx: { browser: import("@playwright/test").Browser; seed: { シードID: string }; notes: { set(k: string, v: string): void } }) => Promise<void> {
  return async ({ browser, seed, notes }) => {
    const issue = (m: string) => reportSeedIssue(seed.シードID, m);
    await withAdminSession(browser, SETUP_ADMIN, async (page) => {
      page.setDefaultTimeout(60_000);
      for (const d of o.店) {
        const s = await ensureM1202Store(page, d, issue);
        店舗を控える(d.名前, s);
        notes.set(`〔店舗ID-M1202-${d.呼び名}〕`, s.id);
      }
    });
    if (o.日次) 日次を足す(o.日次);
    if (o.月次) 月次を足す(o.月次);
    issue("読み替え: 集計データ・店舗IDの固定値は自動採番、店舗は印つきの新しい店舗。画面に集計行を入れる操作が無いので、印つきの店舗の集計行をDBで足した。"
      + "店舗は新しく作ったので登録前に削除する集計結果は無く、削除はしていない。通販集計の基準店舗（共有の設定）は書き換えていない");
  };
}

