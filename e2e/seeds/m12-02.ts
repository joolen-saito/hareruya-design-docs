/** 正本の店（呼び名・控えのキー・正本の店舗の定め）。実際の店舗は E2E の店舗（東京=5006・大阪=221） */
type 店 = { 呼び名: string; 名前: string; 役割: "TC東京" | "大阪店" };
type 行 = { 店: string; 日または月: string; 値: 集計の値 };
type 作り方 = { 番号: string; 店: 店[]; 日次?: (y: number) => 行[]; 月次?: (y: number) => 行[] };

const 日次1200 = 値(1200, 400, 800, 3, 2, 600, 1, 250, 5, 6);
