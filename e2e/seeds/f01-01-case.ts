// ---- ログイン済みの会員のブラウザで、商品詳細のお気に入りを押して登録する ----
type お気に入り先 = { m: 作った商品; 言語: "JP" | "EN" };
async function お気に入りを入れる(browser: Browser, n: string, 先: お気に入り先[]): Promise<void> {
  const { メール, パスワード } = 会員の資格(n);
  const context = await browser.newContext({ locale: "ja-JP", ignoreHTTPSErrors: true });
  try {
    const page = await context.newPage();
    const fav = new FrontFavorite(page);
    await fav.login(メール, パスワード);
    for (const { m, 言語 } of 先) {
      await fav.openDetail(m.商品ID, 言語);
      if (!(await fav.登録済みの表示か())) await fav.押す();
      await expect.poll(async () => fav.登録済みの表示か(), { message: `${m.名前} のお気に入りが登録済みの表示になる`, timeout: 20_000 }).toBe(true);
    }
  } finally { await context.close(); }
}

type 定め = {
  needs?: string[];
  /** 対象を空にして控える固定タグ（商品が付けるタグを含める） */
  空にする?: 固定タグ名[];
  商品: (試験商品 & { 呼び名?: string })[];
  /** 商品を作ったあと、キャッシュを待つ前にすること（お気に入りの登録など） */
  後?: (a: { browser: Browser; made: Map<string, 作った商品>; issue: (m: string) => void }) => Promise<void>;
};

function 商品のシード(seedId: string, d: 定め): void {
  defineSeed(seedId, { needs: d.needs ?? [] }, async ({ browser, seed, notes }) => {
    const issue = (m: string) => reportSeedIssue(seedId, m);
    const tagIds = d.空にする?.length ? await 共有タグの対象を空にする(browser, seedId, d.空にする, issue) : {};
    const made = await 試験商品を作る(browser, seedId, d.商品, tagIds, issue);
    const byCode = new Map(made.map((m) => [m.コード, m]));
    for (const m of made) 作った.set(m.コード, m);
    呼び名を控える(made, d.商品, new Set(Notes.labelsIn(seed["状態・属性"] + seed.投入方法)), (l, v) => notes.set(l, v));
    if (d.後) await d.後({ browser, made: byCode, issue });
    if (d.空にする?.length) await キャッシュの期限切れを待つ();
  });
}

