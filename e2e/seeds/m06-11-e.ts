const 支店入力 = 使い回す店舗の入力("4973", "M06-11試験支店A");
export const 本店: 店の定義 = { 入力: 本店入力, 閾値: ["1000", "5000", "10000"], get 支店URL() { return 本店入力.支店URL; } };
export const 支店A: 店の定義 = { 入力: 支店入力, 閾値: ["2000", "7000", "12000"], get 支店URL() { return 支店入力.支店URL; } };
const セット = { 名: "M06-11試験カードセット", 英: "M0611 Test Set", コード: "M0611S" };
const NEEDS = ["S-M06-11-ADM", "S-M06-11-REF"];

/** 実在庫の呼び名（〔実在庫ID-M0611-NNNA〕…）を、買取の商品を並べた順の商品名に代えて控える */
function 買取シード(seedId: string, no: string, 店: 店の定義, 品: 品[], 読み替え: string[] = [], 追加の控え?: (a: { 店舗ID: string; カード詳細: Map<string, string> }, set: (l: string, v: string) => void) => void): void {
  defineSeed(seedId, { needs: NEEDS }, async ({ browser, notes, seed }) => {
    const r = await 作る(browser, { seedId, 申込者の姓: `戻し${no}`, 店, 管理者: M0611_ADMIN, カードセット: セット, 買取: [{ ラベル: `〔買取番号-M0611-${no}〕`, 品 }], 読み替え });
    notes.set(`〔買取番号-M0611-${no}〕`, r.ids[0]);
    const 文 = seed["状態・属性"] + seed.投入方法;
    const ラベル = [...new Set(文.match(/〔実在庫ID-M0611-[^〕…]+〕/g) ?? [])].sort();
    ラベル.forEach((l, i) => { if (i < 品.length) notes.set(l, rc(品[i].名)); });
    if (ラベル.length) reportSeedIssue(seedId, `${ラベル.join("・")} は、画面に表示されない実在庫を商品名の行で指す呼び名なので、買取の商品を並べた順に商品名を控えた`);
    追加の控え?.(r, (l, v) => { notes.set(l, v); });
  });
}

