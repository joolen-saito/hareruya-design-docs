type F = { 名: string; 並び順: string; 検索?: boolean; R?: boolean; O?: boolean };
type D = {
  プレイヤー: string; フォーマット: string; 順位: string;
  /** アーキタイプ（省略は「型」） */
  型?: string;
  /** 当日の N 日前（負は N 日後）。省略は 30 */
  日前?: number; 時刻?: string;
  非公開?: boolean; ユーザー?: boolean; リスト非公開?: boolean;
  /** 大会名の後ろ（「大会A」なら "A"）。英語名は「EventA」 */
  大会?: string;
  参加人数?: string; タグ?: string[]; 成績?: string;
};
type 計画 = { ケース: string; フォーマット: F[]; タグ?: string[]; デッキ: D[] };

const 印 = (s: string) => s.replace(/^フォーマット/, "Format").replace(/^タグ/, "Tag");

async function 計画どおりに作る(page: Page, seedId: string, p: 計画): Promise<void> {
  const issue = (m: string) => reportSeedIssue(seedId, m);
  const n = (名: string) => N(p.ケース, 名);

  // シード表の「ほかのフォーマットを一覧の対象から外す」の代わり: 書き換えず、対象のフォーマットが無いことを確かめる（作る前に見る）
  const ほか = await その他デッキの対象のフォーマット(page);
  if (ほか.length) {
    throw new Error(
      `${seedId}: このケースのフォーマットのほかに、ランキング表示もメタ分布簡易化もチェックの無いフォーマットが ${ほか.length} 件ある`
      + `（${ほか.slice(0, 10).join("、")}${ほか.length > 10 ? " ほか" : ""}）。シード表の「ほかのフォーマットを一覧の対象から外す」は、`
      + "既存のフォーマットの設定を書き換えて戻さないため、PM の判断待ちで行わない",
    );
  }
  issue("シード表の「ほかのフォーマットを一覧の対象から外す」は、既存のフォーマットの設定を書き換えて戻さないため行わず（PM の判断待ち）、"
    + "フォーマット一覧の全件を編集画面で開いて、ランキング表示もメタ分布簡易化もチェックの無いフォーマットが無いことを確かめた");

  for (const f of p.フォーマット) {
    await F0905フォーマットを登録する(page, {
      名日: n(f.名), 名英: n(印(f.名)), 並び順: f.並び順, メタ日数: "14",
      検索対象: !!f.検索, ランキング: !!f.R, その他メタ: !!f.O,
    }, issue);
  }
  for (const t of p.タグ ?? []) await 行を用意する(page, "デッキタグ", n(t), n(印(t)), `${seedId} のデッキタグ`);

  // デッキに使う（アーキタイプ, フォーマット）の組ごとにアーキタイプを登録する
  const 組 = [...new Set(p.デッキ.map((d) => `${d.型 ?? "型"}\t${d.フォーマット}`))];
  for (const k of 組) {
    const [型, fm] = k.split("\t");
    await F0905アーキタイプを登録する(page, { 名日: n(型), 名英: n(型.replace(/^型/, "Type")), フォーマット: n(fm) }, issue);
  }
  const 型ごと = new Map<string, number>();
  for (const k of 組) 型ごと.set(k.split("\t")[0], (型ごと.get(k.split("\t")[0]) ?? 0) + 1);
  if ([...型ごと.values()].some((c) => c > 1)) issue(`アーキタイプは、デッキに使うフォーマットごとに同じ名前で登録した（${組.map((k) => k.replace("\t", "@")).join("・")}）。デッキ登録画面のアーキタイプの選択肢がフォーマットで絞られるため`);

  for (const d of p.デッキ) {
    const 日 = 日付(-(d.日前 ?? 30)).replace(/-/g, "/");
    await デッキを登録する(page, {
      デッキ種別: d.ユーザー ? "user" : "event", フォーマット: n(d.フォーマット), アーキタイプ: n(d.型 ?? "型"),
      公開状態: d.非公開 ? "非公開" : "公開", デッキリスト非公開: !!d.リスト非公開,
      タグ: d.タグ?.map(n), プレイヤー名: n(d.プレイヤー),
      イベント名日: n(`大会${d.大会 ?? ""}`), イベント名英: n(`Event${d.大会 ?? ""}`),
      開催日: `${日} ${d.時刻 ?? "12:00"}`, 順位: d.順位, 参加人数: d.参加人数 ?? "32",
      ...(d.成績 !== undefined ? { 成績: n(d.成績) } : {}),
    }, issue);
  }
}

