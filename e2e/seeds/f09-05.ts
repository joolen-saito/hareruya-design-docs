/**
 * F09-05 その他デッキ一覧 のシードの作り方（画面操作）。正本: cases/F09-05_seed_data.tsv
 *
 * - 操作する管理者: 全権限の管理者（SETUP_ADMIN）。フォーマット・アーキタイプ・デッキ・デッキタグは店舗に属さないので足りる。
 *   試験管理者（S-F09-05-ADMIN）は、ケースの手順でフォーマットの設定を変えるためだけに作る。
 * - 決め打ちの識別の値（フォーマット名・アーキタイプ名・プレイヤー名・大会名・タグ名・成績）は、「F0905-001」のような
 *   ケースの前半に実行の印を付けて作る（例: F0905-001-フォーマットA → F0905-001-<印>-フォーマットA）。
 *   同じケースの値どうしの並び（大会A・B・C、選手01〜21）は変わらない。前の実行の残りに当たらないので、
 *   シード表の①（前回の残りを消す）は行わない（消す対象が無い）。
 * - フォーマットコードは、フォーマット名(英)から作る 10 文字の半角英数字（画面の入力規則が 10 文字まで。シード表は値を定めない）。
 * - 並び順: シード表の 930361・930362・930371・930372（036・037）は画面の入力規則（1〜10000）を超えて登録できないので、
 *   9361・9362・9371・9372 に代えた（ケースは並び順そのものを確かめない）。
 * - アーキタイプは1つのフォーマットに属し、デッキ登録画面のアーキタイプの選択肢はフォーマットで絞られる。シード表は
 *   アーキタイプ「…-型」を1つ（フォーマットA）だけ作り、ほかのフォーマットのデッキにも「…-型」を選ぶので、
 *   デッキに使うフォーマットごとに同じ名前のアーキタイプを登録して作る（F09-01 と同じ作り方）。
 * - シード表の「ほかのフォーマットを一覧の対象から外す」（ほかのフォーマットにランキング表示のチェックを付けて登録する）は、
 *   既存の共有のマスタ（すべてのフォーマットの設定）を書き換えて戻さない。PM の方針（2026-11-09）で書かず、判断待ちとする。
 *   代わりに、フォーマット一覧の全件を編集画面で開いて（書き換えない）、このケースのフォーマットのほかに、ランキング表示も
 *   メタ分布簡易化もチェックの無いフォーマットが無いことを確かめ、あればシードを止める（ケースは未判定になる）。
 */
