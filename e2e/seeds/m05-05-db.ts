const 文字 = (i: number): string => String.fromCharCode(65 + i);

type ctx = 後の文脈 & { seedId: string; ids: { 受注ID: string; 注文番号: string }[]; 定義ID: Record<string, string> };

type 設定M = {
  受注: 定義[];
  /** 作る定義（名前は正本の値。印は定義名() が付ける） */
  定義: { キー?: string; 名前: string; 項目: string[]; 全項目?: boolean }[];
  /** 定義を作ったあとの処理。控える値（呼び名のキー → 値）を返す */
  後?: (c: ctx) => Promise<Record<string, string> | void>;
  注記?: string[];
};

/** シード表（状態・属性＋投入方法）に出る「出力項目=…」の項目名の一覧 */
export function シード表の出力項目(seedId: string): string[] {
  const m = /登録表示順1〜75の出力項目=([^／]+)／?/.exec(getSeed(seedId)["状態・属性"]);
  if (!m) throw new Error(`${seedId} のシード表から出力項目を読めない`);
  return m[1].split("・").map((s) => s.trim());
}

function defineM0505Seed(seedId: string, o: 設定M): void {
  defineDbOrderSeed(seedId, {
    // 注文番号の読み替え（正本 → 接頭辞＋末尾）は、受注ごとに defineDbOrderSeed が登録する（末尾は定義の接尾。省略時は通し番号2桁）
    組: {},
    受注: o.受注,
    注記: o.注記,
    後: async (c) => {
      const issue = c.issue;
      const ids = o.受注.map((d) => c.作った.get(d.正本)!);
      const 定義ID: Record<string, string> = {};
      for (const [i, d] of o.定義.entries()) {
        const 名 = 定義名(d.名前);
        let id: string;
        if (d.全項目) {
          const r = await withAdminSession(c.browser, M0505_ADMIN, (page) => createCustomShippingCsvAll(page, 名, d.項目, `${seedId} の定義「${名}」`));
          id = r.定義ID;
          if (r.足りない項目.length) issue(`定義「${d.名前}」に入れられなかった項目（「CSV出力しない項目」に無い）: ${r.足りない項目.join("・")}`);
        } else {
          id = await defineCsv(c.browser, seedId, 名, d.項目);
        }
        定義ID[d.キー ?? (i === 0 ? "" : String(i))] = id;
      }
      const cx: ctx = { ...c, seedId, ids, 定義ID };
      const extra = (await o.後?.(cx)) ?? {};
      // 呼び名（〔…-M0505-…〕）に当たる値: 種別＋末尾の英字（受注が複数のときは受注の順にA・B・…）
      const values: Record<string, string> = {};
      const multi = ids.length > 1;
      ids.forEach((m, i) => {
        const L = multi ? 文字(i) : "";
        values[`注文番号${L}`] = m.注文番号;
        values[`注文ID${L}`] = m.受注ID;
        values[`配送ID${L}`] = 配送IDの一覧(m.受注ID)[0] ?? "";
        try { values[`会員ID${L}`] = 受注の会員ID(m.受注ID); } catch { /* 会員のない受注 */ }
        try { values[`受注明細ID${L}`] = 受注明細IDの一覧(m.受注ID)[0] ?? ""; } catch { /* 明細なし */ }
      });
      for (const [k, v] of Object.entries(定義ID)) values[`定義ID${k}`] = v;
      Object.assign(values, extra);
      noteLabels(seedId, c.notes, values);
    },
  });
}

