// 155〜157: 個別入力商品A（実在庫登録済み）と、あれば B（実在庫未登録）。振込依頼済み・身分証明書登録済み・買取合計10000円未満
function 個別つき(n: string, 登録済みだけ: boolean, 受信済み: boolean): void {
  const 登録 = `M0703-CB${n}-FB`;
  defineBuySeed(`S-M07-03-CBMAIL-${n}`, {
    n, メール: `cbm0703-${n}`, 品: [{ コード: `M0703-${n}-FB`, 数量: "1" }], 保存: 振込依頼(n), 別の商品: [登録],
    読み替え: [
      `個別入力商品は、IND-M0703-CB${n}-A（500×1・売却する・実在庫登録済み。実在庫情報は商品コード ${登録}・数量1・買取単価500・買取小計500）` +
      (登録済みだけ ? "だけにした" : "と IND-M0703-CB" + n + "-B（500×1・売却する・実在庫未登録）にした"),
      "買取合計10000円未満は、選んで買取（査定500×1）と個別入力商品の合計で満たしている",
    ],
    後で: async (browser, issue, a) => {
      個別を足す(a, [{ 名前: `IND-M0703-CB${n}-A`, 金額: 500, 数量: 1, 登録済み: 登録 }]);
      if (!登録済みだけ) 個別入力商品をDBで作る(a.番号, a.メール, [{ 名前: 品(`IND-M0703-CB${n}-B`), 査定金額: 500, 数量: 1, 売却: "する" as const }]);
      if (受信済み) await 振込完了にしてメールを受け取る(browser, a, issue);
      else reportSeedIssue(`S-M07-03-CBMAIL-${n}`, "シード作成時の問題: 振込完了にしたステータス変更履歴は0件のまま（メールは未送信）");
    },
  });
}
