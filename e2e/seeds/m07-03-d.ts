/**
 * M07-03 買取情報編集 の、振込完了メールを確かめるケース（046・047・155〜157）のシード。正本: cases/M07-03_seed_data.tsv
 *
 * 作り方は seeds/m07-03-c.ts と同じ（画面で印つきの会員・商品・買取を作り、画面で作れない個別入力商品・実在庫だけを、依頼者の承認 2026-11-10
 * 「印つきデータは何でも」に沿って、その印つきの買取にだけ DB で整える）。
 *
 * メールの受け口（開発環境の mailcatcher。E2E_MAIL_URL）:
 * - S-M07-03-MAIL の「振込完了メールの配送先を MailCatcher に設定」は画面に無い共有の設定なので書き換えない。開発環境のアプリのメールは
 *   すでに受け口へ届く（会員登録のメールを読む部品がある）ので、その環境の設定を使う。
 * - 「宛先のメールを0件にする」は、受け口のメールを消さず（共有の受け口）、買取依頼者のメールアドレスが実行の印つきで新しいアドレスであることと、
 *   ケースが操作の前に控えたメールの番号より後に届いたメールだけを数えることで代える。
 * - 047・156・157 の「過去に振込完了にして、その振込完了メールを1件受信済み」は、シードが管理画面で買取状況を「振込完了」にして保存し、
 *   メールが届いたことを受け口で確かめてから、買取状況だけを DB で「振込依頼済み」に戻して作る。
 */
import { reportSeedIssue } from "../lib/seeds";
import { mailIds, 届くのを待つ } from "../pages/mail_inbox";
import { defineBuySeed, 保存まで行う, 品, 買取の作り方, 作った買取, 明細の入力 } from "./m07-03-b";
import { 個別入力商品をDBで作る, 実在庫情報をDBで作る, 買取状況をDBで設定する } from "./m07-db-prep";

const 承諾 = { 状況: "査定内容承諾" } as const;
const 身分証 = "自動車運転免許証";
const 査定 = (コード: string, 査定価格: string, 数量: string, 売却?: "する" | "しない"): 明細の入力 => ({ コード, 査定価格, 数量, 売却 });
const 振込依頼 = (n: string): 買取の作り方["保存"] => [{ ...承諾, 査定: [査定(`M0703-${n}-FB`, "500", "1", "する")] }, { 身分証明書: 身分証, 状況: "振込依頼済み" }];

type 個別 = { 名前: string; 金額: number; 数量: number; 登録済み?: string };

/** 個別入力商品（売却する）を DB で足す。登録済みの商品コードがあれば、その実在庫情報（数量・金額×数量）も足す */
function 個別を足す(a: 作った買取, 商品: 個別[]): void {
  個別入力商品をDBで作る(a.番号, a.メール, 商品.map((x) => ({
    名前: 品(x.名前), 査定金額: x.金額, 数量: x.数量, 売却: "する" as const, 登録済みの商品コード: x.登録済み ? 品(x.登録済み) : undefined,
  })));
  for (const x of 商品) if (x.登録済み) 実在庫情報をDBで作る(a.番号, a.メール, { 商品コード: 品(x.登録済み), 数量: x.数量, 小計: x.金額 * x.数量 });
}

/** 管理画面で買取状況を「振込完了」にして保存し、振込完了メールが届いたことを確かめてから、買取状況だけを DB で「振込依頼済み」に戻す */
async function 振込完了にしてメールを受け取る(browser: Parameters<NonNullable<買取の作り方["後で"]>>[0], a: 作った買取, issue: (m: string) => void): Promise<void> {
  const 控え = await mailIds();
  await 保存まで行う(browser, a.番号, { 状況: "振込完了" });
  const m = await 届くのを待つ(a.メール, 控え);
  if (m.件数 !== 1) throw new Error(`${a.メール} 宛の振込完了メールが ${m.件数} 件（1件のはず）`);
  買取状況をDBで設定する(a.番号, a.メール, "振込依頼済み");
  issue(`シード作成時の問題: 管理画面で買取番号 ${a.番号} を「振込完了」にして保存し、${a.メール} 宛の振込完了メール（件名「${m.件名}」）が1件届いたことを確かめた。そのあと買取状況だけを DB で「振込依頼済み」に戻した（振込完了の履歴は1件残る）`);
}

