/**
 * F09-01 デッキ検索TOP のシードの作り方（画面操作）。正本: cases/F09-01_seed_data.tsv
 *
 * - 操作する管理者: 全権限の管理者（SETUP_ADMIN）。シード表は管理者を定めない。フォーマット・アーキタイプ・デッキ・直近の大会・
 *   デッキタグ・カードは店舗に属さないので、編集可能店舗を持たない全権限の管理者で足りる。
 * - 決め打ちの識別の値（フォーマット名・アーキタイプ名・プレイヤー名・大会名・タグ名・カード名）は、「F0901-001」のような
 *   ケースの前半に実行の印を付けて作る（例: F0901-001-F1 → F0901-001-<印>-F1）。前の実行の残りに当たらず、
 *   フォーマットは毎回新しい番号になるので、メタゲーム上位の集計結果のキャッシュ（フォーマットの番号ごと）は作られていない。
 *   このため、シード表の「キャッシュ保存先（Redis）で集計結果のキャッシュを削除する」は行わない（消す対象が無い）。
 * - フォーマット名(英)には、フォーマット名(日)と同じ値を入れる。フォーマットコードは10文字以内の規則に合わせ、その名前から作る（f09_01_setup の フォーマットコード()）。
 *   フォーマットコードは、公開側の検索条件の選択肢・アーキタイプの選択画面のタブを区別するのに使われるので、空にしない。
 * - 状態に指定の無いフォーマットの項目（任意の値）: 表示順 900・ランキング表示 なし・メタ分布簡易化 なし・メタゲーム分析日数 30・
 *   デッキ検索条件に表示 あり。
 * - アーキタイプは1つのフォーマットに属し、デッキ登録画面のアーキタイプの選択肢はフォーマットで絞られる。同じ名前のアーキタイプの
 *   デッキを複数のフォーマットに持つ状態（002・045・080）は、フォーマットごとに同じ名前のアーキタイプを登録して作る。
 * - デッキの「任意の値」: 大会名(日)「<ケースの前半>-大会」・大会名(英)「<ケースの前半>-Event」・時刻 12:00・順位と参加人数は空。
 */
