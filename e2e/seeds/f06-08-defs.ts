export type 追加の規格 = {
  言語: "日本語" | "英語"; 状態: "NM" | "SP"; 価格: string;
  /** 〔商品規格ID-F0608-…〕の末尾 */
  規格: string;
};
export type 商品の定義 = {
  /** 正本の商品コード（商品名も同じ値）。実行の印は作るときに付ける */
  code: string;
  /** 〔商品ID-F0608-…〕の末尾 */
  商品ID: string;
  /** 取り込みで作られた規格の〔商品規格ID-F0608-…〕の末尾 */
  規格: string;
  /** カード商品にする。Foil は カード詳細の選択肢（なし・通常）。カード情報ID・カードID は呼び名の末尾 */
  カード?: { Foil: "なし" | "通常"; カード情報ID: string; カードID?: string };
  /** 商品CSVの言語。省略は日本語 */
  取込言語?: "英語";
  /** 取り込みの基準価格＝販売価格（省略は100） */
  価格?: string;
  /** 取り込みで作られた規格の状態別称（個別メモ） */
  メモ?: string;
  /** 商品画像として追加する画像の名前（カード商品のカード指定のときに追加する） */
  画像?: string;
  追加?: 追加の規格[];
};
export type 通知の定義 = {
  /** 〔通知ID-F0608-…〕の末尾 */
  通知: string;
  /** 商品の並びの番号 */
  商品: number;
  /** 規格の番号（0＝取り込みの規格、1〜＝追加の規格）。まとめて入荷通知のときは書かない */
  規格?: number;
  /** まとめて入荷通知（商品・言語単位）の言語 */
  まとめて?: "JP" | "EN";
};
export type 高額の定義 = { 商品: number; 規格: number; コード: string };
export type シードの定義 = {
  n: string;
  前半: string;
  名: string;
  パスワード: string;
  商品: 商品の定義[];
  通知: 通知の定義[];
  /** 通知を登録したあとで、規格に高額商品コードを入れる（高額商品コードのある規格には通知ボタンが出ない） */
  高額?: 高額の定義[];
};

