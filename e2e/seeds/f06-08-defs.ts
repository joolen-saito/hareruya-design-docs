/** 定義から控えられる呼び名（「種類|末尾」）。会員ID・プレイヤーIDは会員を作るときに控える */
export function 控えられる呼び名(d: シードの定義): Set<string> {
  const s = new Set<string>([`会員ID|${d.n}`, `プレイヤーID|${d.n}`]);
  for (const p of d.商品) {
    s.add(`商品ID|${p.商品ID}`);
    s.add(`商品規格ID|${p.規格}`);
    for (const a of p.追加 ?? []) s.add(`商品規格ID|${a.規格}`);
    if (p.カード) {
      s.add(`カード情報ID|${p.カード.カード情報ID}`);
      if (p.カード.カードID) s.add(`カードID|${p.カード.カードID}`);
    }
  }
  for (const t of d.通知) s.add(`通知ID|${t.通知}`);
  return s;
}
