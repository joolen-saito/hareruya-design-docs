/** 店頭買取を申し込み、買取番号（査定番号）と店頭買取のID（詳細のアドレスの番号）を返す */
async function 店頭買取を申し込んでIDも読む(browser: Browser, メール: string, 申込者: { 姓: string; 名: string }, パスワード: string): Promise<{ 番号: string; ID: string }> {
  const ctx = await browser.newContext({ baseURL: BASE_URL, locale: "ja-JP", ignoreHTTPSErrors: true });
  try {
    await hideDebugToolbar(ctx);
    const page = await ctx.newPage();
    page.setDefaultTimeout(60_000);
    const 番号 = await applyAsMember(page, STORE_A.支店URL, { メール, パスワード }, { 姓: 申込者.姓, 名: 申込者.名, セイ: "シケン", メイ: "カイイン" });
    const d = new NetDetailPage(page);
    await d.一覧を開く();
    if ((await d.一覧の番号リンク(番号).count()) === 0) throw new Error(`店頭買取の申込み完了画面の査定番号 ${番号} が、マイページの買取履歴一覧に出ない（一覧: ${(await d.一覧の番号()).join("、")}）`);
    const to = await d.一覧のリンクの宛先(番号);
    if (to.種類 !== "otc") throw new Error(`買取番号 ${番号} のリンクが店頭買取の詳細でない`);
    return { 番号, ID: to.番号 };
  } finally { await ctx.close(); }
}

