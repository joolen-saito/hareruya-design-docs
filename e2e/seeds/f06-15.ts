type 明細の入力 = { 名前: string; 査定価格?: string; 売却?: "売却する" | "売却しない" };

/** 管理画面の買取情報編集で、査定（査定価格・売却）と買取状況を入れて保存する。保存後の画面の買取状況と査定金額合計を返す */
async function 管理画面で保存する(browser: Browser, 番号: string, v: { 査定?: 明細の入力[]; 状況?: string }): Promise<{ 状況: string; 査定金額合計: string }> {
  return withAdminSession(browser, SETUP_ADMIN, async (page) => {
    page.setDefaultTimeout(60_000);
    const e = await 一覧から編集を開く(page, 番号);
    if (v.査定?.length) {
      await e.査定編集を始める();
      for (const m of v.査定) await e.明細を名前で入れる(品(m.名前), { 査定価格: m.査定価格, 売却: m.売却 });
      await e.査定確定する();
    }
    if (v.状況) await e.買取状況を選ぶ(v.状況);
    await e.保存する(`買取番号 ${番号} の保存（${JSON.stringify(v)}）`);
    const e2 = await 一覧から編集を開く(page, 番号);
    return { 状況: (await e2.基本情報()).買取状況, 査定金額合計: await e2.査定金額合計() };
  });
}

type ネット買取の定め = {
  /** 控える買取番号の呼び名（無ければ固定の買取番号の読み替えだけ） */
  呼び名?: string;
  /** 正本の決め打ちの買取番号（CB のシード） */
  固定?: string;
  /** 管理画面で行う保存（無ければ申込みのまま＝注文） */
  保存?: { 査定?: 明細の入力[]; 状況?: string };
  /** シード表の買取状況（保存のあとで確かめる。振込完了は進んだ状況を許す） */
  状況?: string;
  /** 画面の保存のあとに、画面で作れない部分をDBで整える（印つきの買取にだけ書く）。買取の番号（詳細のアドレスの番号）・表示・印（会員のメール）を渡す */
  後で?: (a: { 番号: string; 表示: string; 印: string }) => unknown;
};

/**
 * ネット買取のシード: 会員 → 商品 → 申込み（買取の数だけ）→ 管理画面の保存。
 * 品々は1回の申込みに入れる商品（買取ごとに同じ商品で申し込む）。
 */
function defineNetSeed(seedId: string, v: { 会員: 会員の定め; 会員IDの呼び名?: string; 品々: 商品の定め[]; /** 申込みには入れず、DBで明細にする商品（グッズ商品CSV登録で作るだけ） */ 別の商品?: 商品の定め[]; 買取: ネット買取の定め[]; 読み替え?: string[] }): void {
  defineSeed(seedId, async ({ browser, notes }) => {
    const issue = (s: string) => reportSeedIssue(seedId, s);
    const 会員ID = await 会員を用意する(browser, seedId, v.会員);
    if (v.会員IDの呼び名) 控える(notes, seedId, v.会員IDの呼び名, 会員ID);
    const ids = await 商品を用意する(browser, seedId, v.品々);
    if (v.別の商品?.length) await 商品を用意する(browser, seedId, v.別の商品);
    for (const b of v.買取) {
      const r = await ネット買取を申し込む(browser, mailOf(v.会員.前半), v.会員.パスワード ?? PW, v.品々.map((p, i) => ({ 商品ID: ids[i], 数量: p.数量 })));
      if (b.呼び名) { 控える(notes, seedId, b.呼び名, r.表示); 詳細の番号.set(b.呼び名, r.番号); }
      if (b.固定) { 固定の買取番号.set(b.固定, r.表示); 詳細の番号.set(b.固定, r.番号); issue(`シード作成時の問題: 決め打ちの買取番号 ${b.固定} は、画面が振った買取番号 ${r.表示} に読み替えた（会員IDも画面が振った ${会員ID}）`); }
      if (b.保存) {
        const after = await 管理画面で保存する(browser, r.番号, b.保存);
        const want = b.状況 ?? b.保存.状況;
        if (want === "振込完了") {
          issue(`シード作成時の問題: 買取状況の振込完了はDBで入れる定め。管理画面で「振込完了」を選んで保存した（保存後の買取状況は「${after.状況}」。ケースの確かめは買取完了の表示の項目で、進んだ状況でも同じ表示になる）`);
        } else if (want && after.状況 !== want) {
          throw new Error(`買取番号 ${r.表示} の買取状況を「${want}」にして保存したが、保存後は「${after.状況}」`);
        }
        if (seedId === "S-F06-15-NETSUM-015") issue(`保存後の管理画面の査定金額合計は ${after.査定金額合計} 円（シード表は25000円）`);
      }
      if (b.後で) await b.後で({ 番号: r.番号, 表示: r.表示, 印: mailOf(v.会員.前半) });
    }
    issue("シード作成時の問題: 買取依頼日（2026-06-10 など）はDBで入れる定め。画面では指定できないので申込みの日時のまま（ケースは日付の値を確かめない）");
    for (const m of v.読み替え ?? []) issue(`シード作成時の問題: ${m}`);
  });
}

