    const d = new NetDetailPage(page);
    await d.一覧を開く();
    if ((await d.一覧の番号リンク(表示).count()) === 0) throw new Error(`申込みの完了画面の買取番号 ${表示} が、マイページの買取履歴一覧に出ない（一覧: ${(await d.一覧の番号()).join("、")}）`);
