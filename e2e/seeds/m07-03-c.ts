/** 正本の商品コード（印なし）で書く */
type M = { c: string; 価格: number; 数量: number; 売却: 売却 };
type I = { 名前: string; 金額: number; 数量: number; 売却: 売却; 登録済み?: string };
type 準備 = {
  状況?: 買取状況名;
  まとめて?: M[];
  個別?: I[];
  /** 個別入力商品とは別に、買取に紐づく実在庫情報（商品コードは正本の値）。履歴の日時を与えると実在庫の履歴も1件作る */
  実在庫?: { c: string; 数量: number; 小計: number; 履歴?: string }[];
  合計?: number;
  カードの査定価格?: { c: string; 価格: number };
  履歴を足す?: { 状況: 買取状況名; 日時: string }[];
  /** 申込みなどで作られた履歴をすべて消して、与えたものだけにする（空なら消すだけ） */
  履歴を置き換える?: { 状況: 買取状況名; 日時: string; 変更者のログインID?: string }[];
};
const m = (c: string, 価格: number, 数量: number, 売却: 売却): M => ({ c, 価格, 数量, 売却 });
const i = (名前: string, 金額: number, 数量: number, 売却: 売却, 登録済み?: string): I => ({ 名前, 金額, 数量, 売却, 登録済み });

/** 準備で使う商品（グッズ商品CSV登録で作る）の、正本の商品コード */
function 商品群(p: 準備): string[] {
  return [...(p.まとめて ?? []).map((x) => x.c), ...(p.個別 ?? []).flatMap((x) => (x.登録済み ? [x.登録済み] : [])), ...(p.実在庫 ?? []).map((x) => x.c)];
}

/** 画面で作った印つきの買取に、画面で作れない部分をDBで整える */
function DBで整える(a: 作った買取, p: 準備): void {
  const 印 = a.メール;
  if (p.まとめて?.length) まとめて買取の明細をDBで作る(a.番号, 印, p.まとめて.map((x) => ({ 商品コード: 品(x.c), 査定価格: x.価格, 数量: x.数量, 売却: x.売却 })));
  if (p.個別?.length) {
    個別入力商品をDBで作る(a.番号, 印, p.個別.map((x) => ({ 名前: 品(x.名前), 査定金額: x.金額, 数量: x.数量, 売却: x.売却, 登録済みの商品コード: x.登録済み ? 品(x.登録済み) : undefined })));
    for (const x of p.個別) if (x.登録済み) 実在庫情報をDBで作る(a.番号, 印, { 商品コード: 品(x.登録済み), 数量: x.数量, 小計: x.金額 * x.数量 });
  }
  for (const s of p.実在庫 ?? []) 実在庫情報をDBで作る(a.番号, 印, { 商品コード: 品(s.c), 数量: s.数量, 小計: s.小計, 履歴: s.履歴 ? { 日時: s.履歴 } : undefined });
  if (p.カードの査定価格) 選んで買取の査定価格をDBで設定する(a.番号, 印, 品(p.カードの査定価格.c), p.カードの査定価格.価格);
  if (p.履歴を置き換える) ステータス変更履歴をDBで置き換える(a.番号, 印, p.履歴を置き換える);
  for (const h of p.履歴を足す ?? []) ステータス変更履歴をDBで足す(a.番号, 印, h);
  if (p.状況) 買取状況をDBで設定する(a.番号, 印, p.状況);
  if (p.合計 !== undefined) 査定金額合計をDBで設定する(a.番号, 印, p.合計);
}

function seed(seedId: string, v: 買取の作り方, p: 準備 = {}, needs: string[] = []): void {
  defineBuySeed(seedId, { ...v, 別の商品: [...(v.別の商品 ?? []), ...商品群(p)], 後で: async (_b, _issue, a) => DBで整える(a, p) }, needs);
}

