/**
 * M07-05 入金CSV出力 の、あとから足したシード（RICH-002）。正本: cases/M07-05_seed_data.tsv
 * 既存の seeds/m07-05.ts は変えず、同じ作り方（会員をフロントで登録 → 本人確認ステータス → フロントで申込）を写し、
 * 画面で作れない値（送料・受理合計価格・明細金額・銀行口座の値）だけを、E2E が作った実行の印つきの買取・銀行口座にDBで書く（db/m07_w.ts）。
 * CSV出力設定・買取状況・本人確認ステータスは共有の設定・マスタ。書き換えず、いまのまま使う。
 */
import { reportSeedIssue } from "../lib/seeds";
import { defineSeed } from "./current_seed";
import { 会員IDをメールで } from "../db/m08_05_07";
import { 会員のプレイヤーID } from "../db/m07_02";
import * as w from "../db/m07_w";
import { 会員を作る, 申込みを行う, 本人確認を設定する } from "./m07-common";
import { 注文者名 } from "./m07-05";

export const 口座002 = { 銀行コード: "0001", 支店コード: "001", 口座種別: "1", 口座番号: 12345, 名義: "ﾊﾚﾙﾔ ﾀﾛｳ" };

defineSeed("S-M07-05-RICH-002", { needs: ["S-M07-05-ADM"] }, async ({ browser, notes, seed }) => {
  const issue = (m: string) => reportSeedIssue(seed.シードID, m);
  const m = await 会員を作る(browser, 注文者名("M0705RICH002"), "002");
  await 本人確認を設定する(browser, m, "オンライン本人確認済み");
  const [id] = await 申込みを行う(browser, m, 1);
  // 受理合計価格＝売却する明細の金額の合計（12000）、明細金額＝すべての明細の金額の合計（15000）にする
  w.先頭の明細を設定する(id, m.メール, { 価格: 12000, 個数: 1, 売却: true });
  w.売却しない明細を足す(id, m.メール, { 価格: 3000, 個数: 1 });
  w.送料を設定する(id, m.メール, 800);
  w.銀行口座を設定する(id, m.メール, 口座002);
  notes.set("〔買取注文ID-M0705-002〕", id);
  const 会員ID = 会員IDをメールで(m.メール);
  if (!会員ID) throw new Error(`会員 ${m.メール} の会員IDをDBの参照で読めない`);
  notes.set("〔会員ID-M0705-002〕", 会員ID);
  notes.set("〔プレイヤーID-M0705-002〕", 会員のプレイヤーID(会員ID));
  notes.set("〔銀行口座ID-M0705-002〕", w.銀行口座の番号(id));
  notes.set("〔買取明細ID-M0705-002〕", w.売却する明細の番号(id));
  issue("シード作成時の問題: 送料800・受理合計価格12000（売却する明細1件の金額）・明細金額15000（売却しない明細3000円を足した合計）・銀行口座（銀行コード0001・支店コード001・口座種別1・口座番号12345・名義 ﾊﾚﾙﾔ ﾀﾛｳ）は申込みの画面では決められないので、DBで、実行の印つきの買取・銀行口座に書いた（シード表は固定IDで登録する定め。固定IDは振れないので、画面が振った番号を控えた）");
  issue("シード作成時の問題: 会員ID・プレイヤーID・銀行口座ID・買取明細IDは、画面に表示されないものを含むので、DBの参照で読んで控えた。申込む商品は既存の買取できる商品（共有のマスタは書き換えない）");
});
