export type 作った規格 = { 商品規格ID: string; 商品コード: string; 言語: string; 状態: 状態 };
export type 作った商品 = { 商品ID: string; 商品名: string; 規格: 作った規格[] };
type 作ったもの = { 商品: Record<string, 作った商品>; 規格: Record<string, 作った規格> };
const 作ったものの表 = new Map<string, 作ったもの>();
function 作ったものの(seedId: string): 作ったもの {
  const v = 作ったものの表.get(seedId);
  if (!v) throw new Error(`${seedId} はまだ作っていない`);
  return v;
}
/** 呼び名（〔…〕の中の文字）の商品 */
export function 商品の(seedId: string, 呼び名: string): 作った商品 {
  const p = 作ったものの(seedId).商品[呼び名];
  if (!p) throw new Error(`${seedId}: 〔${呼び名}〕の商品を作っていない`);
  return p;
}
/** 呼び名（〔…〕の中の文字）の商品規格 */
export function 規格の(seedId: string, 呼び名: string): 作った規格 {
  const c = 作ったものの(seedId).規格[呼び名];
  if (!c) throw new Error(`${seedId}: 〔${呼び名}〕の商品規格を作っていない`);
  return c;
}
/** 009・016 の検索の言葉（印つき） */
export const 連鎖の言葉 = (番号: "009" | "016"): string => rc(`連鎖商品-${番号}`);

function 定めの文(seedId: string): string {
  const s = getSeed(seedId);
  return s["状態・属性"] + s.投入方法;
}
/** 呼び名を、シード表の文にあるときだけ控える（〔…〕付き） */
function 控える(notes: Notes, seedId: string, 呼び名: string | null, 値: string): void {
  if (!呼び名) return;
  const label = `〔${呼び名}〕`;
  const 文 = 定めの文(seedId);
  if (!文.includes(label)) {
    // シード表が「〔商品ID-M0310-009A〕〜〔商品ID-M0310-009K〕」のように範囲でまとめて書いた呼び名（B〜J）は、文にそのままの形では出ない。
    // ケースもその呼び名を書かないので、控えずに進む（2026-11-12 の 009・016 の止まりの直し）
    const m = /^(.*?)([A-Z])$/.exec(呼び名);
    const 範囲 = m ? [...文.matchAll(/〔([^〔〕]*?)([A-Z])〕〜〔([^〔〕]*?)([A-Z])〕/g)].some((r) => r[1] === m[1] && r[3] === m[1] && r[2] <= m[2] && m[2] <= r[4]) : false;
    if (範囲) return;
    throw new Error(`${seedId}: シード表に ${label} が無い`);
  }
  notes.set(label, 値);
}

