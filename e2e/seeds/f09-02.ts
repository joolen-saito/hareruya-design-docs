type D = {
  プレイヤー: string; フォーマット?: string; 大会?: string;
  /** 固定の開催日「yyyy-mm-dd」。日前 が無ければ使う */
  開催日?: string;
  /** 実行日の N 日前 */
  日前?: number;
  順位?: string; 参加人数?: string; 成績?: string; タグ?: string[];
  /** メインボードの欄に書くカード名（枚数1） */
  カード?: string;
  /** 大会名(英)。省略は大会名(日)と同じ */
  大会英?: string;
  /** 開催日の時刻「hh:mm」または「hh:mm:ss」。省略は 00:00。秒がある値は CSV 登録で作る（画面の入力欄は分まで） */
  時刻?: string;
  ユーザー?: boolean; 非公開?: boolean; リスト非公開?: boolean;
  /** 画面で登録したあと、DBでアーキタイプを未設定にする（画面はアーキタイプが必須のため） */
  アーキタイプなし?: boolean;
};
type 計画 = {
  ケース: string;
  /** 記号（"FMT"・"FMT-A" など）。先頭がアーキタイプのフォーマット */
  フォーマット: string[];
  アーキタイプ?: string[];
  タグ?: string[];
  /** カード名(日)の記号。カード名(英)は「<ケースの前半>-Card<連番>」 */
  カード?: string[];
  デッキ: D[];
  /** アーキタイプごとのデッキ（無ければ全デッキが アーキタイプ[0]） */
  アーキタイプの割り当て?: Record<string, string>;
  /** すべてのデッキを、デッキ登録CSVアップロードの1回で登録する（件数の多いケース。デッキリストは非公開で作る） */
  CSVで作る?: boolean;
  /** 画面で作ったあと、DBですべてのデッキの更新日時を「yyyy/mm/dd hh:mm:ss」にする */
  更新日時?: string;
};

const 数字だけ = (ケース: string) => ケース.replace(/\D/g, "").slice(-3);

const 印の末尾 = RUN_MARK.slice(-6).toUpperCase();

function definePlanSeed(seedId: string, p: 計画): void {
  defineSeed(seedId, async ({ browser }) => {
    const issue = (m: string) => reportSeedIssue(seedId, m);
    const n = (名: string) => N(p.ケース, 名);
    await 管理画面(browser, async (page) => {
      const 記号 = "ABCDEFGH";
      for (const [i, f] of p.フォーマット.entries()) {
        await フォーマットを登録する(page, { 名: n(f), コード: `${数字だけ(p.ケース)}${記号[i]}${印の末尾}`, 表示順: "900", 検索対象: true }, issue);
      }
      for (const t of p.タグ ?? []) await 行を用意する(page, "デッキタグ", n(t), n(t), `${seedId} のデッキタグ`);
      for (const [i, c] of (p.カード ?? []).entries()) {
        await カードを登録する(page, { カード名日: n(c), カード名英: n(`Card${i + 1}`), 点数で見たマナ: "0", 詳細: false }, seedId, issue);
      }
      const arcs = p.アーキタイプ ?? ["ARC"];
      const アーキタイプ = (d: D) => p.アーキタイプの割り当て?.[d.プレイヤー] ?? arcs[0];
      // アーキタイプは1つのフォーマットに属し、デッキ登録画面のアーキタイプの選択肢はフォーマットで絞られる。
      // 複数のフォーマットのデッキが同じアーキタイプを持つときは、フォーマットごとに同じ名前のアーキタイプを登録する
      const 組 = [...new Set(p.デッキ.map((d) => `${アーキタイプ(d)}\t${d.フォーマット ?? p.フォーマット[0]}`))];
      for (const k of 組) {
        const [a, f] = k.split("\t");
        await アーキタイプを登録する(page, { 名: n(a), フォーマット: n(f) }, issue);
      }
      if (組.length > arcs.length) issue(`アーキタイプ ${arcs.map(n).join("・")} は、デッキのフォーマットごとに同じ名前で登録した（${組.length} 件）。アーキタイプは1つのフォーマットに属するため`);
      const 日の文字 = (d: D) => (d.日前 !== undefined ? 日付(-d.日前) : (d.開催日 ?? "2025-03-10"));
      const 秒あり = (d: D) => (d.時刻 ?? "").split(":").length === 3;
      const CSV行 = p.デッキ.filter((d) => p.CSVで作る || 秒あり(d));
      for (const d of p.デッキ) {
        if (CSV行.includes(d)) continue;
        await デッキを登録する(page, {
          デッキ種別: d.ユーザー ? "user" : "event", デッキリスト非公開: !!d.リスト非公開,
          フォーマット: n(d.フォーマット ?? p.フォーマット[0]),
          アーキタイプ: n(アーキタイプ(d)),
          タグ: d.タグ?.map(n), 公開状態: d.非公開 ? "非公開" : "公開",
          プレイヤー名: n(d.プレイヤー), イベント名日: n(d.大会 ?? "T"), イベント名英: n(d.大会英 ?? d.大会 ?? "T"),
          開催日: `${表示日付(日の文字(d))} ${d.時刻 ?? "00:00"}`, 順位: d.順位, 参加人数: d.参加人数, 成績: d.成績,
          メイン: d.カード ? `1 ${n(d.カード)}` : undefined,
        }, issue);
      }
      if (CSV行.length) {
        if (CSV行.some((d) => d.リスト非公開 === false || d.タグ || d.成績 || d.ユーザー || d.アーキタイプなし)) throw new Error(`${seedId}: CSV登録では作れない項目（リスト公開・タグ・成績・ユーザーデッキ・アーキタイプなし）がある`);
        const rows: CSVデッキ定義[] = CSV行.map((d) => ({
          プレイヤー名: n(d.プレイヤー), フォーマット: n(d.フォーマット ?? p.フォーマット[0]), アーキタイプ: n(アーキタイプ(d)),
          イベント名英: n(d.大会英 ?? d.大会 ?? "T"), イベント名日: n(d.大会 ?? "T"),
          開催日時: `${日の文字(d)} ${(d.時刻 ?? "00:00").length === 5 ? `${d.時刻 ?? "00:00"}:00` : d.時刻}`,
          表示: !d.非公開, リスト非公開: true, 順位: d.順位, 参加人数: d.参加人数,
        }));
        await デッキをCSVで登録する(page, rows, seedId, issue);
        issue(`デッキ ${rows.length} 件を、デッキ登録CSVアップロード（1回）で登録した。開催日を秒まで指定する・件数が多いため。列の並びはCSV登録画面の見出しに合わせた。デッキリスト非公開フラグは1・メインリストは空（任意の値）`);
      }
      for (const d of p.デッキ.filter((x) => x.アーキタイプなし)) {
        デッキのアーキタイプを未設定にする(n(d.プレイヤー));
        issue(`DBで、プレイヤー名「${n(d.プレイヤー)}」のデッキのアーキタイプを未設定にした（画面の登録・編集はアーキタイプが必須で、未設定にできないため。画面で作ったこのシードの印つきのデッキだけに書いた）`);
      }
      if (p.更新日時) {
        for (const d of p.デッキ) デッキの更新日時を設定する(n(d.プレイヤー), p.更新日時);
        issue(`DBで、デッキの更新日時を ${p.更新日時} にした（画面に更新日時の入力欄が無いため。画面で作ったこのシードの印つきのデッキだけに書いた）`);
      }
      issue(削除しない);
    });
  });
}

