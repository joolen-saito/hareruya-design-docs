const CB = (n: string, 商品: number) => `M1204-CB${n}-0${商品}`;
const 判定名 = (n: string, 商品: number) => `M1204-CB${n}-判定0${商品}`;
/** 12月10日の受注。種別: 宅配（通販）・店頭（TC東京）・大阪（印つきの店舗の店頭受取） */
function 受注12月(y: number, n: string, 種別: "宅配" | "店頭" | "大阪", 商品: number, 数量: number, 単価: number, 店舗ID: string | undefined, 追加: Partial<受注の定め> = {}): 受注の定め {
  return {
    注文日: at(y, "12-10 12:00:00"),
    ...(種別 === "宅配" ? {} : { 店頭受取: true }),
    ...(種別 === "大阪" ? { 店舗ID } : {}),
    明細: [{ コード: CB(n, 商品), 名: 判定名(n, 商品), 単価, 数量 }],
    ...追加,
  };
}
const 店 = (n: string, 順: number): 店舗の指定 => ({ 名前: `大阪店-M1204-CB${n}`, 表示順: 100 + 順, 英語: `Osaka C B ${"ABCDEFGHIJ"[順 % 10]}${"KLMNOPQRST"[Math.floor(順 / 10) % 10]}` });

