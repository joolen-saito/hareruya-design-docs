const at = (y: number, md: string) => `${y}-${md}`;

let basePromise: Promise<{ 受注ID: string }> | null = null;
function 基の受注(browser: Browser, issue: (m: string) => void): Promise<{ 受注ID: string }> {
  if (!basePromise) {
    basePromise = 画面で受注を作る(browser, "M12-04 の集計用データの基の受注", "注文受領", issue);
    basePromise.catch(() => { basePromise = null; });
  }
  return basePromise;
}

type 店舗の指定 = { 名前: string; 表示順: number; 英語: string };
type データ = {
  /** 受注番号の途中に入る3文字（シードごとに違う値） */
  番号: string;
  月: number;
  /** 受注の店舗として新しく作る店舗（ケースの「大阪店-M1204-…」） */
  店舗?: 店舗の指定;
  受注: (y: number, 店舗ID: string | undefined) => 受注の定め[];
  注記?: string[];
};

function defineSalesSeed(seedId: string, d: データ): void {
  defineSeed(seedId, { needs: ["S-M12-04-ADM", "S-M12-04-STORES", "S-M05-01-ADM"] }, async ({ browser }) => {
    const issue = (m: string) => reportSeedIssue(seedId, m);
    // 12月の集計は翌年の1月1日までなので、翌年の1月も空いている年を探す
    const y = 空いている年(d.番号, { 月: d.月, データを置く月: d.月 === 12 ? [[1, 1]] : [] });
    let 店名: string | undefined; let 店舗ID: string | undefined;
    if (d.店舗) {
      const s = await withAdminSession(browser, SETUP_ADMIN, async (page) => {
        page.setDefaultTimeout(60_000);
        return ensureM1201Store(page, { 名前: d.店舗!.名前, 表示順: d.店舗!.表示順, 公開: "公開", 開店: "開店", 売上集計: "表示する", カナ: "オオサカテン", 英語: d.店舗!.英語 }, issue);
      });
      店名 = s.店名; 店舗ID = s.id;
    }
    const base = await 基の受注(browser, issue);
    const 受注 = 受注群を作る(base.受注ID, d.番号, d.受注(y, 店舗ID));
    データを控える(seedId, { 年: y, 受注, 店名 });
    issue(`読み替え: 正本の日付の年（2026）は、ほかの人の受注が無い遠い将来の年（実行ごとに探して決める。今回は ${y} 年）に読み替えた。商品コードは実行の印を付けた値にした`);
    issue("DBで設定した: 受注は、画面（フロントの購入）で作った印つきの受注の行をDBで写し、受注日時・店舗・対応状況・受注明細の単価・数量・商品コード・受注時商品名・移行先受注・スマレジ由来を設定した（画面では指定できないため）。" +
      "店頭受取の受注は配送先の配送方法を店頭受取にした。商品そのもの（商品ID・商品規格ID）は作らず、基の受注の商品を受注明細が参照する");
    for (const n of d.注記 ?? []) issue(n);
  });
}

