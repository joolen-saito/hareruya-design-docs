// 001: 本店・支店・スマレジの受注を選ぶと、1受注につき1部ずつ続けて出て、選んでいない本店の受注（001C）は出ない
caseTest("IT-M05-10-001", async (ctx) => {
  const { page, step, expected } = ctx;
  await loginAdmin(page, M0510_ADMIN);
  const l = new SlipEnOrderListPage(page);
  const v = 作ったものの("S-M05-10-STORES-001");
  const 検索語 = 会員の検索語("001");
  const A = ctx.notes.get("〔注文番号-M0510-001A〕"), B = ctx.notes.get("〔注文番号-M0510-001B〕"), C = ctx.notes.get("〔注文番号-M0510-001C〕"), S = v.注文番号[3];
  let popup!: Page; let pages: 英語の納品書のページ[] = [];
  await step(1, async () => {
    await l.会員の受注を出す(検索語, ["1", 試験支店]);
    supplement(`事前準備の受注日での検索は、ケースの試験会員のメールアドレスに共通する先頭（${検索語}）で、全ての対応状況・店舗ID 1・${試験支店}を選んで検索して読み替えた`);
    note(`検索結果の注文番号: ${(await l.結果の注文番号()).join("・")}`);
  });
  await step(2, async () => { for (const n of [A, B, S]) await l.受注を選ぶ(n); });
  await step(3, async () => {
    popup = await l.英語の納品書印刷を押す();
    pages = await 英語の納品書を読む(popup);
    note(`納品書の注文番号（ページごと）: ${pages.map((p) => `${p.注文番号}(${p.ページ})`).join("・") || "なし"}`);
  });
  await expected(async () => {
    supplement(支店の補い.replace("試験支店を選んだ", "本店と試験支店を選んだ"));
    supplement(`シード表のスマレジの受注（EN-SM-001-001）は、試験会員がフロントで注文した受注のスマレジ取引IDを DB で印つきの値にして読み替えた（スマレジの取引通知で作られる受注は画面で作れない）。注文番号は画面が振った ${S}（注文番号の欄は11文字までで「EN-SM-001-001」は入らない）`);
    expect.soft(popup.url(), "納品書印刷（英語）の窓が開いた").toMatch(/\/order\/print\/delivery_slips\/en/);
    const 出た = pages.map((p) => p.注文番号);
    expect.soft([...出た].sort(), `本店（${A}）・支店（${B}）・スマレジ（${S}）の納品書が1部ずつ出た`).toEqual([A, B, S].sort());
    expect.soft(出た.includes(C), `選んでいない本店の受注（${C}）の納品書は出ない`).toBe(false);
  });
});
