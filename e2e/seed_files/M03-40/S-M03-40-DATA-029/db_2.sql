-- S-M03-40-DATA-029（商品存在確認データ）
-- 流す時点: 投入方法の「どちらの場合も、商品規格登録画面に表示された商品IDと商品規格IDを控える（〔商品ID-M0340-…」を終えたあと、次の「商品一覧で商品IDに999999、商品コードに999999をそれぞれ入れて検索し…」より前。手順書（S-M03-40-DATA-029.md）の「DBへ直接設定する部分（SQL）」と同じ。
BEGIN;

-- [2] 文（投入方法）: 商品コード4099の商品と商品規格を削除済みにすることは、商品一覧の削除では商品そのものが消えてしまい、商品規格が1件だけの商品では商品規格登録画面に「商品規格を削除」ボタンが出ないため画面で指定できず、DBへ直接設定する。
--     備考: アプリの商品規格の削除は論理削除（公開状態を廃止(3)にし、表示しないにする。行は残る）。同じ形にする。スマレジ連携の削除の呼び出しはしない。商品規格の削除済みだけを作る
--     作れない部分（SQLに入れていない）: 商品本体の削除済み: アプリの商品削除は行そのものを消す動作で、「削除済みとして行が残る」状態を表す列が商品の表に無いため作れない（現行のDBに設定先の表・列が無い。設計と実装の差の候補）
DO $$ DECLARE n bigint; BEGIN SELECT (SELECT count(*) FROM dtb_product_class WHERE product_code = '4099') INTO n; IF n IS DISTINCT FROM 1 THEN RAISE EXCEPTION '商品コード4099の規格が1件に決まらない（%件）', n; END IF; END $$;
UPDATE dtb_product_class SET product_status_id = 3, visible = false WHERE product_code = '4099';

COMMIT;
